"""Generate MAP_EFFECTS_INFOS and the fog curve; compare every C value to US BODYPROG."""
import hashlib
from pathlib import Path
import re
import struct
import sys

import gen_map_data as g

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "vendor/silent-hill-decomp"
OUTPUT = ROOT / "source/game/environment_data.h"


def fixed_value(expression):
    match = re.fullmatch(r'Q12\((.+)\)', expression.strip())
    if not match:
        return g.value(expression)
    value = match[1].strip()
    if re.fullmatch(r'-?[\d.]+f?', value):
        number = float(value.removesuffix('f'))
        number = struct.unpack('<f', struct.pack('<f', number))[0]
    else:
        terrain = (DECOMP / 'include/bodyprog/map/terrain.h').read_text(encoding='utf-8')
        macro = re.search(rf'^#define {re.escape(value)}\s+([-\d.]+)f?\s*$', terrain, re.M)
        number = float(macro[1]) if macro else g.value(value)
    return int(number * 4096)


def rows():
    text = (DECOMP / "src/bodyprog/sys/map_info.c").read_text(encoding="utf-8")
    body = text.split("s_MapEffectsInfo MAP_EFFECTS_INFOS[21] = {", 1)[1].split("\n};", 1)[0]
    result = []
    scalar_names = ('spotLightIntensity', 'worldLightIntensity', 'worldTintR', 'worldTintG', 'worldTintB',
                    'field_E', 'fogDistance')
    color_names = ('fogColor', 'pointLightTint', 'worldTint', 'field_21', 'field_25')
    for record in g.records(g.strip_comments(body)):
        flags = [g.value(part) for part in re.search(r'\.field_00\s*=\s*\{([^}]+)', record)[1].split(',')]
        fields = g.fields(record)
        values = [fixed_value(fields[name]) for name in scalar_names]
        colors = [[g.value(part) for part in re.search(rf'\.{name}\s*=\s*\{{([^}}]+)', record)[1].split(',')]
                  for name in color_names]
        result.append((flags, values, g.value(fields['enableTintLightOverlap']), colors))
    if len(result) != 21:
        raise ValueError("Expected 21 retail environment presets")
    return result


def emit():
    presets = rows()
    config = (DECOMP / "configs/USA/bodyprog.yaml").read_text(encoding="utf-8")
    binary = (ROOT / "dump/assets/1ST/BODYPROG.BIN").read_bytes()
    if hashlib.sha1(binary).hexdigest() != re.search(r'^sha1: (\w+)', config, re.M)[1]:
        raise ValueError("BODYPROG.BIN SHA1 differs from decomp US version")
    vram = int(re.search(r'    vram: (0x[\da-fA-F]+)', config)[1], 16)
    symbols = (DECOMP / "configs/USA/sym.bodyprog.txt").read_text(encoding="utf-8")
    address = int(re.search(r'^MAP_EFFECTS_INFOS\s*=\s*(0x[\da-fA-F]+)', symbols, re.M)[1], 16)
    lines = ['/* Generated by tools/gen_environment_data.py - do not edit. */',
             '/* map_info.c MAP_EFFECTS_INFOS; all values checked against SHA1-verified US BODYPROG. */',
             'static const ShEnvPreset s_env_presets[] = {']
    for index, (flags, values, overlap, colors) in enumerate(presets):
        packed = struct.pack('<4B5hBx i4BB4B4B4B4B3x', *flags, *values, *colors[0], overlap,
                             *colors[1], *colors[2], *colors[3], *colors[4])
        actual = binary[address - vram + index * 44: address - vram + (index + 1) * 44]
        # The final padding bytes are not fields.
        if packed[:41] != actual[:41]:
            raise ValueError(f"Environment preset {index} differs between C and US binary")
        def array(data):
            return '{' + ', '.join(map(str, data)) + '}'
        lines.append(f'    {{{array(flags)}, {values[0]}, {values[1]}, {array(values[2:5])}, {values[5]}, '
                     f'{values[6]}, {array(colors[0])}, {overlap}, {array(colors[1])}, '
                     f'{array(colors[2])}, {array(colors[3])}, {array(colors[4])}}}, /* {index} */')
    lines += ['};', 'static const int s_env_fog_curve[] = {']
    curve_source = (DECOMP / 'src/bodyprog/gfx/bodyprog_80055028.c').read_text(encoding='utf-8')
    curve = curve_source.split('s32 D_800AE1C0[] = {', 1)[1].split('};', 1)[0]
    for expression in g.strip_comments(curve).split(','):
        if expression.strip():
            lines.append(f'    {g.value(expression)},')
    lines += ['};']
    shape_source = re.search(r'VECTOR3 D_800AE1B4\[1\]\s*=\s*\{([^}]+)', curve_source)[1]
    shape = [g.value(part) for part in shape_source.split(',')]
    shape = [value - (1 << 32) if value >= (1 << 31) else value for value in shape]
    if shape[0] != 0:
        raise ValueError('The retail light envelope origin is no longer zero')
    lines.append('static const int32_t s_env_light_shape[] = {' + ', '.join(map(str, shape)) + '};')
    effects = (DECOMP / 'src/bodyprog/world/world_effects.c').read_text(encoding='utf-8')
    attributes = effects.split('void Game_FlashlightAttributesFix(void)', 1)[1].split('\n}', 1)[0]
    position = re.search(r'Math_Vector3Set\(&g_SysWork.lightPosition, (.+)\);', attributes)[1]
    offset = [fixed_value(part.strip()) for part in position.split(',')]
    lines.append('static const int32_t s_env_flashlight_offset[] = {' + ', '.join(map(str, offset)) + '};')
    rotation = re.search(r'Math_SVectorSet\(&g_SysWork.lightRotation, (.+)\);', attributes)[1]
    angles = []
    for part in rotation.split(','):
        degrees = float(re.fullmatch(r'Q12_ANGLE\(([-\d.]+)f\)', part.strip())[1])
        turns = struct.unpack('<f', struct.pack('<f', degrees / 360.0))[0]
        angles.append(int(turns * 4096))
    lines.append('static const int32_t s_env_flashlight_angles[] = {' + ', '.join(map(str, angles)) + '};')
    lines.append(f'#define SH_ENV_FLASHLIGHT_BONE {g.value("HarryBone_Torso")}')
    for flag in ('DarkEnvironment', 'FlashlightAllowed', 'EnableBrightness', 'EnableLensflare'):
        lines.append(f'#define SH_ENV_{flag.upper()} {g.value("SpecialEnvEventFlags_" + flag)}')
    lines.append('')
    return '\n'.join(lines)


if __name__ == '__main__':
    expected = emit()
    if '--check' in sys.argv:
        if OUTPUT.read_text(encoding='ascii') != expected:
            raise SystemExit('FAIL: environment header differs from retail count/values')
        print('PASS: 21 environment presets match C and US binary; fog curve matches retail C')
    else:
        OUTPUT.write_text(expected, encoding='ascii', newline='\n')
