#!/usr/bin/env python3
"""Generate cafe text, voice durations and chain endings from NTSC-U retail data."""
import ast
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "vendor/silent-hill-decomp"


def messages():
    common = (DECOMP / "include/maps/shared/map_msg_common.h").read_text(encoding="utf-8")
    common = common.split("#if VERSION_REGION_IS(NTSC)", 1)[1].split("#elif", 1)[0]
    cafe = (DECOMP / "src/maps/map0_s01/map0_s01_events.c").read_text(encoding="utf-8")
    cafe = cafe.split("const char* MAP_MESSAGES[] = {", 1)[1].split("};", 1)[0]
    rows = []
    for index, literal in re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', common + cafe):
        raw = ast.literal_eval(literal)
        duration = re.search(r"~J0\(([^)]+)\)", raw)
        # ~N is a retail line break; tabs and source newlines are text positioning.
        text = re.sub(r"~N", "\x01", raw)
        text = re.sub(r"~[A-Z]\d*(?:\([^)]*\))?", "", text).replace("_", " ")
        text = "\n".join(re.sub(r"\s+", " ", line).strip() for line in text.split("\x01"))
        end = "~E" in raw or "~S" in raw or int(index) <= 14 or not text.strip()
        rows.append((int(index), text, float(duration[1]) if duration else 0.0, end))
    if [row[0] for row in rows] != list(range(76)):
        raise ValueError("Expected contiguous retail messages 0..75")
    return rows


def emit():
    lines = ["/* Generated by tools/gen_cafe_messages.py - do not edit. */",
             "/* map0_s01_events.c MAP_MESSAGES + shared/map_msg_common.h NTSC. */",
             "static const CafeMsg s_msgs[] = {"]
    for index, text, duration, end in messages():
        lines.append(f"    /* {index:2d} */ {{{json.dumps(text, ensure_ascii=True)}, {duration:.1f}f, {str(end).lower()}}},")
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    check = "--check" in sys.argv
    args = [arg for arg in sys.argv[1:] if arg != "--check"]
    output = Path(args[0]) if args else ROOT / "source/game/cafe_messages.h"
    if check:
        header = output.read_text(encoding="ascii")
        pattern = r'/\*\s*(\d+)\s*\*/\s*\{("(?:[^"\\]|\\.)*"), ([\d.]+)f, (true|false)\}'
        actual = [(int(i), json.loads(text), float(duration), end == "true")
                  for i, text, duration, end in re.findall(pattern, header)]
        if actual != messages():
            raise SystemExit("FAIL: generated cafe messages differ from retail count/values")
        print("PASS: 76 messages, text/line breaks/durations/chain endings match retail")
    else:
        output.write_text(emit(), encoding="ascii", newline="\n")
        print(f"76 retail messages -> {output}")
