"""Extract valve/locker animation states and clips from verified MAP1_S03."""
import hashlib
from pathlib import Path
import re
import struct
import sys
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/roof_animation_data.h'


def emit(map_name='map1_s03', state_numbers=(107, 108, 85, 86), symbol='roof'):
    config = (DECOMP / f'configs/USA/maps/{map_name}.yaml').read_text(encoding='utf-8')
    raw = (ROOT / f'dump/assets/VIN/{map_name.upper()}.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / f'configs/USA/maps/sym.{map_name}.txt').read_text(encoding='utf-8')
    address = lambda name: int(re.search(r'^' + name + r'\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    rows = list(struct.iter_unpack('<4h', raw[address('g_MapHeaderTable_38') - base:address('LOADABLE_INVENTORY_ITEMS') - base]))
    shared = (DECOMP / 'include/maps/shared/sharedFunc_800CDAA8_0_s02.h').read_text(encoding='utf-8')
    from gen_school_smoke import function
    import gen_map_data as map_data
    control = function(map_data.strip_comments((DECOMP / 'src/bodyprog/player_control.c').read_text(encoding='utf-8')), 'func_8007FB94')
    assert set(re.findall(r'g_MapOverlayHdr\.field_38\[i\]\.(\w+)', control)) == {'status', 'status_2'}
    playback = function(map_data.strip_comments((DECOMP / 'src/maps/characters/player.c').read_text(encoding='utf-8')), 'Player_AnimPlaybackStateGet')
    assert 'animInfo->startKeyframeIdx' in playback and 'animInfo->endKeyframeIdx' in playback
    info = (DECOMP / f'src/maps/{map_name}/{map_name}_anim_info.c').read_text(encoding='utf-8')
    states = []
    for state in state_numbers:
        body = shared.split(f'case PlayerState_Unk{state}:', 1)[1].split('break;', 1)[0]
        virtual, active = re.search(r'ANIM_STATUS\((\d+), (true|false)\)', body).groups()
        packed, _, first, last = next(row for row in rows if row[1] == int(virtual) * 2 + (active == 'true'))
        states.append((state, packed & 255, first, last))
    pattern = r'\{ (Anim_BlendLinear|Anim_PlaybackOnce), ANIM_STATUS\((\d+), (true|false)\), false, ANIM_STATUS\((\d+), (true|false)\), \{ Q12\(([-\d.]+)f?\)\s*\}, (NO_VALUE|\d+), (\d+)\s*\}'
    lines = [f'/* Generated by tools/gen_{symbol}_animation.py from retail {map_name.upper()}. */',
             f'static const ShPathAnimDef s_{symbol}_animation_defs[] = {{']
    count = 0
    for kind, index, active, link, link_active, rate, first, last in re.findall(pattern, re.sub(r'\s+', ' ', info)):
        status = int(index) * 2 + (active == 'true')
        selected = next((row for row in states if (row[1] & ~1) == (status & ~1)), None)
        if selected is None:
            continue
        first_value = -1 if first == 'NO_VALUE' else int(first)
        signed_rate = (fixed(rate) + (1 << 31)) % (1 << 32) - (1 << 31)
        if kind == 'Anim_PlaybackOnce':
            # func_8007FB94 selects status only. Actual playback endpoints come
            # from AnimInfo (Player_AnimPlaybackStateGet), not field_38.keyframeIdx_6.
            assert selected[2] == first_value and selected[3] >= int(last), (selected, first, last)
        lines.append(f'    {{{status}, {1 if kind == "Anim_BlendLinear" else 2}, false, {{{first_value}, {last}, {int(link) * 2 + (link_active == "true")}}}, {signed_rate}}},')
        count += 1
    assert count == len(state_numbers) * 2
    lines += ['};', f'static const struct {{ int state, status, mapping_time, mapping_keyframe; }} s_{symbol}_animation_states[] = {{']
    lines += [f'    {{{state}, {status}, {first}, {last}}},' for state, status, first, last in states]
    lines += ['};', '']
    animation = 'HB_' + map_name.upper().replace('MAP', 'M').replace('_', '') + '.ANM'
    assert (ROOT / 'romfs/game/anim' / animation).read_bytes() == (ROOT / 'dump/assets/ANIM' / animation).read_bytes()
    return '\n'.join(lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: valve/locker states, eight clips, verified overlay mapping and packaged ANM')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
