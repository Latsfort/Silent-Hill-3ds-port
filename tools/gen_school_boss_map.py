"""Reuse map extraction while preserving retail float32/Q12 truncation and exact coordinates."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/mapdata_map1_s05.h'


def emit():
    previous, previous_enums = g.evaluate, g._enums
    def exact(expression):
        expression = re.sub(r'\bQ12\(\s*([-\d.]+)f?\s*\)', lambda m: str(fixed(m[1])), expression)
        return previous(expression)
    try:
        g.evaluate, g._enums = exact, None
        data = g.emit('map1_s05', precision=12)
        return data.replace('Generated by tools/gen_map_data.py map1_s05', 'Generated by tools/gen_school_boss_map.py (exact retail Q12)')
    finally:
        g.evaluate, g._enums = previous, previous_enums


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: boss points/spawn/events with original float32/Q12 truncation and lossless decimal positions')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
