"""Extract water ribbon geometry after the original particle movement."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/water_ribbon.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/particle_water.c').read_text(encoding='utf-8'))
    body = function(source, 'sharedFunc_800CBDA8_1_s02')
    progress = r'temp_s4\s*= sharedData_800DFB7C_0_s00\[idx\]\.field_10\.s_3\.field_0;'
    matches = list(re.finditer(progress, body))
    assert len(matches) == 2
    horizontal = body[matches[0].end():body.index('\n    else\n    {\n        sharedData_800DFB7C_0_s00[idx].field_C.s_0.field_2 = MIN')]
    vertical = body[matches[1].end():body.index('gte_ldv3c')]
    code = 'if (config->field_30[idx0] == 0) {\n' + horizontal + '\nelse {\n' + vertical
    code = code.replace('setPolyFT4(*poly);', '')
    code = code.replace('sharedData_800E30C8_1_s02.', 'config->').replace('sharedData_800DFB7C_0_s00[idx].', 'particle->')
    code = code.replace('ptr->field_0.field_0.vx', 'camera[0]').replace('ptr->field_0.field_0.vy', 'camera[1]').replace('ptr->field_0.field_0.vz', 'camera[2]')
    code = code.replace('ptr->field_0.u_field_EC.raw_0[idx0]', '((config->field_5C[idx0] >> 1) * sh_fixed_sin(config->field_34[idx0]))')
    code = code.replace('ptr->field_0.u_field_FC.raw_0[idx0]', '((config->field_5C[idx0] >> 1) * sh_fixed_cos(config->field_34[idx0]))')
    code = code.replace('ptr->field_0.field_10C[idx0]', '(config->field_64[idx0] * sh_fixed_sin(config->field_34[idx0]))')
    code = code.replace('ptr->field_0.field_11C[idx0]', '(config->field_64[idx0] * sh_fixed_cos(config->field_34[idx0]))')
    for name, trig in [('EC', 'sin'), ('FC', 'cos')]:
        for component, sign in [('vx', '-'), ('vy', '+')]:
            code = code.replace(f'ptr->field_0.u_field_{name}.field_0[idx0].{component}',
                f'sh_q12_mul(config->field_5C[idx0] >> 1, sh_fixed_{trig}(yaw {sign} 1024))')
    corners = ('12C', '134', '13C', '144')
    def vector(match):
        index = corners.index(match[1])
        args, start, depth = [], 0, 0
        for offset, char in enumerate(match[2]):
            if char == '(': depth += 1
            elif char == ')': depth -= 1
            elif char == ',' and depth == 0:
                args.append(match[2][start:offset])
                start = offset + 1
        args.append(match[2][start:])
        assert len(args) == 3
        return '\n'.join(f'out->position[{index}][{axis}] = {value.strip()};' for axis, value in enumerate(args))
    code = re.sub(r'Math_SetSVectorFastSum\(&ptr->field_(12C|134|13C|144),\s*([^;]+)\);', vector, code)
    fields = body[body.index('s32             field_164;'):body.index('} s_func_800CBDA8;')]
    fields = fields.replace('u8              unk_17E[2];', '')
    code = re.sub(r'ptr->(field_\w+)', r'scratch.\1', code)
    code = code.replace('Q12_MULT_PRECISE', 'sh_q12_mul').replace('Q12_MULT', 'sh_q12_mul')
    code = code.replace('Math_Sin', 'sh_fixed_sin').replace('Math_Cos', 'sh_fixed_cos')
    code = code.replace('Q12_TO_Q6', 'RIBBON_Q12_TO_Q6').replace('Q12_TO_Q8', 'RIBBON_Q12_TO_Q8')
    code = code.replace('Q12_SHIFT', '12').replace('TO_FIXED', 'RIBBON_TO_FIXED').replace('ABS', 'abs').replace('CLAMP_MAX', 'water_min')
    code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
    code = re.sub(r'Q6\(([-\d.]+)f\)', lambda m: str(int(float(m[1]) * 64)), code)
    code = code.replace('Q12(', 'RIBBON_Q12(')
    for old, new in [('s32', 'int32_t'), ('s16', 'int16_t'), ('u8', 'uint8_t'), ('q8_8', 'int16_t')]:
        fields = re.sub(r'\b' + old + r'\b', new, fields)
        code = re.sub(r'\b' + old + r'\b', new, code)
    assert not re.search(r'\b(?:ptr|sharedData_|Math_|Q12_|gte_|poly)\w*', code), code
    result = '\n'.join(['/* Generated by tools/gen_water_ribbon.py from sharedFunc_800CBDA8_1_s02. */',
        'void sh_water_ribbon(const ShWaterParticle *particle, const ShWaterConfig *config,',
        '    const int32_t camera[3], int yaw, ShWaterRibbon *out)', '{',
        '    struct {', fields, '    } scratch = {0};',
        '    int32_t temp_v1_5, var_s1, var_s3, var_v1;',
        '    const int idx0 = particle->field_C.s_1.field_0 >> 2;',
        '    const int32_t temp_s4 = particle->field_10.s_3.field_0;', code,
        '    out->shade = scratch.field_180;',
        '    out->v_start = scratch.field_17C; out->v_length = scratch.field_17D;',
        '    out->variant = particle->field_C.s_1.field_0 & 3;', '}', ''])
    return '\n'.join(line.rstrip() for line in result.split('\n'))


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original horizontal/vertical ribbon geometry and terminal stream shaping')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
