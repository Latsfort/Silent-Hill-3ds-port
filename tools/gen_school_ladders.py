"""Adapt the two retail ladder callbacks without rewriting their step switches."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_ladders.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s00/map1_s00.c').read_text(encoding='utf-8'))
    lines = ['/* Generated by tools/gen_school_ladders.py; retail step switches retained. */']
    for retail, native in [('func_800D85D8', 'ladder_exit_update'), ('func_800D8948', 'ladder_enter_update')]:
        code = function(source, retail)
        code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
        code = re.sub(r'\bEventFlag_\w+\b', lambda m: str(g.value(m[0])), code)
        code = code.replace('(g_Controller0->buttonFlags.clicked & g_GameWorkPtr->config.controllerConfig.skip)', 'sh_input_down(input, KEY_START)')
        code = code.replace('g_SysWork.sysStateSteps[0]', 'town->step').replace('g_DeltaTime', 'SH_Q12(dt)')
        code = code.replace('playerChara', 'town->school.ladder_player').replace('g_MapEventData->mapPointIdx', 'town->school.ladder_point')
        code = code.replace('Q12_MULT_PRECISE', 'sh_q12_mul')
        code = code.replace('Player_ControlFreeze()', '(town->controls_locked = true)')
        code = code.replace('ScreenFade_ResetTimestep()', '(town->fade_speed = 3.0f)')
        code = code.replace('SysWork_StateStepReset()', 'step_set(town, -1)')
        code = code.replace('SysWork_StateStepIncrement(0)', 'step_set(town, town->step + 1)')
        code = code.replace('Event_WaitPlayerStop()', 'step_set(town, town->step + 1)')
        code = re.sub(r'Event_WaitTimer\((\d+), false\)', r'ladder_wait(town, dt, \1)', code)
        code = re.sub(r'Savegame_EventFlag(Get|Set|Clear)\((\d+)\)',
                      lambda m: 'sh_save_event_' + m[1].lower() + '(save, ' + m[2] + ')', code)
        def camera(match):
            args = [a.strip() for a in match[2].split(',')]
            assert args[0] == 'NULL' and args[4:8] == ['0'] * 4 and args[8] == 'true'
            return 'ladder_camera(town, ' + str(match[1] == 'LookAt').lower() + ', ' + ', '.join(args[1:4]) + ');'
        code = re.sub(r'Event_Camera(Position|LookAt)Set\(([^;]+)\);', camera, code)
        code = re.sub(r'Event_ScreenFadeCmd\(ScreenFadeCmd_(Start|Wait|Auto), (true|false), 0, (\d+), false\)',
                      lambda m: f'ladder_fade(town, {dict(Start=0, Wait=1, Auto=2)[m[1]]}, {m[2]}, {m[3]})', code)
        code = re.sub(r'Event_CharaAnimCmdExecute\(CharaAnimCmd_SetState, &town->school.ladder_player, (\d+), false\)',
                      r'ladder_animation(town, \1)', code)
        code = code.replace('Player_ControlUnfreeze(true)', 'ladder_unfreeze(town)')
        code = code.replace('SysWork_StateSetNext(SysState_Gameplay)', 'ladder_finish(town)')
        code = code.replace('vcReturnPreAutoCamWork(true)', '(void)0')
        code = re.sub(r'(step_set\(town, town->step \+ 1\);)(\s+case \d+:)', r'\1\n        /* fall through */\2', code)
        assert not re.search(r'\b(?:Event_|Player_|SysWork_|ScreenFade_|g_)\w*', code), code
        lines += [f'/* {retail} */', f'static void {native}(ShTown *town, ShSavegame *save, const ShInputState *input, float dt)', '{', code, '}']
    return '\n'.join(line.rstrip() for line in lines + [''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: both ladder callbacks generated directly from retail switches and expressions')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
