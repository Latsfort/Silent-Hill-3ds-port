"""Adapt MAP1_S03's original animated locker objects without bypassing flags."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    source = g.strip_comments((DECOMP / 'src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    body = function(source, 'func_800DE828')
    init = function(source, 'Map_WorldObjectsInit')
    data = ['/* Generated by tools/gen_locker_world.py from func_800DE828. */',
            'static const ShPathPoint s_locker_positions[] = {']
    for obj in range(5):
        args = re.search(r'WorldObject_(?:Init|PlacementInit)\(&g_WorldObject' + str(obj) + r', "[^"]+", ([^;]+)\);', init)[1]
        position = [fixed(value.strip()) for value in args.split(',')[:3]]
        data.append('    {' + ', '.join(map(str, position)) + '},')
    data += ['};']
    sound_position = re.search(r'const static VECTOR3 sfxPos = VECTOR3\(([^)]+)\);', body)[1]
    data += ['static const ShPathPoint s_locker_sound_position = {' + ', '.join(str(fixed(v.strip())) for v in sound_position.split(',')) + '};']
    code = body[body.index('if (g_DeltaTime'):]
    calls = len(re.findall(r'Sfx_WithFlagsPlay\(', code)) + len(re.findall(r'func_800892(?:A4|DC)\(', code))
    code = re.sub(r'WorldObjects_Add\(&g_WorldObject(\d)\.object, [^;]+\);', lambda m: f'frame->draw_mask |= 1u << {m[1]};', code)
    def sound(match):
        sound, position, clamped, volume, flags = match.groups()
        value = fixed(volume) // 16
        if clamped: value = min(255, max(0, value))
        if position == 'sfxPos': position = 's_locker_sound_position'
        else:
            index = re.fullmatch(r'g_WorldObject(\d)\.position', position)[1]
            position = f's_locker_positions[{index}]'
        return f'locker_sound(frame, {g.value(sound)}, {position}, {value}, {g.value(flags)});'
    code = re.sub(r'Sfx_WithFlagsPlay\((\w+), &([\w.]+), Q8(_CLAMPED)?\(([-\d.]+)f\), (\w+)\);', sound, code)
    utility = g.strip_comments((DECOMP / 'src/bodyprog/bodyprog_80089090.c').read_text(encoding='utf-8'))
    default_effect = int(re.search(r'func_800895E4\([^;]+, (0x[\dA-Fa-f]+)\)', function(utility, 'func_800892A4'))[1], 16)
    code = re.sub(r'func_800892A4\((\d+)\)', lambda m: f'locker_effect(frame, {m[1]}, {default_effect})', code)
    code = re.sub(r'func_800892DC\((\d+), (0x[\dA-Fa-f]+)\)', r'locker_effect(frame, \1, \2)', code)
    for index in range(3): code = code.replace(f'g_WorldObject{index}.rotation.vy', f'world->rotation[{index}]')
    code = code.replace('D_800E20E8', 'world->speed').replace('D_800E20EC', 'world->timer').replace('D_800E20EE', 'world->phase')
    code = code.replace('g_DeltaTime', 'dt').replace('ScreenFade_IsFinished()', 'fade_finished')
    code = re.sub(r'Savegame_EventFlagGet\((\w+)\)', lambda m: f'sh_save_event_get(save, {g.value(m[1])})', code)
    code = re.sub(r'Savegame_EventFlagSet\((\w+)\)', lambda m: f'sh_save_event_set(save, {g.value(m[1])})', code)
    code = code.replace('Rng_GenerateUInt', 'locker_random').replace('Q12_MULT_PRECISE', 'sh_q12_mul')
    code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
    code = code.replace('ABS', 'abs').replace('MIN', 'locker_min').replace('MAX', 'locker_max').replace('FP_FROM', 'LOCKER_FROM').replace('Q12_SHIFT', '12')
    code = re.sub(r'(world->phase = 1;)(\s+case 1:)', r'\1\n                    /* fall through */\2', code)
    assert not re.search(r'\b(?:g_|D_|WorldObjects_|Sfx_|Savegame_|Rng_|Q12_|func_)\w*', code), code
    data += ['void sh_locker_world_step(ShLockerWorld *world, ShSavegame *save, int32_t dt,',
        '    bool fade_finished, ShLockerFrame *frame)', '{', '    int32_t tmp0, tmp1;',
        '    memset(frame, 0, sizeof(*frame));', code, '}', '']
    limits = f'/* Generated from original locker command call sites. */\n#pragma once\n#define SH_LOCKER_COMMAND_CAPACITY {calls}\n#define SH_LOCKER_SFX_NO_DIST_ATTEN {g.value("SfxFlag_NoDistAtten")}\n'
    return {'source/game/locker_world_steps.h': '\n'.join(line.rstrip() for line in '\n'.join(data).split('\n')),
        'include/sh3ds/locker_world_data.h': limits}


if __name__ == '__main__':
    for name, data in outputs().items():
        path = ROOT / name
        if '--check' in sys.argv: assert path.read_text(encoding='ascii') == data
        else: path.write_text(data, encoding='ascii', newline='\n')
    if '--check' in sys.argv: print('PASS: original locker rotations, RNG, phases, flags and ordered sound/effect requests')
