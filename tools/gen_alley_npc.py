"""Extract original Grey Child staging poses and frozen animation keyframe."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/alley_npc_data.h'


def emit():
    source = g.strip_comments((DECOMP / 'src/maps/map0_s00/map0_s00_2.c').read_text(encoding='utf-8'))
    spawns = re.findall(r'Chara_Spawn\(ENEMY_CHARA_ID, (\d+), Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\), Q12_ANGLE\(([-\d.]+)f\),\s*(\d+)\)',
                        function(source, 'MapEvent_GreyChildrenSpawn'))
    cutscene = re.findall(r'Chara_Spawn\(ENEMY_CHARA_ID, (\d+), Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\), Q12_ANGLE\(([-\d.]+)f\),\s*(\d+)\)',
                          function(source, 'MapEven_CutsceneAlleyGetsDarker'))
    assert spawns == cutscene and len(spawns) == 3
    stalker = g.strip_comments((DECOMP / 'src/maps/characters/stalker.c').read_text(encoding='utf-8'))
    init = function(stalker, 'Stalker_Init')
    keyframe = int(re.search(r'stalker->model.anim.keyframeIdx\s*=\s*(\d+)', init)[1])
    assert re.search(r'case 5:\s*stalker->model.controlState = StalkerControl_1;', init)
    update = function(stalker, 'Stalker_Update')
    assert 'if (stalker->model.controlState != StalkerControl_1)' in update
    lines = ['/* Generated by tools/gen_alley_npc.py; retail MAP0_S00 and Stalker_Init. */',
             f'#define ALLEY_GREY_FROZEN_KEYFRAME {keyframe}',
             'static const struct { int32_t x, z, yaw; } s_alley_grey_spawns[] = {']
    for index, (slot, x, z, yaw, state) in enumerate(spawns):
        assert int(slot) == index and state == '5'
        lines.append(f'    {{{fixed(x)}, {fixed(z)}, {fixed(yaw, True)}}},')
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original Grey Child staging positions, headings and frozen keyframe')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
