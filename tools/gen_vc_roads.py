#!/usr/bin/env python3
"""Convert a decomp map's vc_road_data.h into a flat C table for the 3DS port.

Usage: gen_vc_roads.py <vc_road_data.h> <out.h> <symbol>

Values stay in PS1 metres / degrees (Y down); the runtime converts to 3DS space.
"""
import re
import sys

FLAG_BITS = {
    "VC_RD_NOFLAG": 0,
    "VC_RD_END_DATA_F": 1 << 0,
    "VC_RD_WARP_IN_F": 1 << 1,
    "VC_RD_WARP_OUT_F": 1 << 2,
    "VC_RD_WARP_IN_OUT_FS": (1 << 1) | (1 << 2),
    "VC_RD_NO_FRONT_FLIP_F": 1 << 3,
    "VC_RD_LIM_UP_FAR_VIEW_F": 1 << 4,
    "VC_RD_USE_NO_ENEMY_F": 1 << 5,
    "VC_RD_USE_NEAR_ENEMY_F": 1 << 6,
    "VC_RD_MARGE_ROAD_F": 1 << 7,
}
ENUMS = {
    "VC_AREA_TINY": 0, "VC_AREA_SMALL": 1, "VC_AREA_WIDE": 2, "VC_AREA_OUTDOOR": 3,
    "VC_RD_TYPE_ROAD": 0, "VC_RD_TYPE_EFFECT": 1, "VC_RD_TYPE_EVENT": 2,
    "VC_RD_TYPE_ROAD_PRIO_LOW": 3, "VC_RD_TYPE_ROAD_PRIO_HIGH": 4, "VC_RD_TYPE_SV_ONLY": 5,
    "VC_MV_CHASE": 0, "VC_MV_SETTLE": 1, "VC_MV_FIX_ANG": 2, "VC_MV_SELF_VIEW": 3, "VC_MV_THROUGH_DOOR": 4,
    "LensFlareType_Default": 0,
}


def num(expr):
    expr = expr.strip()
    m = re.fullmatch(r"Q\d+(?:_ANGLE)?\((-?[\d.]+)f?\)", expr)
    if m:
        return float(m.group(1))
    if expr in ENUMS:
        return ENUMS[expr]
    if "VC_RD_" in expr:
        bits = 0
        for part in expr.split("|"):
            bits |= FLAG_BITS[part.strip()]
        return bits
    return float(expr)


def parse(text):
    roads = []
    for block in re.findall(r"\{\s*\.lim_sw(.*?)\.fix_ang_y\s*=\s*([^,\n]+),?\s*\}", text, re.S):
        body, fix_y = block
        def box(name):
            m = re.search(r"\." + name + r"\s*=\s*\{(.*?)\}", ".lim_sw" + body, re.S)
            vals = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n]+)", m.group(1)))
            return [num(vals[k]) for k in ("min_hx", "max_hx", "min_hz", "max_hz")]
        fields = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n{]+)", body))
        roads.append({
            "sw": box("lim_sw"),
            "rd": box("lim_rd"),
            "flags": int(num(fields["flags"])),
            "area": int(num(fields["area_size_type"])),
            "rd_type": int(num(fields["rd_type"])),
            "mv_y": int(num(fields["mv_y_type"])),
            "max_hy": num(fields["lim_rd_max_hy"]),
            "min_hy": num(fields["lim_rd_min_hy"]),
            "ofs_watch_hy": num(fields["ofs_watch_hy"]),
            "cam_mv": int(num(fields["cam_mv_type"])),
            "fix_x": num(fields["fix_ang_x"]),
            "fix_y": num(fix_y),
        })
    return roads


def main():
    src, out, sym = sys.argv[1:4]
    roads = [r for r in parse(open(src, encoding="utf-8").read()) if not (r["flags"] & 1)]
    f = lambda v: "%.3ff" % v
    with open(out, "w", encoding="utf-8", newline="\n") as fp:
        fp.write("/* Generated by tools/gen_vc_roads.py from %s - do not edit. */\n" % src.replace("\\", "/"))
        fp.write("static const ShVcRoad %s[] = {\n" % sym)
        for r in roads:
            fp.write("    {{%s}, {%s}, 0x%02X, %d, %d, %d, %s, %s, %s, %d, %s, %s},\n" % (
                ", ".join(map(f, r["sw"])), ", ".join(map(f, r["rd"])), r["flags"], r["area"], r["rd_type"],
                r["mv_y"], f(r["max_hy"]), f(r["min_hy"]), f(r["ofs_watch_hy"]), r["cam_mv"], f(r["fix_x"]),
                f(r["fix_y"])))
        fp.write("};\n")
    print("%d roads -> %s" % (len(roads), out))


if __name__ == "__main__":
    main()
