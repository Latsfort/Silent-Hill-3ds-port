"""Extract each school's common-pickup callback index from its retail header."""
from pathlib import Path
import sys
import gen_map_data as g

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_routing.h'


def emit():
    lines = ['/* Generated by tools/gen_school_routing.py from retail event function tables. */',
        'int sh_school_common_pickup_callback(uint8_t map)', '{', '    switch (map) {']
    for index in range(4):
        name = f'map1_s0{index}'
        functions = g.event_funcs(name)
        assert functions.count('MapEvent_CommonItemTake') == 1
        lines.append(f'    case SH_MAP_IDX_{name.upper()}: return {functions.index("MapEvent_CommonItemTake")};')
    return '\n'.join(lines + ['    default: return -1;', '    }', '}', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: common-pickup dispatch indices for all four retail school overlays')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
