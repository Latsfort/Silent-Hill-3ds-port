"""Generate the two Event_ItemTake key wrappers from map2_s00 retail data."""
import ast
import json
from pathlib import Path
import re
import sys

import gen_map_data as g

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor/silent-hill-decomp/src/maps/map2_s00/map2_s00.c"
OUTPUT = ROOT / "source/game/town_keys.h"


def emit():
    source = SOURCE.read_text(encoding="utf-8")
    messages = dict(re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', source))
    item_source = (ROOT / "vendor/silent-hill-decomp/src/bodyprog/items/item_unk_data.c").read_text(encoding="utf-8")
    rotation_source = item_source.split("const DVECTOR INV_ITEM_ROTATIONS[] = {", 1)[1].split("};", 1)[0]
    rotations = re.findall(r'\{\s*Q12_ANGLE\(([-\d.]+)f\),\s*Q12_ANGLE\(([-\d.]+)f\)\s*\}', rotation_source)
    name_source = item_source.split("const char* INV_ITEM_NAMES[] = {", 1)[1].split("#else", 1)[1].split("#endif", 1)[0]
    names = re.findall(r'"(?:[^"\\]|\\.)*"|\bNULL\b', g.strip_comments(name_source))
    events = g.load_events("map2_s00")
    lines = ["/* Generated by tools/gen_town_keys.py - do not edit. */",
             "/* map2_s00.c Event_ItemTake wrappers; item_unk_data.c INV_ITEM_ROTATIONS. */",
             "#ifdef SH_TOWN_KEY_ASSETS"]
    rows = []
    name_cases = []
    for name in ("func_800E9A0C", "func_800E9CB4"):
        body = source.split(f"void {name}(void)", 1)[1].split("\n}\n", 1)[0]
        item, count, flag, msg = re.search(r'Event_ItemTake\((\w+), (\w+), (\w+), (\d+)\)', body).groups()
        if count != "DEFAULT_PICKUP_ITEM_COUNT":
            raise ValueError(count)
        marker_required, marker_set = re.findall(r'Savegame_EventFlag(?:Get|Set)\((EventFlag_\w+)\)', body)[1:]
        callbacks = {e["event_param"] for e in events if e["func"] == name}
        if len(callbacks) != 1:
            raise ValueError(name)
        item_id = g.value(item)
        rx, rz = rotations[item_id - 32]
        asset = f"UNQ{item_id:02X}.TMD"
        if not (ROOT / "dump/assets/ITEM" / asset).is_file():
            raise ValueError(f"Missing retail asset {asset}")
        lines.append(f'    {{{item_id}, "romfs:/game/item/{asset}", {float(rx):.1f}f, {float(rz):.1f}f}},')
        item_name = ast.literal_eval(names[item_id - 32]).replace('_', ' ')
        name_cases.append(f'    case {item_id}: return {json.dumps(item_name)};')
        raw = ast.literal_eval(messages[msg])
        text = re.sub(r'~[A-Z]\d*(?:\([^)]*\))?', '', raw).replace('_', ' ')
        text = ' '.join(text.split())
        rows.append(f'    {{{callbacks.pop()}, {item_id}, {g.value(flag)}, {g.value(marker_required)}, {g.value(marker_set)}, {json.dumps(text)}}}, /* {name} */')
    lines += ["#elif defined(SH_TOWN_KEY_NAMES)", *name_cases,
              "#else", "static const ShTownKey s_town_keys[] = {", *rows, "};", "#endif", ""]
    return '\n'.join(lines)


if __name__ == "__main__":
    expected = emit()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="ascii") != expected:
            raise SystemExit("FAIL: town key count/values differ from retail")
        print("PASS: two key wrappers, callbacks, flags, messages and model rotations match retail")
    else:
        OUTPUT.write_text(expected, encoding="ascii", newline="\n")
