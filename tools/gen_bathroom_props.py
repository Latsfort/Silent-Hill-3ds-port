"""Extract the bathroom's original door/shotgun placements and visibility."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_bathroom_props.h'
BOSS_OBJECTS = ('Ring1Hi', 'Ring2Hi', 'Door2Hi', 'Door1Hi', 'BoxHide')
PHONE_OBJECTS = ('Phone3H', 'Phone2H')


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s02/map1_s02.c').read_text(encoding='utf-8'))
    init = function(source, 'Map_WorldObjectsInit')
    lines = ['/* Generated by tools/gen_bathroom_props.py from MAP1_S02. */',
        'static const ShSchoolProp s_school_bathroom_props[] = {']
    for index, name in enumerate(('DoorHid', 'GunHide') + BOSS_OBJECTS + PHONE_OBJECTS):
        kind, model, args = re.search(r'WorldObject_(Init|PlacementInit)\(&g_WorldObject_' + name + r', "([^"]+)", ([^;]+)\);', init).groups()
        values = [v.strip() for v in args.split(',')]
        position = [fixed(v) / 4096 for v in values[:3]]
        rotation = [fixed(v, True) / 4096 * 360 for v in values[3:]] if kind == 'Init' else [0, 0, 0]
        assert len(position) == len(rotation) == 3
        fmt = lambda values: ', '.join(f'{v:.12f}f' for v in values)
        lines.append(f'    {{"{model}", {{{fmt(position)}}}, {{{fmt(rotation)}}}, 1u << {index}}},')
    lines += ['};']
    body = function(source, 'Map_WorldObjectsUpdate')
    begin = body.index('if (PLAYER_IN_MAP_CHUNK(vx, 0, 0, -1, 1) && PLAYER_IN_MAP_CHUNK(vz, 1, 2, -1, 2))')
    end = body.index('if (PLAYER_IN_MAP_CHUNK(vx, 1, 2, -1, 2)', begin)
    code = body[begin:end]
    opened = re.search(r'if \(Savegame_EventFlagGet\((\w+)\)\)\s*\{\s*g_WorldObject_DoorHid.rotation.vy = Q12_ANGLE\(([-\d.]+)f\);\s*\}\s*else\s*\{\s*collFlags = CollisionTriggerFlag_Objects;\s*\}', code)
    assert opened
    flag, angle = opened.groups()
    lines += [f'#define SH_BATHROOM_OPEN_FLAG {g.value(flag)}', f'#define SH_BATHROOM_OPEN_ROTATION {fixed(angle, True)}']
    lines += [f'#define SH_BATHROOM_COLLISION_MAP {g.value("CollisionTriggerFlag_Map")}',
        f'#define SH_BATHROOM_COLLISION_OBJECTS {g.value("CollisionTriggerFlag_Objects")}']
    code = code[:opened.start()] + code[opened.end():]
    code = re.sub(r'WorldObjects_Add\(&g_WorldObject_(GunHide|DoorHid).object, [^;]+\);',
        lambda m: f'mask |= s_school_bathroom_props[{0 if m[1] == "DoorHid" else 1}].mask;', code)
    code = re.sub(r'Savegame_EventFlagGet\((\w+)\)', lambda m: f'sh_save_event_get(save, {g.value(m[1])})', code)
    code = code.replace('PLAYER_IN_MAP_CHUNK(vx,', 'in_chunk(SH_Q12(x),').replace('PLAYER_IN_MAP_CHUNK(vz,', 'in_chunk(SH_Q12(-z),')
    assert not re.search(r'\b(?:g_|WorldObjects_|Savegame_|PLAYER_|collFlags)\w*', code), code
    lines += ['#ifdef SH_SCHOOL_BATHROOM_PROP_MASK',
        'static uint32_t bathroom_prop_mask(const ShSavegame *save, float x, float z)', '{',
        '    uint32_t mask = 0;', code.rstrip(), '    return mask;', '}', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original bathroom door/shotgun placements, rotations, chunk gate and pickup visibility')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
