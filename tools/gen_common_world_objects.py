#!/usr/bin/env python3
"""Generate map common pickup props from Map_WorldObjectsUpdate + overlay poses.

  gen_common_world_objects.py map2_s00 [OUT]
    e.g. gen_common_world_objects.py map2_s00 source/game/map_world_objects_map2_s00.h

Poses: dump/assets/VIN/MAP2_S00.BIN @ PA from configs/USA/maps/sym.map2_s00.txt
Models: g_CommonWorldObjects[N] -> g_CommonWorldObjectNames[N+2] (bodyprog_data_800A99B4.c)
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECOMP = os.path.join(ROOT, "vendor", "silent-hill-decomp")
DUMP_BIN = os.path.join(ROOT, "dump", "assets", "VIN", "MAP2_S00.BIN")
SYM = os.path.join(DECOMP, "configs", "USA", "maps", "sym.map2_s00.txt")

MODEL_BY_OBJ_IDX = {
    0: "AIDKIT_N",
    1: "DRINK_NE",
    2: "AMPULE_N",
    3: "BULLET_N",
    4: "SHELL_NE",
    5: "SHOT_NEA",
}


def pa_for_symbol(sym_path, name):
    text = open(sym_path, encoding="utf-8", errors="replace").read()
    m = re.search(
        rf"//--- PA: (0x[0-9A-Fa-f]+)\s+VA: (0x[0-9A-Fa-f]+)[^\n]*\n(?:.*\n)*?^{name}\s*=\s*(0x[0-9A-Fa-f]+)",
        text,
        re.M,
    )
    if not m:
        raise SystemExit(f"PA not found for {name} in {sym_path}")
    pa_base = int(m.group(1), 16)
    va_base = int(m.group(2), 16)
    va_sym = int(m.group(3), 16)
    return pa_base + (va_sym - va_base)


def read_poses(bin_path, pa):
    poses = []
    with open(bin_path, "rb") as f:
        f.seek(pa)
        for _ in range(32):
            data = f.read(20)
            vx, vy, vz = struct.unpack("<3i", data[0:12])
            rx, ry, rz, _pad = struct.unpack("<4h", data[12:20])
            poses.append(
                (
                    vx / 4096.0,
                    vy / 4096.0,
                    vz / 4096.0,
                    rx / 4096.0 * 360.0,
                    ry / 4096.0 * 360.0,
                    rz / 4096.0 * 360.0,
                )
            )
    return poses


def parse_world_objects(map_name):
    path = os.path.join(DECOMP, "src", "maps", map_name, f"{map_name}.c")
    text = open(path, encoding="utf-8", errors="replace").read()
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import gen_map_data as g  # noqa: E402

    g.enums()
    rows = []
    pat = re.compile(
        r"if\s*\(\s*!Savegame_EventFlagGet\s*\(\s*(EventFlag_\w+)\s*\)\s*\)\s*\{[^}]*"
        r"WorldObjects_Add\s*\(\s*&g_CommonWorldObjects\[(\d+)\]\s*,\s*"
        r"&g_CommonWorldObjectPoses\[(\d+)\]",
        re.S,
    )
    for flag, obj_i, pose_i in pat.findall(text):
        rows.append((g.value(flag), int(obj_i), int(pose_i), flag))
    rows.sort(key=lambda r: r[2])
    return rows


def emit(map_name, out_path):
    if map_name != "map2_s00":
        raise SystemExit("only map2_s00 supported for now")
    pa = pa_for_symbol(SYM, "g_CommonWorldObjectPoses")
    poses = read_poses(DUMP_BIN, pa)
    rows = parse_world_objects(map_name)
    lines = [
        f"/* Generated by tools/gen_common_world_objects.py {map_name} - do not edit. */",
        f"/* Map_WorldObjectsUpdate + g_CommonWorldObjectPoses @ PA 0x{pa:X} */",
        "#pragma once",
        "",
        "typedef struct ShMapWorldObject {",
        "    unsigned event_flag;",
        "    const char *model;",
        "    float pos_x, pos_y, pos_z;",
        "    float rot_x, rot_y, rot_z;",
        "} ShMapWorldObject;",
        "",
        f"static const ShMapWorldObject s_map_world_objects_{map_name}[] = {{",
    ]
    for flag, obj_i, pose_i, flag_name in rows:
        model = MODEL_BY_OBJ_IDX.get(obj_i)
        if not model:
            raise SystemExit(f"unknown g_CommonWorldObjects[{obj_i}]")
        x, y, z, rx, ry, rz = poses[pose_i]
        lines.append(
            f"    {{{flag}, \"{model}\", "
            f"{x:.6f}f, {y:.6f}f, {z:.6f}f, {rx:.6f}f, {ry:.6f}f, {rz:.6f}f}}, "
            f"/* {flag_name} pose {pose_i} */"
        )
    lines += [
        "};",
        f"#define MAP_WORLD_OBJECT_COUNT_{map_name.upper()} {len(rows)}",
        "",
    ]
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", newline="\n", encoding="ascii") as f:
        f.write("\n".join(lines))


def main():
    map_name = sys.argv[1] if len(sys.argv) > 1 else "map2_s00"
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "source", "game", f"map_world_objects_{map_name}.h")
    emit(map_name, out)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
