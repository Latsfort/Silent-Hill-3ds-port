"""Resolve original WATER.TIM sprite state and deduplicate exact shaded palettes."""
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    source = (DECOMP / 'src/maps/map1_s03/unk_draw_800CDCE0.c').read_text(encoding='utf-8')
    packed = {}
    for index in range(4):
        line = next(line for line in source.splitlines() if f')->u{index} =' in line)
        packed[index] = int(re.search(r'(0x[\dA-Fa-f]+)\);', line)[1], 16)
    clut, page = packed[0] >> 16, packed[1] >> 16
    screen = (DECOMP / 'src/bodyprog/screen/screen_data.c').read_text(encoding='utf-8')
    descriptor = list(map(int, re.findall(r'\d+', screen.split('D_800A908C ', 1)[1].split(';', 1)[0])))
    assert descriptor == [0, page & 15, 0, 0, (clut & 63) * 16, clut >> 6]
    effects = (DECOMP / 'src/bodyprog/gfx/bodyprog_effects_8005E0DC.c').read_text(encoding='utf-8')
    assert re.search(r'case MapIdx_MAP1_S03:\s*effectTexFlags = EffectTextureFlag_Water;', effects)
    assert re.search(r'case EffectTextureFlag_Water:\s*Fs_QueueStartReadTim\(FILE_TIM_WATER_TIM,[^;]+&D_800A908C\)', effects)
    raw = (ROOT / 'dump/assets/TIM/WATER.TIM').read_bytes()
    assert (ROOT / 'romfs/game/tim/WATER.TIM').read_bytes() == raw
    assert struct.unpack_from('<I', raw, 4)[0] == 8
    colors = struct.unpack_from('<H', raw, 16)[0]
    palette = struct.unpack_from(f'<{colors}H', raw, 20)
    assert colors == 16 and all(not c or c & 0x8000 for c in palette)
    stride_bits = int(re.search(r'field_2 << (\d+)', source)[1])
    stride = 1 << (stride_bits - 8)
    variants = int(re.search(r'field_C.s_1.field_2\s*= Rng_GenerateUInt\(0, (\d+)\)', source)[1]) + 1
    width = (packed[1] & 255) - (packed[0] & 255) + 1
    height = ((packed[2] >> 8) & 255) - ((packed[0] >> 8) & 255) + 1
    palettes, representatives, mapping = [], [], []
    for shade in range(256):
        shaded = tuple(tuple(min(31, ((color >> channel) & 31) * shade // 128) for channel in (0, 5, 10)) for color in palette)
        if shaded not in palettes:
            palettes.append(shaded)
            representatives.append(shade)
        mapping.append(palettes.index(shaded))
    columns = 8
    atlas_width = width * columns
    atlas_height = 1 << (((len(palettes) * variants + columns - 1) // columns * height - 1).bit_length())
    assert atlas_width <= 1024 and atlas_height <= 1024
    constants = dict(TEXTURE_U=packed[0] & 255, TEXTURE_V=(packed[0] >> 8) & 255,
                     TEXTURE_W=width, TEXTURE_H=height, TEXTURE_STRIDE=stride, TEXTURE_VARIANTS=variants,
                     CLUT_ROW=0, ATLAS_WIDTH=atlas_width, ATLAS_HEIGHT=atlas_height, ATLAS_COLUMNS=columns,
                     PALETTE_SLOTS=len(palettes), CLUT=clut, PAGE=page)
    metadata = ['/* Generated by tools/gen_water_texture.py from source and WATER.TIM. */', '#pragma once']
    metadata += [f'#define SH_WATER_TIM_SIZE {len(raw)}']
    metadata += [f'#define SH_WATER_SPRAY_{name} {value}' for name, value in constants.items()]
    ribbon = (DECOMP / 'src/maps/particle_water.c').read_text(encoding='utf-8')
    uv0 = next(line for line in ribbon.splitlines() if '(*poly)->u0 =' in line)
    uv1 = next(line for line in ribbon.splitlines() if '(*poly)->u1 =' in line)
    u0 = int(re.search(r'\+ (0x[\dA-Fa-f]+) \+', uv0)[1], 16)
    u1 = int(re.search(r'\+ (0x[\dA-Fa-f]+) \+', uv1)[1], 16)
    u_stride = int(re.search(r'& (0x[\dA-Fa-f]+)\) \* (\d+)', uv0)[2]) * 2
    v_stride = 1 << int(re.search(r'& (0x[\dA-Fa-f]+)\) << (\d+)', uv0)[2])
    ribbon_clut = int(re.search(r'\+ (0x[\dA-Fa-f]+);', uv0)[1], 16) >> 16
    ribbon_page = int(re.search(r'\+ (0x[\dA-Fa-f]+);', uv1)[1], 16) >> 16
    assert (ribbon_clut, ribbon_page) == (clut, page)
    assert 'Q6(1.0f) - 1' in ribbon
    ribbon_constants = dict(TEXTURE_U=u0, TEXTURE_V=0, TEXTURE_W=u1-u0+1, TEXTURE_H=v_stride,
        TEXTURE_U_STRIDE=u_stride, TEXTURE_V_STRIDE=v_stride, TEXTURE_VARIANTS=variants,
        CLUT_ROW=0, ATLAS_COLUMNS=columns, PALETTE_SLOTS=len(palettes), CLUT=ribbon_clut, PAGE=ribbon_page)
    ribbon_constants['ATLAS_WIDTH'] = ribbon_constants['TEXTURE_W'] * columns
    ribbon_constants['ATLAS_HEIGHT'] = 1 << (((len(palettes) * variants + columns - 1) // columns * v_stride - 1).bit_length())
    game_header = (DECOMP / 'include/game.h').read_text(encoding='utf-8')
    ribbon_constants['ORDERING_TABLE_SIZE'] = int(re.search(r'#define ORDERING_TABLE_SIZE\s+(\d+)', game_header)[1])
    for axis, field in [('X', 'vx'), ('Y', 'vy')]:
        ribbon_constants[f'SCREEN_LIMIT_{axis}'] = int(re.search(r'ABS\(ptr->field_14C\.' + field + r'\) > (\d+)', ribbon)[1])
    assert u0 + u_stride + ribbon_constants['TEXTURE_W'] <= 128
    assert ribbon_constants['ATLAS_HEIGHT'] <= 1024
    metadata += [f'#define SH_WATER_RIBBON_{name} {value}' for name, value in ribbon_constants.items()]
    surface = ribbon.split('void sharedFunc_800CCE60_1_s02(void)', 1)[1]
    surface_clut = int(re.search(r'ptr->field_260 = (\d+)', surface)[1])
    surface_page = int(re.search(r'ptr->field_262 = (\d+)', surface)[1])
    surface_u = int(re.search(r'poly->u0 = \(\(var_t2_2 << 8\) \+ (\d+)\)', surface)[1])
    surface_right = int(re.search(r'poly->u1 = \(\(var_t2_2 << 8\) \+ (\d+)\)', surface)[1])
    surface_v = int(re.search(r'var_t2_2 = (0x[\dA-Fa-f]+);', surface)[1], 16)
    surface_last = int(re.search(r'var_t3_2 = (0x[\dA-Fa-f]+);', surface)[1], 16)
    surface_row = (surface_clut >> 6) - descriptor[-1]
    assert (surface_clut & 63) * 16 == descriptor[-2] and surface_page == page
    assert surface_row < struct.unpack_from('<H', raw, 18)[0]
    surface_palette = struct.unpack_from(f'<{colors}H', raw, 20 + surface_row * colors * 2)
    assert all(color & 0x8000 for color in surface_palette)
    surface_constants = dict(TEXTURE_U=surface_u, TEXTURE_V=surface_v,
        TEXTURE_W=surface_right - surface_u + 1, TEXTURE_H=surface_last + 1,
        CLUT_ROW=surface_row, CLUT=surface_clut, PAGE=surface_page)
    metadata += [f'#define SH_WATER_SURFACE_{name} {value}' for name, value in surface_constants.items()]
    data = ['/* Generated: exact 5-bit shaded WATER.TIM palettes. */',
            'static const uint8_t s_water_spray_shade_slot[] = {' + ', '.join(map(str, mapping)) + '};',
            'static const uint8_t s_water_spray_slot_shade[] = {' + ', '.join(map(str, representatives)) + '};']
    return {'include/sh3ds/water_render_data.h': '\n'.join(metadata) + '\n',
            'source/game/water_palette_data.h': '\n'.join(data) + '\n'}


if __name__ == '__main__':
    for name, text in outputs().items():
        path = ROOT / name
        if '--check' in sys.argv: assert path.read_text(encoding='ascii') == text
        else: path.write_text(text, encoding='ascii', newline='\n')
    if '--check' in sys.argv: print('PASS: WATER.TIM loading, sprite state and all 256 exact shaded palettes')
