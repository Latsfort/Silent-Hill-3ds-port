"""Extract the retail Math_Sin/Math_Cos lookup values from the verified US overlay."""
import hashlib
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/fixed_trig_data.h'


def emit():
    config = (DECOMP / 'configs/USA/bodyprog.yaml').read_text(encoding='utf-8')
    binary = (ROOT / 'dump/assets/1ST/BODYPROG.BIN').read_bytes()
    if hashlib.sha1(binary).hexdigest() != re.search(r'^sha1: (\w+)', config, re.M)[1]:
        raise ValueError('US BODYPROG SHA1 mismatch')
    symbols = (DECOMP / 'configs/USA/sym.bodyprog.txt').read_text(encoding='utf-8')
    address = int(re.search(r'^g_SineTable\s*=\s*(0x[\da-fA-F]+)', symbols, re.M)[1], 16)
    vram = int(re.search(r'    vram: (0x[\da-fA-F]+)', config)[1], 16)
    table = struct.unpack_from('<5120h', binary, address - vram)
    if table[4096:] != table[:1024]:
        raise ValueError('Math_Cos extension does not repeat the sine first quadrant')
    lines = ['/* Generated by tools/gen_fixed_trig.py - do not edit. */',
             '/* libkmath.s Math_Sin/Math_Cos; values from SHA1-verified US g_SineTable. */',
             'static const int16_t s_fixed_sine[] = {']
    for first in range(0, 4096, 16):
        lines.append('    ' + ', '.join(map(str, table[first:first + 16])) + ',')
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    expected = emit()
    if '--check' in sys.argv:
        if OUTPUT.read_text(encoding='ascii') != expected:
            raise SystemExit('FAIL: generated sine values differ from retail')
        print('PASS: all 4096 sine and 4096 cosine inputs match the retail table')
    else:
        OUTPUT.write_text(expected, encoding='ascii', newline='\n')
