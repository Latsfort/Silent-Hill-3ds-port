"""Extract the school's exact US messages and background inspection wrappers."""
import ast
import json
import hashlib
import struct
from pathlib import Path
import re
import sys

import gen_map_data as g
import gen_common_pickups as pickups
import gen_vc_roads as cameras

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "vendor/silent-hill-decomp"
OUTPUT = ROOT / "source/game/school_data.h"


def emit():
    source = (DECOMP / "src/maps/map1_s00/map1_s00.c").read_text(encoding="utf-8")
    header = (DECOMP / "src/maps/map1_s00/map1_s00_header.c").read_text(encoding="utf-8")
    callbacks = re.findall(r'/\*\s*\d+\s*\*/\s*(\w+)', header.split("void (*g_MapEventFuncs[])() = {", 1)[1].split("};", 1)[0])
    common = (DECOMP / "include/maps/shared/map_msg_common.h").read_text(encoding="utf-8")
    common = common.split("#if VERSION_REGION_IS(NTSC)", 1)[1].split("#elif", 1)[0]
    messages = re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', common + source.split("const char* MAP_MESSAGES[] = {", 1)[1].split("};", 1)[0])
    item_source = (DECOMP / "src/bodyprog/items/item_unk_data.c").read_text(encoding="utf-8")
    names_source = item_source.split("const char* INV_ITEM_NAMES[] = {", 1)[1].split("#else", 1)[1].split("#endif", 1)[0]
    names = re.findall(r'"(?:[^"\\]|\\.)*"|\bNULL\b', g.strip_comments(names_source))
    item_ids = [g.value(name) for name in ("InvItemId_GoldMedallion", "InvItemId_SilverMedallion")]
    lines = ["/* Generated by tools/gen_school_data.py - do not edit. */", "#if defined(SH_SCHOOL_ITEM_NAMES)"]
    for item in item_ids:
        lines.append(f'    case {item}: return {json.dumps(ast.literal_eval(names[item - 32]).replace("_", " "))};')
    lines += ["#elif defined(SH_SCHOOL_ITEM_USE)"]
    for item in item_ids:
        lines.append(f'    case {item}: return true;')
    lines += ["#else", "#pragma once",
             "static const ShSchoolMessage s_school_messages[] = {"]
    for index, literal in messages:
        raw = ast.literal_eval(literal)
        text = re.sub(r'~N', '\x01', raw)
        text = re.sub(r'~[A-Z]\d*(?:\([^)]*\))?', '', text).replace('_', ' ')
        text = '\n'.join(' '.join(line.split()) for line in text.split('\x01'))
        lines.append(f'    [{index}] = {{{json.dumps(text)}, {str("~E" in raw or "~S" in raw).lower()}}},')
    lines += ["};", "static const ShSchoolInspection s_school_inspections[] = {"]
    for match in re.finditer(r'void\s+(\w+)\(void\)[^{]*\{([^{}]*)\}', source):
        name, body = match.groups()
        call = re.search(r'Event_DisplayMapMsgWith(Bg|DimmedBg)\(FILE_TIM_(\w+)_TIM,\s*Q12\(([-\d.]+)f\),\s*Q12\(([-\d.]+)f\),\s*(\d+)(?:,\s*(\d+))?\)', body)
        if not call:
            continue
        kind, image, fade0, fade1, msg0, msg1 = call.groups()
        gamma = re.search(r'g_Screen_BackgroundImgGamma\s*=\s*Q8\(([^)]+)\)', body)
        brightness = 128
        if gamma:
            brightness = int(float(eval(gamma[1].replace('f', ''), {"__builtins__": {}})) * 256)
        if not (ROOT / "romfs/game/tim" / (image + ".TIM")).is_file():
            raise ValueError(f"Missing inspection image: {image}")
        lines.append(f'    {{{callbacks.index(name)}, "{image}.TIM", {fade0}f, {fade1}f, {msg0}, {msg1 or -1}, {brightness}}}, /* {name} */')
    lines += ["};"]
    map_call = re.search(r'Event_PaperMapTake\((\d+), (\w+), (\d+)\)', source)
    map_index, map_flag, map_message = map_call.groups()
    map_index = int(map_index)
    shared = (DECOMP / "src/bodyprog/events/bodyprog_data_800A99B4.c").read_text(encoding="utf-8")
    file_indices = [int(value.strip()) for value in shared.split("s8 g_PaperMapFileIdxs[] = {", 1)[1].split("};", 1)[0].split(',') if value.strip()]
    files = dict((int(index), path) for index, path in re.findall(r'= (\d+), // (\S+)', (ROOT / "dump/assets/fileenum.h.inc").read_text(encoding="utf-8")))
    base_file = int(re.search(r'FILE_TIM_MP_0TOWN_TIM = (\d+)', (ROOT / "dump/assets/fileenum.h.inc").read_text(encoding="utf-8"))[1])
    map_image = Path(files[base_file + file_indices[map_index]]).name
    utility = (DECOMP / "src/bodyprog/events/events_util.c").read_text(encoding="utf-8").split("void Event_PaperMapTake", 1)[1]
    extra_flags = utility.split(f"case {map_index}:", 1)[1].split("break;", 1)[0]
    mask = 1 << map_index
    for expression in re.findall(r'paperMapFlags\s*\|=\s*([^;]+);', extra_flags):
        mask |= g.value(' '.join(expression.split()))
    lines += [f'#define SH_SCHOOL_MAP_IMAGE "{map_image}"', f'#define SH_SCHOOL_MAP_FLAGS {mask}u',
              f'#define SH_SCHOOL_MAP_FLAG {g.value(map_flag)}', f'#define SH_SCHOOL_MAP_MESSAGE {map_message}']
    lines += ["static const ShSchoolProp s_school_boiler_props[] = {"]
    for index, symbol in enumerate(("g_WorldObject0", "g_WorldObject6[0]", "g_WorldObject6[1]")):
        match = re.search(r'WorldObject_PlacementInit\(&' + re.escape(symbol) + r', "(\w+)", ([^)]+)\)', source)
        model, coordinates = match.groups()
        values = []
        for value in coordinates.split(','):
            f32 = struct.unpack('<f', struct.pack('<f', float(value.strip().rstrip('f'))))[0]
            values.append(int(f32 * 4096) / 4096)
        lines.append(f'    {{"{model}", {{{", ".join(f"{v:.8f}f" for v in values)}}}, {{0.0f, 0.0f, 0.0f}}, 1u << {index}}}, /* {symbol} */')
    map_pose = re.search(r'WorldObject_Init\(&g_WorldObject8, "(\w+)", ([^)]+)\)', source)
    model, arguments = map_pose.groups()
    raw_values = [struct.unpack('<f', struct.pack('<f', float(v.strip().rstrip('f'))))[0] for v in arguments.split(',')]
    positions = [int(v * 4096) / 4096 for v in raw_values[:3]]
    rotations = [int(struct.unpack('<f', struct.pack('<f', v / 360))[0] * 4096) * 360 / 4096 for v in raw_values[3:]]
    lines += [f'    {{"{model}", {{{", ".join(f"{v:.8f}f" for v in positions)}}}, {{{", ".join(f"{v:.8f}f" for v in rotations)}}}, 1u << 3}}, /* g_WorldObject8 */', "};"]
    lines += ["static const ShSchoolMedallion s_school_medallions[] = {"]
    for name in ("MapEvent_GoldenSunItemUse", "MapEvent_SilverMoonItemUse"):
        body = source.split(f"void {name}(void)", 1)[1].split("\n}\n", 1)[0]
        images = re.findall(r'FILE_TIM_(\w+)_TIM', body)
        if len(images) != 2:
            raise ValueError(name + ": expected two medallion images")
        msg = re.search(r'Event_DisplayMapMsg\(false, (\d+),', body)[1]
        flag, marker = re.findall(r'Savegame_EventFlagSet\((\w+)\)', body)
        sounds = re.findall(r'SD_Call\((\w+)\)', body)
        lines.append(f'    {{{callbacks.index(name)}, "{images[0]}.TIM", "{images[1]}.TIM", {msg}, {g.value(flag)}, {g.value(marker)}, {{{g.value(sounds[0])}, {g.value(sounds[1])}}}}}, /* {name} */')
    lines += ["};"]
    clock = source.split("void MapEvent_ClockTowerInspect(void)", 1)[1].split("\n}\n", 1)[0]
    images = re.findall(r'Event_BgTextureFadeIn\(FILE_TIM_(\w+)_TIM', clock)
    clock_messages = re.findall(r'Event_DisplayMapMsg\(false, (\d+),', clock)[1:]
    if len(images) != 3 or len(clock_messages) != 3:
        raise ValueError("Expected three retail clock variants")
    lines += ["static const ShSchoolClock s_school_clocks[] = {"]
    for image, msg in reversed(list(zip(images, clock_messages))):
        lines.append(f'    {{"{image}.TIM", {msg}}},')
    lines += ["};"]
    config = (DECOMP / "configs/USA/maps/map1_s00.yaml").read_text(encoding="utf-8")
    overlay = (ROOT / "dump/assets/VIN/MAP1_S00.BIN").read_bytes()
    if hashlib.sha1(overlay).hexdigest() != re.search(r'^sha1: (\w+)', config, re.M)[1]:
        raise ValueError("MAP1_S00.BIN differs from the decomp's US overlay")
    vram = int(re.search(r'    vram: (0x[0-9A-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / "configs/USA/maps/sym.map1_s00.txt").read_text(encoding="utf-8")
    address = int(re.search(r'^MAP_ROOM_IDXS\s*=\s*(0x[0-9A-Fa-f]+)', symbols, re.M)[1], 16)
    map_header = (DECOMP / "include/maps/map1/map1_s00.h").read_text(encoding="utf-8")
    bounds = {key: int(float(value) * 4096) for key, value in re.findall(r'#define MAP_ROOM_(MIN_X|MAX_X|MIN_Z|MAX_Z) Q12\(([-\d.]+)f\)', map_header)}
    terrain = (DECOMP / "include/bodyprog/map/terrain.h").read_text(encoding="utf-8")
    chunk = int(float(re.search(r'#define CHUNK_SIZE\s+([-\d.]+)f', terrain)[1]) * 4096)
    stride = (bounds["MAX_Z"] - bounds["MIN_Z"]) // chunk
    size = (bounds["MAX_X"] - bounds["MIN_X"]) // chunk * stride
    rooms = overlay[address - vram:address - vram + size]
    if len(rooms) != size:
        raise ValueError("Truncated school room grid")
    lines += [f'#define SH_SCHOOL_ROOM_{key} {value}' for key, value in bounds.items()]
    lines += [f'#define SH_SCHOOL_ROOM_STRIDE {stride}', f'#define SH_SCHOOL_ROOM_CHUNK {chunk}',
              "static const uint8_t s_school_rooms[] = {"]
    for i in range(0, size, stride):
        lines.append("    " + ", ".join(map(str, rooms[i:i + stride])) + ",")
    lines += ["};"]
    for name in ("MapIdx_MAP1_S00", "EventFlag_MapMark_Begin", "MapMsgIdx_DoorJammed", "MapMsgIdx_DoorLocked", "MapMsgIdx_DoorUnlocked", "Sfx_DoorJammed", "Sfx_DoorLocked", "Sfx_DoorUnlocked", "EventFlag_71", "EventFlag_72", "EventFlag_73", "EventFlag_83", "EventFlag_84", "Sfx_Unk1420", "Sfx_Unk1422", "Sfx_Unk1430"):
        lines.append(f'#define SH_SCHOOL_{name} {g.value(name)}')
    lines += ["#endif", ""]
    return '\n'.join(lines)


if __name__ == "__main__":
    data = emit()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="ascii") != data:
            raise SystemExit("FAIL: school messages or inspections differ from retail")
        for name, expected in (("mapdata_map1_s00.h", g.emit("map1_s00")),
                               ("map_pickups_map1_s00.h", pickups.emit("map1_s00"))):
            if (ROOT / "source/game" / name).read_text(encoding="ascii") != expected:
                raise SystemExit(f"FAIL: {name} differs from retail")
        roads = [row for row in cameras.parse((DECOMP / "src/maps/map1_s00/vc_road_data.h").read_text(encoding="utf-8")) if not row["flags"] & 1]
        generated = (ROOT / "source/game/vc_roads_map1_s00.h").read_text(encoding="ascii")
        rows = re.findall(r'^    \{\{(.+)\},$', generated, re.M)
        if len(rows) != len(roads):
            raise SystemExit("FAIL: school camera count differs from retail")
        for row, road in zip(rows, roads):
            values = re.findall(r'0x[\dA-F]+|[-\d.]+', row)
            actual = [int(v, 16) if v.startswith("0x") else float(v) for v in values]
            expected = road["sw"] + road["rd"] + [road[k] for k in ("flags", "area", "rd_type", "mv_y", "max_hy", "min_hy", "ofs_watch_hy", "cam_mv", "fix_x", "fix_y")]
            if actual != [round(v, 3) for v in expected]:
                raise SystemExit("FAIL: school camera values differ from retail")
        print("PASS: school US messages, continuation terminators, inspections and door constants match retail")
        print(f"PASS: {len(g.load_points('map1_s00'))} points, {len(g.load_events('map1_s00'))} events, {len(g.load_spawns('map1_s00'))} spawns and {len(roads)} cameras match retail")
    else:
        OUTPUT.write_text(data, encoding="ascii", newline="\n")
