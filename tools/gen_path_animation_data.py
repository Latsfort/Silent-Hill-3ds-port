"""Extract base walk/turn clips and the original variable walk cadence."""
from pathlib import Path
import re
import sys
import hashlib
import struct
import gen_map_data as g
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/path_animation_data.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/bodyprog/player_control.c').read_text(encoding='utf-8'))
    table = source.split('s_AnimInfo HARRY_BASE_ANIM_INFOS[57] = {', 1)[1].split('\n};', 1)[0]
    pattern = r'\{ (Anim_\w+),\s*ANIM_STATUS\((HarryAnim_\w+),\s*(false|true)\),\s*(false|true),\s*(ANIM_STATUS\(\w+,\s*(?:false|true)\)|NO_VALUE),\s*\{ ([^}]+) \},\s*(NO_VALUE|\d+),\s*(\d+)\s*\}'
    lines = ['/* Generated by tools/gen_path_animation_data.py from HARRY_BASE_ANIM_INFOS. */',
             'static const ShPathAnimDef s_path_animation_defs[] = {']
    count = 0
    for kind, name, active, variable, link, duration, first, last in re.findall(pattern, table):
        if name not in ('HarryAnim_WalkForward', 'HarryAnim_TurnLeft', 'HarryAnim_TurnRight'):
            continue
        status = g.value(name) * 2 + (active == 'true')
        if link == 'NO_VALUE': link_value = -1
        else:
            link_name, link_active = re.search(r'ANIM_STATUS\((\w+),\s*(true|false)\)', link).groups()
            link_value = g.value(link_name) * 2 + (link_active == 'true')
        assert kind in ('Anim_BlendLinear', 'Anim_PlaybackLoop')
        rate = 0 if variable == 'true' else fixed(re.search(r'Q12\(([-\d.]+)f\)', duration)[1])
        lines.append(f'    {{{status}, {1 if kind == "Anim_BlendLinear" else 0}, {variable}, {{{-1 if first == "NO_VALUE" else first}, {last}, {link_value}}}, {rate}}},')
        count += 1
    assert count == 6
    config = (ROOT / 'vendor/silent-hill-decomp/configs/USA/maps/map1_s02.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP1_S02.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (ROOT / 'vendor/silent-hill-decomp/configs/USA/maps/sym.map1_s02.txt').read_text(encoding='utf-8')
    address = lambda name: int(re.search(r'^' + name + r'\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    mapping = list(struct.iter_unpack('<4h', raw[address('g_MapHeaderTable_38') - base:address('LOADABLE_INVENTORY_ITEMS') - base]))
    shared = (ROOT / 'vendor/silent-hill-decomp/include/maps/shared/sharedFunc_800CDAA8_0_s02.h').read_text(encoding='utf-8')
    states = []
    for state in (74, 94, 95, 59, 60, 106, 97, 98):
        code = shared.split(f'case PlayerState_Unk{state}:', 1)[1].split('break;', 1)[0]
        virtual, active = re.search(r'ANIM_STATUS\((\d+), (true|false)\)', code).groups()
        packed, _, _, _ = next(row for row in mapping if row[1] == int(virtual) * 2 + (active == 'true'))
        states.append((state, packed & 255))
    arrival = (ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s02/map1_s02_anim_info.c').read_text(encoding='utf-8')
    arrival_pattern = r'\{ (Anim_\w+),\s*ANIM_STATUS\((\d+),\s*(false|true)\),\s*false,\s*ANIM_STATUS\((\d+),\s*(false|true)\),\s*\{ Q12\(([-\d.]+)f\)\s*\},\s*(NO_VALUE|\d+),\s*(\d+)\s*\}'
    arrival_count = 0
    for kind, index, active, link_index, link_active, rate, first, last in re.findall(arrival_pattern, arrival):
        status = int(index) * 2 + (active == 'true')
        if not any(status in (initial, initial + 1) for _, initial in states): continue
        assert kind in ('Anim_BlendLinear', 'Anim_PlaybackOnce')
        link_value = int(link_index) * 2 + (link_active == 'true')
        signed_rate = (fixed(rate) + (1 << 31)) % (1 << 32) - (1 << 31)
        lines.append(f'    {{{status}, {1 if kind == "Anim_BlendLinear" else 2}, false, {{{-1 if first == "NO_VALUE" else first}, {last}, {link_value}}}, {signed_rate}}},')
        arrival_count += 1
    assert arrival_count == len(states) * 2
    lines += ['};', 'static const struct { int state, status; } s_path_school_states[] = {']
    lines += [f'    {{{state}, {status}}},' for state, status in states]
    lines += ['};', 'static int32_t path_walk_duration(int stick_y, int stick_magnitude)', '{', '    int32_t duration;']
    body = source.split('case ANIM_STATUS(HarryAnim_WalkForward, true):', 1)[1].split('case ANIM_STATUS(HarryAnim_RunForward, true):', 1)[0]
    body = body.rsplit('break;', 1)[0]
    body = re.sub(r'Q12\(([-\d.]+)f\)', lambda m: str(fixed(m[1])), body)
    body = body.replace('g_Controller0->rawSticks.sticks_0.leftY', 'stick_y').replace('g_Player_MoveStickMag', 'stick_magnitude')
    joy = (ROOT / 'vendor/silent-hill-decomp/include/bodyprog/sys/joy.h').read_text(encoding='utf-8')
    deadzone = int(float(re.search(r'#define STICK_DEADZONE\s+FP_STICK\(([-\d.]+)f\)', joy)[1]) * 256) // 2
    body = body.replace('STICK_DEADZONE', str(deadzone)).replace('ABS', 'abs')
    assert not re.search(r'\bg_\w+', body)
    lines += [body, '    return duration;', '}', '']
    return '\n'.join(line.rstrip() for line in lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: walk/turn and school clips, verified overlay mappings and walk cadence')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
