"""Adapt the original lighter sprite CPU logic without replacing its random/counter steps."""
from pathlib import Path
import re
import struct
import sys
import gen_map_data as g
from gen_school_smoke import function

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    source = g.strip_comments((DECOMP / 'src/bodyprog/world/world_effects.c').read_text(encoding='utf-8'))
    code = function(source, 'func_8003E740')
    for declaration in ('MATRIX    viewMat;', 's32       depthZ;', 'POLY_FT4* poly;', 'static u32 D_800A9FB0 = 0;'):
        assert declaration in code
        code = code.replace(declaration, '')
    replacements = {
        'g_DeltaTime != Q12(0.0f)': 'tick', 'D_800A9FB0': 'flame->counter', 'D_800BCDE8': 'flame->random',
        'Rng_Rand16()': 'sh_rng_rand16()', 'Q12_MULT(': 'sh_q12_mul(', 'Math_AngleNormalize(': 'flame_angle(',
        'poly = (POLY_FT4*)GsOUT_PACKET_P;': '',
        'Vw_CoordToViewSpaceMatrix(&g_SysWork.playerBoneCoords[HarryBone_RightHand], &viewMat);': '',
        'SetRotMatrix(&viewMat);': '', 'SetTransMatrix(&viewMat);': '',
        'RotTransPers(&sp38, &sp10, &depthZ, &depthZ)': 'project(user, true, &sp38, &sp10)',
        'SetPolyFT4(poly);': '', 'setSemiTrans(poly, true);': '',
        'setRGB0(poly, flame->counter + 48, flame->counter + 48, flame->counter + 48);':
            'poly->shade = (uint8_t)(flame->counter + 48);',
        'SetRotMatrix(&GsIDMATRIX);': '', 'SetTransMatrix(&GsIDMATRIX);': '',
        'RotTransPers(&sp50, &sp58, &depthZ, &depthZ);': 'project(user, false, &sp50, &sp58);',
        'AddPrim(&g_OrderingTable0[g_ActiveBufferIdx].org[var_s5], poly);':
            'poly->ordering = var_s5;\n        poly->depth = temp_s6;\n        return true;',
        'GsOUT_PACKET_P = (PACKET*)poly + sizeof(POLY_FT4);': '',
        'ORDERING_TABLE_SIZE': str(g.value('ORDERING_TABLE_SIZE')),
        'DVECTOR': 'ShFlameScreen', 'SVECTOR': 'ShFlamePoint', 's32': 'int32_t', 's16': 'int16_t',
    }
    for old, new in replacements.items():
        assert old in code, old
        code = code.replace(old, new)
    code = '\n'.join(line.rstrip() for line in code.splitlines())
    code += '\n    return false;\n'
    assert not re.search(r'\b(?:g_|D_800|RotTrans|SetRot|SetTrans|Q12|Gs|PACKET|POLY_)\w*', code)
    data = ('/* Generated by tools/gen_flame.py from world_effects.c func_8003E740. */\n'
            'static bool flame_frame(ShFlame *flame, bool tick, ShFlameProject project, void *user, ShFlameQuad *poly)\n{\n' + code + '}\n')
    asset = (ROOT / 'dump/assets/TIM/FLAME.TIM').read_bytes()
    assert asset == (ROOT / 'romfs/game/tim/FLAME.TIM').read_bytes()
    palette_bytes = struct.unpack_from('<I', asset, 8)[0]
    _, _, words, height = struct.unpack_from('<4H', asset, 8 + palette_bytes + 4)
    relocation = function(source, 'GameFs_FlameGfxLoad')
    relocated_u = int(re.search(r'\.u\s*=\s*(\d+)', relocation)[1]) * 4
    constants = ('/* Generated by tools/gen_flame.py; retail asset and environment flag. */\n#pragma once\n' +
        f'#define SH_FLAME_TIM_BYTES {len(asset)}\n' +
        f'#define SH_FLAME_TEXTURE_W {words * 4}\n#define SH_FLAME_TEXTURE_H {height}\n' +
        f'#define SH_FLAME_TEXTURE_U {relocated_u}\n' +
        f'#define SH_FLAME_ENV_FLAG {g.value("SpecialEnvEventFlags_UseLighter")}\n')
    return {ROOT / 'source/game/flame_steps.h': data, ROOT / 'include/sh3ds/flame_data.h': constants}


if __name__ == '__main__':
    for path, data in outputs().items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='ascii') == data
        else:
            path.write_text(data, encoding='ascii', newline='\n')
    print('PASS: original lighter sprite CPU function and packaged FLAME.TIM')
