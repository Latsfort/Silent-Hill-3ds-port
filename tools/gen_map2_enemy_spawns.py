#!/usr/bin/env python3
"""Extract map2_s00 D_800F1CAC[3][2][16] s_SpawnInfo (func_800EE5D0) from MAP2_S00.BIN."""
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = os.path.join(ROOT, "dump", "assets", "VIN", "MAP2_S00.BIN")
OUT = os.path.join(ROOT, "source", "game", "map_enemy_spawns_map2_s00.h")

VRAM = 0x800C9578  # configs/USA/maps/map2_s00.yaml
TABLE = 0x800F1CAC  # D_800F1CAC
# s_SpawnInfo (map.h): posX q19_12, charaId s8, rotY q0_8, flags s8, difficultyMin s4, posZ q19_12
RECORD = struct.Struct("<ibBbBi")


def main():
    with open(BIN, "rb") as f:
        blob = f.read()
    base = TABLE - VRAM
    lines = [
        "/* Generated by tools/gen_map2_enemy_spawns.py - MAP2_S00.BIN D_800F1CAC (func_800EE5D0). */",
        "#pragma once",
        "",
        "typedef struct ShMapEnemySpawn {",
        "    float x, z;     /* PS1 xz; 3DS z = -z */",
        "    float yaw_deg;  /* PS1 rotation.vy */",
        "    int chara_id;   /* 0 = charaGroupIds[group] */",
        "    int flags;      /* e_SpawnFlags, 0 = unused slot */",
        "    int diff_min;   /* e_GameDifficulty (signed 4 bits) */",
        "} ShMapEnemySpawn;",
        "",
        "/* [variant func_800EE518][group: 0 AirScreamer, 1 Groaner][slot] */",
        "static const ShMapEnemySpawn s_map_enemy_spawns_map2_s00[3][2][16] = {",
    ]
    for v in range(3):
        lines.append("    {")
        for g in range(2):
            lines.append("        {")
            for i in range(16):
                off = base + ((v * 2 + g) * 16 + i) * RECORD.size
                px, cid, ry, fl, dif, pz = RECORD.unpack_from(blob, off)
                d = dif & 15
                d = d - 16 if d >= 8 else d
                lines.append(
                    f"            {{{px / 4096.0:.4f}f, {pz / 4096.0:.4f}f, {ry * 360.0 / 256.0:.2f}f, {cid}, {fl}, {d}}},"
                )
            lines.append("        },")
        lines.append("    },")
    lines += ["};", ""]
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
