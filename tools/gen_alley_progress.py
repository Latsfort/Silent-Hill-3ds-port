"""Extract the opening alley's darkness paths and original fixed-point queries."""
from pathlib import Path
import hashlib
import re
import struct
import sys

import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/alley_progress_data.h'


def emit():
    source = g.strip_comments((DECOMP / 'src/maps/map0_s00/map0_s00_2.c').read_text(encoding='utf-8'))
    math = g.strip_comments((DECOMP / 'src/bodyprog/bodyprog_math_8005BF38.c').read_text(encoding='utf-8'))
    events_source = g.strip_comments((DECOMP / 'src/bodyprog/events/events_main.c').read_text(encoding='utf-8'))
    config = (DECOMP / 'configs/USA/maps/map0_s00.yaml').read_text(encoding='utf-8')
    overlay = (ROOT / 'dump/assets/VIN/MAP0_S00.BIN').read_bytes()
    assert hashlib.sha1(overlay).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    segments = int(re.search(r'i < (\d+)', function(source, 'func_800DCDA8'))[1])
    lines = ['/* Generated by tools/gen_alley_progress.py; MAP0_S00 and bodyprog_math_8005BF38.c. */',
             '#pragma once', '#include "sh3ds/mapdata.h"']
    points = g.load_points('map0_s00')
    lines.append('static const ShMapPoint s_alley_points[] = {')
    for p in points:
        lines.append('    {' + f"{p['x']:.8f}f, {p['z']:.8f}f, " +
                     ', '.join(str(p[k]) for k in ('paper_map', 'field_4_5', 'loading_screen', 'param0', 'param1')) + '},')
    lines += ['};', 'static const ShMapEvent s_alley_room_events[] = {']
    for event in g.load_events('map0_s00'):
        if event['sys_state'] == g.value('SysState_LoadRoom'):
            lines.append('    {' + ', '.join(str(event[k]) for k in (
                'required_flag', 'complete_flag', 'trigger_type', 'activation_type', 'point_idx', 'required_item',
                'sys_state', 'event_param', 'transition_flags', 'sfx_pair', 'on_rail', 'map_idx')) + '},')
    lines += ['};', 'static const ShMapEvent s_alley_gate_events[] = {']
    for event in g.load_events('map0_s00'):
        if event['func'] == 'MapEvent_CutsceneCherylIntoTheAlley':
            assert event['trigger_type'] == g.value('TriggerType_TouchAabb')
            lines.append('    {' + ', '.join(str(event[k]) for k in (
                'required_flag', 'complete_flag', 'trigger_type', 'activation_type', 'point_idx', 'required_item',
                'sys_state', 'event_param', 'transition_flags', 'sfx_pair', 'on_rail', 'map_idx')) + '},')
    lines += ['};', '']
    for name, count in [('D_800DFAE0', segments + 1), ('D_800DFB28', 2)]:
        address = int(name[2:], 16)
        rows = list(struct.iter_unpack('<3i', overlay[address - base:address - base + count * 12]))
        assert len(rows) == count
        lines.append(f'static const struct {{ int32_t vx, vy, vz; }} {name}[] = {{')
        lines.extend('    {' + ', '.join(map(str, row)) + '},' for row in rows)
        lines += ['};', '']

    def adapt(code):
        changes = {
            'playerChara.position.vx': 'x', 'playerChara.position.vz': 'z',
            '#define playerChara g_SysWork.playerWork.player': '', '#undef playerChara': '',
            'g_SysWork.sysState == SysState_EventCallback': 'callback',
            'g_DeltaTime': 'delta', 'Savegame_EventFlagGet(EventFlag_15)': 'started',
            'Math_AngleNormalizeSigned': 'alley_signed_angle',
            'Math_Vector2MagCalcSafeQ6': 'alley_magnitude',
            'Math_Sin': 'sh_fixed_sin', 'Math_Cos': 'sh_fixed_cos', 'ratan2': 'sh_fixed_atan2',
            'func_8005C478': 'alley_segment',
            'Q12_MULT_PRECISE': 'sh_q12_mul', 'Q12_MULT': 'sh_q12_mul',
            'Q12_SHIFT': 'SH_Q12_SHIFT', 'ABS(': 'ALLEY_ABS(', 'MAX(': 'ALLEY_MAX(',
            'SQUARE(': 'ALLEY_SQUARE(', 's16': 'int16_t', 's32': 'int32_t', 'q3_12': 'int16_t',
            'g_SysWork.playerWork.player.position.vx': 'x',
            'g_SysWork.playerWork.player.position.vz': 'z',
            'g_SysWork.playerWork.player.rotation.vy': 'yaw',
            'mapPoint->positionX': 'SH_Q12(mapPoint->x)', 'mapPoint->positionZ': 'SH_Q12(mapPoint->z)',
            'mapPoint->triggerParam0': 'mapPoint->param0', 'mapPoint->triggerParam1': 'mapPoint->param1',
            'Q12_ANGLE_FROM_Q8(': 'ALLEY_Q8_ANGLE(', 'DIV_FAST(': 'ALLEY_DIV(', 'MIN(': 'ALLEY_MIN(',
            'q19_12': 'int32_t', 'u32': 'uint32_t', 'FP_FROM(': 'ALLEY_FP_FROM(',
        }
        for old in sorted(changes, key=len, reverse=True):
            code = code.replace(old, changes[old])
        code = re.sub(r'Q12\(([-\d.]+)f?\)', lambda m: str(fixed(m[1])), code)
        assert not re.search(r'\b(?:g_|Savegame_|Q12|playerChara)\w*', code), code
        return code

    for name, signature, text in [
        ('func_8005C478', 'static uint32_t alley_segment(int16_t *arg0, int32_t x0, int32_t y0, int32_t x1, int32_t y1, int32_t x2, int32_t y2)', math),
        ('func_800DCDA8', 'static int32_t alley_path_darkness(int32_t x, int32_t z)', source),
        ('func_800DCF38', 'static int32_t alley_darkness_advance(int32_t arg0, bool callback, bool started, int32_t x, int32_t z, int32_t delta)', source),
        ('Event_CollideObbFacingCheck', 'static bool alley_obb_facing(const ShMapPoint *mapPoint, int32_t x, int32_t z, int32_t yaw)', events_source),
        ('Event_CollideObbCheck', 'static bool alley_obb(const ShMapPoint *mapPoint, int32_t x, int32_t z)', events_source),
    ]:
        lines += [signature, '{', adapt(function(text, name)), '}', '']
    return '\n'.join(line.rstrip() for line in '\n'.join(lines).split('\n'))


if __name__ == '__main__':
    result = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == result
        print('PASS: 8 ROM path points and original segment/darkness functions match retail')
    else:
        OUTPUT.write_text(result, encoding='ascii', newline='\n')
