"""Extract original roof/locker placements and their source visibility gates."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_roof_props.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    init = function(source, 'Map_WorldObjectsInit')
    lines = ['/* Generated by tools/gen_roof_props.py from MAP1_S03 world objects. */',
             'static const ShSchoolProp s_school_roof_props[] = {']
    objects = (5, 6, 0, 1, 2, 3, 4, 7)
    for index, obj in enumerate(objects):
        kind, model, arguments = re.search(r'WorldObject_(Init|PlacementInit)\(&g_WorldObject' + str(obj) + r', "([^"]+)", ([^;]+)\);', init).groups()
        values = [value.strip().rstrip('f') for value in arguments.split(',')]
        position = [fixed(value) / 4096 for value in values[:3]]
        rotation = [fixed(value, True) / 4096 * 360 for value in values[3:]] if kind == 'Init' else [0, 0, 0]
        assert len(position) == len(rotation) == 3
        fmt = lambda values: ', '.join(f'{value:.12f}f' for value in values)
        lines.append(f'    {{"{model}", {{{fmt(position)}}}, {{{fmt(rotation)}}}, 1u << {index}}},')
    lines += ['};']
    update = function(source, 'Map_WorldObjectsUpdate')
    begin = update.index('if (PLAYER_IN_MAP_CHUNK')
    end = update.index('\n    if (PLAYER_IN_MAP_CHUNK', begin + 1)
    code = update[begin:end]
    code = re.sub(r'WorldObjects_Add\(&g_WorldObject([56])\.object, [^;]+\);',
        lambda m: f'mask |= s_school_roof_props[{0 if m[1] == "5" else 1}].mask;', code)
    code = code.replace('Savegame_EventFlagGet(EventFlag_M1S02_UsedRubberBall)', f'sh_save_event_get(save, {g.value("EventFlag_M1S02_UsedRubberBall")})')
    code = code.replace('PLAYER_IN_MAP_CHUNK(vx,', 'in_chunk(SH_Q12(x),').replace('PLAYER_IN_MAP_CHUNK(vz,', 'in_chunk(SH_Q12(-z),')
    room = re.search(r'if \((PLAYER_IN_MAP_CHUNK[^\n]+)\)\s*\{\s*func_800DE828\(\);', update)[1]
    room = room.replace('PLAYER_IN_MAP_CHUNK(vx,', 'in_chunk(SH_Q12(x),').replace('PLAYER_IN_MAP_CHUNK(vz,', 'in_chunk(SH_Q12(-z),')
    key_branch = update[update.index('if (Savegame_EventFlagGet(EventFlag_107)'):update.index('if (g_SysWork.playerWork.player.position.vx <')]
    key_branch = re.sub(r'Savegame_EventFlagGet\((\w+)\)', lambda m: f'sh_save_event_get(save, {g.value(m[1])})', key_branch)
    key_branch = re.sub(r'WorldObjects_Add\(&g_WorldObject7\.object, [^;]+\);', f'mask |= s_school_roof_props[{objects.index(7)}].mask;', key_branch)
    code += '\n    if (roof_locker_in_room(x, z)) {\n'
    for obj in range(5): code += f'        if (locker_mask & (1u << {obj})) {{ mask |= s_school_roof_props[{objects.index(obj)}].mask; }}\n'
    code += key_branch + '\n    }\n'
    assert not re.search(r'\b(?:g_|WorldObjects_|Savegame_|PLAYER_)\w*', code), code
    lines += ['#ifdef SH_SCHOOL_ROOF_PROP_MASK',
        'static bool roof_locker_in_room(float x, float z)', '{', f'    return {room};', '}',
        'static uint32_t roof_prop_mask(const ShSavegame *save, float x, float z, uint32_t locker_mask)', '{',
        '    uint32_t mask = 0;', code, '    return mask;', '}', '#endif', '']
    return '\n'.join(line.rstrip() for line in '\n'.join(lines).split('\n'))


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: eight original roof/locker placements, rotations and chunk/flag visibility')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
