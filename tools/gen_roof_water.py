"""Adapt original water configuration and particle initialization, preserving unions."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    header = g.strip_comments((DECOMP / 'include/bodyprog/map/map.h').read_text(encoding='utf-8'))
    types = ['/* Generated by tools/gen_roof_water.py from original map types. */', '#pragma once', '#include <stdint.h>']
    aliases = {'s_MapHdr_field_4C': 'ShWaterParticle', 's_MapOverlayHdr_94': 'ShWaterConfig'}
    primitive = {'s32': 'int32_t', 'u32': 'uint32_t', 's16': 'int16_t', 'u16': 'uint16_t',
                 's8': 'int8_t', 'u8': 'uint8_t', 'q19_12': 'int32_t', 'q20_12': 'int32_t',
                 'q3_12': 'int16_t', 'q4_12': 'int16_t'}
    for original, native in aliases.items():
        end = header.index('} ' + original + ';') + len('} ' + original + ';')
        start = header.rfind('typedef struct', 0, end)
        code = header[start:end].replace(original, native)
        code = re.sub(r'\b(' + '|'.join(primitive) + r')\b', lambda m: primitive[m[0]], code)
        types.append(code)
    expected_size = int(re.search(r'STATIC_ASSERT_SIZEOF\(s_MapHdr_field_4C, (\d+)\)', header)[1])
    types += [f'typedef char sh_water_particle_layout[(sizeof(ShWaterParticle) == {expected_size}) ? 1 : -1];', '']
    map_header = (DECOMP / 'include/maps/map1/map1_s03.h').read_text(encoding='utf-8')
    capacity = int(re.search(r'#define MAP_FIELD_4C_COUNT (\d+)', map_header)[1])
    types.append(f'#define SH_ROOF_WATER_POOL_COUNT {capacity}')
    spray_header = g.strip_comments(map_header)
    spray_end = spray_header.index('} s_800E3A40;') + len('} s_800E3A40;')
    spray_type = spray_header[spray_header.rfind('typedef struct', 0, spray_end):spray_end]
    spray_type = spray_type.replace('s_800E3A40', 'ShWaterSprayConfig')
    spray_type = re.sub(r'\b(' + '|'.join(primitive) + r')\b', lambda m: primitive[m[0]], spray_type)
    types.append(spray_type)
    source = g.strip_comments((DECOMP / 'src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    config = function(source, 'MapEvent_DrainageValveInteract').split('case 4:', 1)[1].split('case 5:', 1)[0]
    config = config[config.index('sharedData_800E30C8_1_s02.'):config.index('g_SysWork.playerWork.player.position.vx')]
    config = re.sub(r'D_800E3A40\[\d+\]\.\w+\s*=\s*[^;]+;', '', config)
    config = config.replace('Savegame_EventFlagGet(EventFlag_M1S02_UsedRubberBall)', 'ball')
    config = config.replace('sharedData_800E30C8_1_s02.', 'config->')
    config = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f?\)', lambda m: str(fixed(m[2], bool(m[1]))), config)
    assert not re.search(r'\b(?:D_|g_|sharedData_|Event_|Savegame_)\w*', config)
    spawn_source = g.strip_comments((DECOMP / 'src/maps/particle_water.c').read_text(encoding='utf-8'))
    spawn = function(spawn_source, 'sharedFunc_800CBA4C_1_s02')
    spawn = spawn.replace('sharedData_800E30C8_1_s02.', 'config->')
    spawn = spawn.replace('sharedData_800DFB7C_0_s00[idx].', 'particle->')
    spawn = spawn.replace('Rng_Rand16()', 'sh_rng_rand16()').replace('Rng_GenerateUInt', 'water_random_range')
    spawn = spawn.replace('Q12_MULT', 'sh_q12_mul').replace('Math_Sin', 'sh_fixed_sin').replace('Math_Cos', 'sh_fixed_cos')
    spawn = re.sub(r'\bs32\b', 'int32_t', spawn)
    assert not re.search(r'\b(?:sharedData_|Rng_|Math_|g_)\w*', spawn)
    steps = ['/* Generated by tools/gen_roof_water.py; original assignments and RNG order. */',
             'void sh_water_configure_roof(ShWaterConfig *config, bool ball)', '{', config, '}',
             'void sh_water_particle_spawn(ShWaterParticle *particle, const ShWaterConfig *config, int arg1, int arg2)',
             '{', spawn, '}']
    allocation_source = g.strip_comments((DECOMP / 'src/bodyprog/gfx/bodyprog_effects_8005E0DC.c').read_text(encoding='utf-8'))
    allocation = function(allocation_source, 'func_8005E7E0')
    allocation = allocation.replace('g_MapOverlayHdr.unkTable1Count_50', 'pool->count')
    allocation = allocation.replace('g_MapOverlayHdr.unkTable1_4C[idx].', 'pool->particles[idx].')
    allocation = allocation.replace('D_800C4408', 'pool->next').replace('NO_VALUE', '-1')
    allocation = re.sub(r'\bs32\b', 'int32_t', allocation)
    assert not re.search(r'\b(?:g_|D_)\w*', allocation)
    steps += ['static int water_slot_alloc(ShWaterPool *pool, int arg0)', '{', allocation, '}']
    for retail, native, arguments in [('sharedFunc_800CBC98_1_s02', 'sh_water_pool_begin', 'ShWaterPool *pool, ShWaterConfig *config'),
                                       ('sharedFunc_800CBD58_1_s02', 'sh_water_pool_stop', 'ShWaterPool *pool')]:
        code = function(spawn_source, retail)
        code = code.replace('sharedData_800E30C8_1_s02.', 'config->')
        code = code.replace('ARRAY_SIZE(sharedData_800DFB7C_0_s00)', 'pool->count')
        code = code.replace('sharedData_800DFB7C_0_s00[i].', 'pool->particles[i].')
        code = code.replace('D_800C4414', 'pool->flags').replace('NO_VALUE', '-1')
        code = code.replace('func_8005E7E0(27)', 'water_slot_alloc(pool, 27)')
        code = code.replace('sharedFunc_800CBA4C_1_s02(idx, 2, 0)', 'sh_water_particle_spawn(&pool->particles[idx], config, 2, 0)')
        code = re.sub(r'\bs32\b', 'int32_t', code)
        assert not re.search(r'\b(?:sharedData_|func_|D_)\w*', code)
        steps += [f'void {native}({arguments})', '{', code, '}']
    motion = function(spawn_source, 'sharedFunc_800CBDA8_1_s02')
    horizontal_start = motion.index('temp_s4 = Q12_MULT_PRECISE(g_DeltaTime,')
    end_pattern = r'temp_s4\s*= sharedData_800DFB7C_0_s00\[idx\]\.field_10\.s_3\.field_0;'
    horizontal_end = re.search(end_pattern, motion[horizontal_start:]).start() + horizontal_start
    horizontal = motion[horizontal_start:horizontal_end]
    vertical_start = motion.index('sharedData_800DFB7C_0_s00[idx].field_C.s_0.field_2 = MIN')
    vertical_end = re.search(end_pattern, motion[vertical_start:]).start() + vertical_start
    vertical = motion[vertical_start:vertical_end]
    code = 'if (config->field_30[idx0] == 0) {\n' + horizontal + '\n} else {\n' + vertical + '\n}'
    code = code.replace('sharedData_800E30C8_1_s02.', 'config->').replace('sharedData_800DFB7C_0_s00[idx].', 'particle->')
    code = code.replace('ptr->field_0.field_DC[idx0]', 'sh_fixed_sin(config->field_34[idx0])')
    code = code.replace('ptr->field_0.field_E4[idx0]', 'sh_fixed_cos(config->field_34[idx0])')
    code = code.replace('sharedFunc_800CBA4C_1_s02(idx, 3, idx0 + 1)', 'sh_water_particle_spawn(particle, config, 3, idx0 + 1)')
    code = code.replace('Q12_MULT_PRECISE', 'sh_q12_mul').replace('Q12_MULT', 'sh_q12_mul')
    code = code.replace('g_DeltaTime', 'dt').replace('g_GravitySpeed', 'gravity').replace('MIN', 'water_min')
    code = re.sub(r'Q12\(([-\d.]+)f\)', lambda m: str(fixed(m[1])), code)
    assert not re.search(r'\b(?:sharedData_|ptr|g_|Q12_)\w*', code)
    update = ['/* Generated from sharedFunc_800CBDA8_1_s02 movement before projection. */',
              'bool sh_water_particle_step(ShWaterParticle *particle, const ShWaterConfig *config, int32_t dt, int32_t gravity)', '{',
              '    const int idx0 = particle->field_C.s_1.field_0 >> 2;', '    int32_t temp_s4;', code, '    return true;', '}']
    spray_config = function(source, 'MapEvent_DrainageValveInteract').split('case 4:', 1)[1].split('case 5:', 1)[0]
    spray_config = spray_config[spray_config.index('sharedData_800E30C8_1_s02.'):spray_config.index('g_SysWork.playerWork.player.position.vx')]
    spray_config = re.sub(r'sharedData_800E30C8_1_s02\.\w+(?:\[[^;]+?\])?\s*=\s*[^;]+;', '', spray_config)
    spray_config = spray_config.replace('Savegame_EventFlagGet(EventFlag_M1S02_UsedRubberBall)', 'ball')
    spray_config = spray_config.replace('D_800E3A40[', 'config[')
    spray_config = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f?\)', lambda m: str(fixed(m[2], bool(m[1]))), spray_config)
    assert not re.search(r'\b(?:sharedData_|Savegame_|g_)\w*', spray_config)
    spray_source = g.strip_comments((DECOMP / 'src/maps/map1_s03/unk_draw_800CDCE0.c').read_text(encoding='utf-8'))
    spray = ['/* Generated from original roof spray configuration and functions. */',
             'void sh_water_spray_configure_roof(ShWaterSprayConfig *config, bool ball)', '{', spray_config, '}']
    for retail, native, args in [('func_800CDCE0', 'sh_water_spray_spawn', 'ShWaterParticle *particle, const ShWaterSprayConfig *config, int arg1, int arg2'),
                                  ('func_800CE0CC', 'sh_water_spray_begin', 'ShWaterPool *pool, const ShWaterSprayConfig *config, int arg0'),
                                  ('func_800CE164', 'sh_water_spray_step', 'ShWaterParticle *particle, const ShWaterSprayConfig *config, int32_t dt')]:
        code = function(spray_source, retail)
        if retail == 'func_800CE164':
            code = code[code.index('sharedData_800DFB7C_0_s00[idx].field_C.s_0.field_0 +='):code.index('Math_SetSVectorFastSum')]
            code = '    int32_t idx2;\n' + code + '\n    return true;'
        code = code.replace('D_800E3A40[', 'config[')
        code = code.replace('sharedData_800DFB7C_0_s00[arg0].', 'particle->').replace('sharedData_800DFB7C_0_s00[idx].', 'particle->')
        code = code.replace('func_800CDCE0(idx, arg0, 0)', 'sh_water_spray_spawn(&pool->particles[idx], config, arg0, 0)')
        code = code.replace('func_800CDCE0(idx, idx2, 1)', 'sh_water_spray_spawn(particle, config, idx2, 1)')
        code = code.replace('func_8005E7E0(28)', 'water_slot_alloc(pool, 28)')
        code = code.replace('Rng_Rand16()', 'sh_rng_rand16()').replace('Rng_AddGeneratedUInt', 'water_random_add')
        code = code.replace('Rng_GenerateInt', 'water_random_range').replace('Rng_GenerateUInt', 'water_random_range')
        code = code.replace('Math_Sin', 'sh_fixed_sin').replace('Math_Cos', 'sh_fixed_cos')
        code = code.replace('FP_FROM', 'WATER_FROM').replace('Q12_SHIFT', '12').replace('SQUARE', 'WATER_SQUARE')
        code = code.replace('g_DeltaTime', 'dt').replace('NO_VALUE', '-1')
        code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f?\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
        code = re.sub(r'\b(' + '|'.join(primitive) + r')\b', lambda m: primitive[m[0]], code)
        assert not re.search(r'\b(?:sharedData_|func_|Rng_|Math_|g_)\w*', code)
        spray += [f'{"bool" if retail == "func_800CE164" else "void"} {native}({args})', '{', code, '}']
    quad = function(spray_source, 'func_800CE164')
    quad = quad[quad.index('var_lo = FP_TO'):quad.index('addPrim(&g_OrderingTable0')]
    quad = quad.replace('D_800E3A40[', 'config[').replace('sharedData_800DFB7C_0_s00[idx].', 'particle->')
    quad = quad.replace('setPolyFT4(*poly);', '').replace('setSemiTrans(*poly, true);', '')
    replacements = {'scratch->field_0.field_2C': 'projection', 'scratch->field_138': 'depth',
                    'scratch->field_0.field_30.vx': 'pitch', 'scratch->field_134.vx': 'screen_x', 'scratch->field_134.vy': 'screen_y'}
    for old, new in replacements.items(): quad = quad.replace(old, new)
    quad = re.sub(r'func_80055D78\([^;]+?\)', 'illumination', quad)
    quad = quad.replace('Q12_MULT_PRECISE', 'sh_q12_mul').replace('FP_FROM', 'WATER_FROM').replace('FP_TO', 'WATER_TO')
    quad = quad.replace('Math_Sin', 'sh_fixed_sin').replace('Q12_SHIFT', '12').replace('ABS', 'abs')
    def xy(match):
        index, x, y = match.groups()
        return f'quad->x[{index}] = {x};\n    quad->y[{index}] = {y};'
    quad = re.sub(r'setXY([0-3])Fast\(\*poly, ([^,;]+), ([^;]+)\);', xy, quad)
    quad = re.sub(r'\*\(u32\*\)&\(\*poly\)->u([01]) = ([^;]+);', r'const uint32_t packed\1 = \2;', quad)
    quad = re.sub(r'\*\(u16\*\)&\(\*poly\)->u([23]) = ([^;]+);', r'const uint16_t packed\1 = \2;', quad)
    quad = quad.replace('setRGB0Fast(*poly, rgbColor, rgbColor, rgbColor);', 'quad->shade = rgbColor;')
    quad = re.sub(r'\b(' + '|'.join(primitive) + r')\b', lambda m: primitive[m[0]], quad)
    assert not re.search(r'\b(?:scratch|sharedData_|func_|Math_|poly|setXY)\w*', quad), quad
    spray += ['void sh_water_spray_quad(const ShWaterParticle *particle, const ShWaterSprayConfig *config,',
              '                          int screen_x, int screen_y, int depth, int projection,',
              '                          int pitch, int illumination, ShWaterSprayQuad *quad)', '{',
              '    const int idx2 = particle->field_10.s_2.field_0;', '    int32_t var_lo, var_a2, var_a1, rgbColor;', quad,
              '    const uint32_t packed[4] = {packed0, packed1, packed2, packed3};',
              '    for (int i = 0; i < 4; i++) { quad->u[i] = packed[i] & 255; quad->v[i] = (packed[i] >> 8) & 255; }',
              '    quad->clut = packed0 >> 16;', '    quad->page = packed1 >> 16;', '}']
    return {'include/sh3ds/water_types.h': '\n'.join(line.rstrip() for line in types) + '\n',
            'source/game/water_spawn.h': '\n'.join(line.rstrip() for line in steps) + '\n',
            'source/game/water_motion.h': '\n'.join(line.rstrip() for line in update) + '\n',
            'source/game/water_spray.h': '\n'.join(line.rstrip() for line in spray) + '\n'}


if __name__ == '__main__':
    for name, text in outputs().items():
        path = ROOT / name
        if '--check' in sys.argv: assert path.read_text(encoding='ascii') == text
        else: path.write_text(text, encoding='ascii', newline='\n')
    if '--check' in sys.argv: print('PASS: original water layouts, both valve configurations and particle spawn assignments')
