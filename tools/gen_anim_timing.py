"""Preserve original animation loop/blend timing; expose its skeleton sample."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/anim_timing_steps.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/bodyprog/world/bodyprog_anim_800445A4.c').read_text(encoding='utf-8'))
    lines = ['/* Generated by tools/gen_anim_timing.py from original animation timing. */']
    for name, native in [('Anim_PlaybackLoop', 'sh_anim_loop_timing'), ('Anim_BlendLinear', 'sh_anim_blend_timing'),
                         ('Anim_PlaybackOnce', 'sh_anim_once_timing')]:
        code = function(source, name)
        code = re.sub(r'\bs32\b|\bq19_12\b', 'int32_t', code)
        code = re.sub(r'\s*int32_t timestep;', '', code)
        code = re.sub(r'\s*timestep = Anim_TimestepGet\(model, animInfo\);', '', code)
        code = code.replace('animInfo->startKeyframeIdx', 'clip->first').replace('animInfo->endKeyframeIdx', 'clip->last').replace('animInfo->linkStatus', 'clip->link')
        for old, new in [('keyframeIdx', 'keyframe'), ('status', 'status'), ('time', 'time'), ('alpha', 'alpha')]:
            code = code.replace('model->anim.' + old, 'model->' + new)
        code = code.replace('NO_VALUE', '-1')
        code = re.sub(r'Q12\(([^)]+)\)', r'SH_Q12(\1)', code)
        code = code.replace('FP_FROM(newTime, Q12_SHIFT)', '(newTime >> 12)').replace('Q12_FRACT(newTime)', '(newTime & 4095)')
        pattern = r'if \(\(model->anim.flags & AnimFlag_Unlocked\) \|\| \(model->anim.flags & AnimFlag_Visible\)\)\s*\{\s*Anim_BoneUpdate\(anmHdr, boneCoords, (\w+), (\w+(?: \+ 1)?), alpha\);\s*\}'
        code, count = re.subn(pattern, r'pose->first = \1;\n    pose->second = \2;\n    pose->alpha = alpha;', code)
        assert count == 1 and 'model->anim' not in code and 'Anim_' not in code
        lines += [f'void {native}(ShAnimTiming *model, const ShAnimClipTiming *clip,',
                  '                         int32_t timestep, ShAnimPoseTiming *pose)', '{', code, '}']
    return '\n'.join(line.rstrip() for line in lines) + '\n'


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original loop, linear blend and once playback timing expressions')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
