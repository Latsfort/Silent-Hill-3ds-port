"""Extract piano hitboxes, sounds and solution from source and verified overlay."""
from pathlib import Path
import hashlib
import re
import struct
import sys

import gen_map_data as g
from gen_school_smoke import function

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    source = (DECOMP / 'src/maps/map1_s01/map1_s01.c').read_text(encoding='utf-8')
    body = function(g.strip_comments(source), 'PianoPuzzle_Control')
    config = (DECOMP / 'configs/USA/maps/map1_s01.yaml').read_text(encoding='utf-8')
    overlay = (ROOT / 'dump/assets/VIN/MAP1_S01.BIN').read_bytes()
    assert hashlib.sha1(overlay).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / 'configs/USA/maps/sym.map1_s01.txt').read_text(encoding='utf-8')

    def array(name):
        address, size = re.search(r'^' + name + r'\s*=\s*(0x[\dA-Fa-f]+); // type:s8 size:(0x[\dA-Fa-f]+)', symbols, re.M).groups()
        return struct.unpack_from(f'{int(size, 16)}b', overlay, int(address, 16) - base)

    keys, sequence = array('g_PianoKeys'), array('g_PianoKeySequence')
    lower = body.split('if (FP_FROM(g_PianoCursorY, Q12_SHIFT) >=', 1)[1].split('else\n        {', 1)[0]
    split_y = int(re.match(r' (\d+)', lower)[1])
    low_keys = re.findall(r'curCursorX < (-?\d+)\)\s*\{\s*keyIdx = (\d+)', lower)
    notes = body.split('switch (keyIdx)', 1)[1].split('switch (keyIdx)', 1)[0]
    entries = re.findall(r'case (\d+):\s*SysWork_StateStepSet\(1, (\d+)\);\s*SD_Call\((\w+)\);\s*g_PianoCursorX = Q12\(([-\d.]+)f\);', notes)
    assert len(keys) == 11 and len(sequence) == 5 and len(entries) == 12 and len(low_keys) == 6
    wrong = [int(v) for v in re.findall(r'case (\d+):', body.split('switch (keyIdx)', 2)[2].split('default:', 1)[0])]
    limits = re.findall(r'CLAMP_RANGE\(g_PianoCursor[XY], Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\)', body)
    waits = re.findall(r'sysStateSteps\[1\] == (\d+)\)\s*\{\s*Event_WaitTimer\(Q12\(([-\d.]+)f\)', body)
    assert len(limits) == 2 and len(waits) == 3
    lines = ['/* Generated by tools/gen_school_piano.py from PianoPuzzle_Control and verified MAP1_S01. */',
             'static const int8_t s_piano_keys[] = {' + ', '.join(map(str, keys)) + '};',
             'static const int8_t s_piano_sequence[] = {' + ', '.join(map(str, sequence)) + '};',
             'static const ShPianoLowerKey s_piano_lower[] = {']
    lines += [f'    {{{x}, {key}}},' for x, key in low_keys]
    lines += ['};', 'static const ShPianoNote s_piano_notes[] = {']
    for index, step, sound, snap in entries:
        lines.append(f'    {{{step}, {g.value(sound)}, {int(float(snap) * 4096)}, {str(int(index) in wrong).lower()}}},')
    lines += ['};', 'static const int32_t s_piano_limits[2][2] = {']
    lines += ['    {' + ', '.join(str(int(float(v) * 4096)) for v in pair) + '},' for pair in limits]
    lines += ['};', 'static const int32_t s_piano_waits[] = {']
    lines += [f'    [{step}] = {int(struct.unpack("<f", struct.pack("<f", float(value)))[0] * 4096)},' for step, value in waits]
    lines += ['};', f'#define SH_PIANO_SPLIT_Y {split_y}',
              f'#define SH_PIANO_MISS_SOUND {g.value(re.search(r"sysStateSteps\[1\] == 4\).*?SD_Call\((\w+)\)", body, re.S)[1])}', '']
    reference = g.strip_comments(body)
    for token in set(re.findall(r'\b(?:Sfx_\w+|EventFlag_\w+)\b', reference)):
        reference = re.sub(r'\b' + token + r'\b', str(g.value(token)), reference)
    cursor = [int(v) for v in re.search(r'Gfx_CursorDraw\(cursorX, cursorY, ([^;]+)\);', body)[1].split(',')]
    assert len(cursor) == 10
    hx, hy, u, v, width, height, tint, clut_x, clut_y, page = cursor
    world = (DECOMP / 'src/bodyprog/world/world_draw.c').read_text(encoding='utf-8')
    loader = function(g.strip_comments(world), 'GameFs_BgEtcGfxLoad')
    assert re.search(r'\.tPage = \{ 0, ' + str(page) + r' \}, \.clutX = ' + str(clut_x), loader)
    assert 'FILE_TIM_BG_ETC_TIM' in loader and 'setSemiTrans(poly, false)' in (DECOMP / 'src/bodyprog/events/events_2d_draw_utils.c').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/TIM/BG_ETC.TIM').read_bytes()
    assert (ROOT / 'romfs/game/tim/BG_ETC.TIM').read_bytes() == raw
    assert struct.unpack_from('<II', raw) == (16, 8)
    clut_size, _, _, colors, rows = struct.unpack_from('<I4H', raw, 8)
    _, _, _, word_width, image_height = struct.unpack_from('<I4H', raw, 8 + clut_size)
    assert clut_y < rows and u + width <= word_width * 4 and v + height <= image_height and tint == 128
    render = ['/* Generated: PianoPuzzle_Control cursor and GameFs_BgEtcGfxLoad. */', '#pragma once']
    render += [f'#define SH_PIANO_CURSOR_{name} {value}' for name, value in
               dict(HALF_X=hx, HALF_Y=hy, U=u, V=v, WIDTH=width, HEIGHT=height,
                    CLUT_OFFSET=clut_y * colors, TIM_SIZE=len(raw)).items()]
    joy = (DECOMP / 'src/bodyprog/sys/joy.c').read_text(encoding='utf-8')
    joy_header = (DECOMP / 'include/bodyprog/sys/joy.h').read_text(encoding='utf-8')
    deadzone = float(re.search(r'#define STICK_DEADZONE\s+FP_STICK\(([-\d.]+)f\)', joy_header)[1])
    digital = int(re.search(r'normalizedAnalogData = processedInputFlags \| 0x([\dA-F]+);', joy)[1], 16) >> 24
    loop = (DECOMP / 'src/bodyprog/sys/game_main.c').read_text(encoding='utf-8')
    hblanks = int(re.search(r'#define H_BLANKS_PER_SECOND\s+(\d+)', loop)[1])
    assert '#define STICK_DEADZONE' in joy_header and 'Q8(analog) / 2' in (DECOMP / 'include/bodyprog/math/fixed_point.h').read_text(encoding='utf-8')
    f32 = lambda value: struct.unpack('<f', struct.pack('<f', value))[0]
    acceleration = float(re.search(r'#define H_BLANKS_GRAVITY_SCALE\s+Q12\(([-\d.]+)f \* H_BLANKS_TO_SEC_CONVERSION_FACTOR\)', loop)[1])
    gravity = int(f32(f32(acceleration) * f32(4096 / hblanks)) * 4096)
    adapter = ['/* Generated: joy.c normalized sticks and game_main.c gravity. */', '#pragma once',
               f'#define SH_PIANO_STICK_DEADZONE {int(deadzone * 256) // 2}',
               f'#define SH_PIANO_DIGITAL_STICK {digital}', f'#define SH_PIANO_HBLANKS {hblanks}',
               f'#define SH_PIANO_GRAVITY_SCALE {gravity}']
    return {ROOT / 'source/game/school_piano_data.h': '\n'.join(lines),
            ROOT / 'include/sh3ds/piano_adapter_data.h': '\n'.join(adapter + ['']),
            ROOT / 'include/sh3ds/piano_render_data.h': '\n'.join(render + ['']),
            ROOT / 'tools/school_piano_reference.h': '/* Generated retail PianoPuzzle_Control, unchanged control flow. */\nstatic void reference_control(bool playNote)\n{\n' + reference + '\n}\n'}


if __name__ == '__main__':
    for path, data in outputs().items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='ascii') == data, path
        else:
            path.write_text(data, encoding='ascii', newline='\n')
    if '--check' in sys.argv:
        print('PASS: piano keys, solution, cursor bounds, sounds and delays match retail source/overlay')
