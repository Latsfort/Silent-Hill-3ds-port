"""Extract MAP0_S00 camera roads, checking every packed field against the retail ROM."""
from pathlib import Path
import hashlib
import re
import struct
import sys
from gen_vc_roads import parse

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/alley_camera_data.h'


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def emit():
    raw = (ROOT / 'dump/assets/VIN/MAP0_S00.BIN').read_bytes()
    config = (DECOMP / 'configs/USA/maps/map0_s00.yaml').read_text()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    roads = parse((DECOMP / 'src/maps/map0_s00/vc_road_data.h').read_text())
    q4 = lambda value: int(f32(value) * 16)
    start = raw.find(struct.pack('<8h', *map(q4, roads[0]['sw'] + roads[0]['rd'])))
    assert start >= 0
    lines = ['/* Generated by tools/gen_alley_camera.py; all fields checked against MAP0_S00. */',
             'static const ShVcRoad s_alley_camera_roads[] = {']
    count = 0
    number = lambda value: f'{value:.8f}f'
    for index, source in enumerate(roads):
        record = raw[start + index * 24:start + (index + 1) * 24]
        boxes = struct.unpack_from('<8h', record)
        assert boxes == tuple(map(q4, source['sw'] + source['rd'])), index
        flags, kinds, high, low, watch, camera, ax, ay = struct.unpack_from('<BBbbbBBB', record, 16)
        assert (flags, kinds & 3, (kinds >> 2) & 7, kinds >> 5) == (
            source['flags'], source['area'], source['rd_type'], source['mv_y']), index
        assert (high, low, watch, camera >> 4) == (
            q4(source['max_hy']), q4(source['min_hy']), q4(source['ofs_watch_hy']), source['cam_mv']), index
        angle = lambda value: min(255, max(0, int(f32(f32(value) / 360.0) * 256)))
        assert (ax, ay) == (angle(source['fix_x']), angle(source['fix_y'])), index
        if flags & 1:
            assert index == len(roads) - 1
            continue
        values = [flags, kinds & 3, (kinds >> 2) & 7, kinds >> 5]
        lines.append('    {{' + ', '.join(number(v / 16) for v in boxes[:4]) + '}, {' +
                     ', '.join(number(v / 16) for v in boxes[4:]) + '}, ' +
                     ', '.join(map(str, values)) + ', ' +
                     ', '.join(number(v / 16) for v in (high, low, watch)) + ', ' +
                     str(camera >> 4) + ', ' + number(ax * 360 / 256) + ', ' + number(ay * 360 / 256) + '},')
        count += 1
    assert count > 0
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: all opening camera road fields match the SHA1-verified retail overlay')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
