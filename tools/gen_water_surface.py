"""Extract the original continuous water strips before GPU projection."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/water_surface_steps.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/particle_water.c').read_text(encoding='utf-8'))
    body = function(source, 'sharedFunc_800CCE60_1_s02')
    fields = body[body.index('q3_12           field_25C;'):body.index('} s_func_800CCE60;')]
    point_count = int(re.search(r'field_23C\[(\d+)\]', body)[1])
    code = body[body.index('sp14 = 0;'):body.index('GsOUT_PACKET_P =')]
    code = code.replace('poly = (POLY_GT4*)GsOUT_PACKET_P;', '')
    start = code.index('Math_SetSVectorFastSum')
    stop = code.index('gte_stsz(&ptr->field_1BC[j][k]);', start) + len('gte_stsz(&ptr->field_1BC[j][k]);')
    code = code[:start] + 'scratch.position[j][k][0] = var_fp;\n                scratch.position[j][k][1] = sp18;\n                scratch.position[j][k][2] = sp1C;' + code[stop:]
    start = code.index('setPolyGT4(poly);')
    stop = code.index('poly++;', start) + len('poly++;')
    draw = code[start:stop]
    packed = re.findall(r'\*\((s32|u16)\*\)&poly->u([0-3]) = ([^;]+);', draw)
    assert len(packed) == 4
    output = ['if (count < capacity && out) {', '    ShWaterSurfaceQuad *quad = &out[count++];',
        '    for (int corner = 0; corner < 4; corner++) {',
        '        const int row = k + (corner >> 1), edge = corner & 1;',
        '        for (int axis = 0; axis < 3; axis++) { quad->position[corner][axis] = scratch.position[row][edge][axis]; }',
        '        quad->shade[corner] = scratch.field_23C[row][edge];', '    }']
    output += [f'    const {"uint32_t" if kind == "s32" else "uint16_t"} packed{index} = {expr};' for kind, index, expr in packed]
    output += ['    const uint32_t uv[4] = {packed0, packed1, packed2, packed3};',
        '    for (int corner = 0; corner < 4; corner++) { quad->u[corner] = uv[corner]; quad->v[corner] = uv[corner] >> 8; }',
        '    quad->clut = packed0 >> 16; quad->page = packed1 >> 16;', '}']
    code = code[:start] + '\n'.join(output) + code[stop:]
    code = code.replace('sharedData_800E30C8_1_s02.', 'config->').replace('ptr->field_0.field_30.vy', 'yaw')
    code = re.sub(r'ptr->(field_\w+)', r'scratch.\1', code)
    code = code.replace('func_80055D78(var_fp, sp18, sp1C)', 'sh_env_light_intensity(environment, light, (const int32_t[3]){var_fp, sp18, sp1C})')
    code = code.replace('Math_Sin', 'sh_fixed_sin').replace('Math_Cos', 'sh_fixed_cos')
    code = code.replace('Q12_MULT_PRECISE', 'sh_q12_mul').replace('Q12_MULT', 'sh_q12_mul').replace('g_DeltaTime', 'dt')
    code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
    code = code.replace('Q12(', 'SURFACE_Q12(')
    for old, new in [('q3_12', 'int16_t'), ('s16', 'int16_t'), ('u16', 'uint16_t')]:
        fields = re.sub(r'\b' + old + r'\b', new, fields)
    assert not re.search(r'\b(?:ptr|poly|gte_|Math_|Q12_|g_|sharedData_|GsOUT)\w*', code), code
    lines = ['/* Generated by tools/gen_water_surface.py from sharedFunc_800CCE60_1_s02. */',
        'size_t sh_water_surface(ShWaterConfig *config, int yaw, const ShEnvState *environment,',
        '    const ShEnvLight *light, ShWaterSurfaceQuad *out, size_t capacity, int32_t dt)', '{',
        '    if (!config || !environment || config->field_78 > 3) { return 0; }',
        '    for (int stream = 0; stream < config->field_78; stream++) {',
        f'        if (config->field_44[stream] <= 0 || config->field_28[stream] <= 0 || (config->field_28[stream] + config->field_44[stream] - 1) / config->field_44[stream] + 2 > {point_count}) {{ return 0; }}',
        '    }', '    size_t count = 0;', '    struct {', fields,
        f'        int32_t position[{point_count}][2][3];', f'        uint8_t field_23C[{point_count}][2];',
        '    } scratch = {0};',
        '    int32_t sp14, sp18, sp1C, i, temp_lo_3, temp_s0, temp_v0_8, temp_v1_3;',
        '    int32_t var_s2, var_s4, var_fp, k, var_t2_2, var_t3_2, j;', code, '    return count;', '}', '']
    return '\n'.join(line.rstrip() for line in '\n'.join(lines).split('\n'))


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: source continuous water positions, shades, clipped UVs and scroll timers')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
    points = int(re.search(r'position\[(\d+)\]', data)[1])
    types = (ROOT / 'include/sh3ds/water_types.h').read_text(encoding='ascii')
    streams = int(re.search(r'field_0\[(\d+)\]', types)[1]) - 1
    limits = f'/* Generated from original water arrays and scratch rows. */\n#pragma once\n#define SH_WATER_SURFACE_MAX_QUADS {streams * (points - 1)}\n'
    limits_path = ROOT / 'include/sh3ds/water_surface_data.h'
    if '--check' in sys.argv: assert limits_path.read_text(encoding='ascii') == limits
    else: limits_path.write_text(limits, encoding='ascii', newline='\n')
