"""Extract Harry's default collision radius and its retail Q12-to-Q8 conversion."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'include/sh3ds/player_collision_data.h'


def emit():
    player = g.strip_comments((DECOMP / 'src/bodyprog/player_control.c').read_text(encoding='utf-8'))
    collision = g.strip_comments((DECOMP / 'src/bodyprog/collision/collision.c').read_text(encoding='utf-8'))
    radius = re.search(r'collision\.cylinder\.radius\s*=\s*Q12\(([-\d.]+)f\)', function(player, 'Game_PlayerInfoInit'))[1]
    assert 'charaState->radius         = Q12_TO_Q8(cylinder->radius);' in collision
    q8 = fixed(radius) >> 4
    return ('/* Generated by tools/gen_player_collision.py; Game_PlayerInfoInit and collision.c. */\n'
            '#pragma once\n' + f'#define SH_COLL_PLAYER_RADIUS {q8 / 256:.8f}f\n')


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original Harry collision radius with Q12-to-Q8 truncation')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
