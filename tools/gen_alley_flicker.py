"""Extract original alley lighter-environment flicker and its ROM initial state."""
import hashlib
from pathlib import Path
import re
import struct
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/alley_flicker_data.h'


def emit():
    config = (DECOMP / 'configs/USA/maps/map0_s00.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP0_S00.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    source = g.strip_comments((DECOMP / 'src/maps/map0_s00/map0_s00_2.c').read_text(encoding='utf-8'))
    body = function(source, 'func_800DD0CC')
    names = re.findall(r'\bD_[0-9A-F]+', body)
    assert len(set(names)) == 3
    value_name, phase_name, rate_name = sorted(set(names))
    address = lambda name: int(name[2:], 16) - base
    value = struct.unpack_from('<i', raw, address(value_name))[0]
    phase = struct.unpack_from('<2h', raw, address(phase_name))
    rate = struct.unpack_from('<3B', raw, address(rate_name))
    call = re.search(r'Gfx_MapEnvUpdate\([^;]+;', body)[0]
    assert re.sub(r'\s+', '', call) == f'Gfx_MapEnvUpdate(6,6,PrimitiveType_S32,&{value_name},0,Q12(100.0f));'
    body = body.replace(call, 'sh_env_transition_begin(environment, 6, 6);')
    for old, new in ((value_name, 'state->value'), (phase_name, 'state->phase'), (rate_name, 'state->rate'),
                     ('NO_VALUE', '-1'), ('g_DeltaTime', 'delta'), ('Rng_GenerateUInt', 'flicker_random'),
                     ('FP_MULTIPLY', 'FLICKER_MULT'), ('Q12_MULT', 'sh_q12_mul'),
                     ('Q12_FRACT', 'flicker_fraction'), ('Math_Sin', 'sh_fixed_sin'), ('MAX(', 'FLICKER_MAX('), ('s32', 'int32_t')):
        body = body.replace(old, new)
    body = re.sub(r'Q12\(([-\d.]+)f?\)', lambda m: str(fixed(m[1])), body)
    assert not re.search(r'\b(?:g_|D_800|Q12|Rng_)\w*', body)
    lines = ['/* Generated by tools/gen_alley_flicker.py; func_800DD0CC and SHA1-verified MAP0_S00. */',
             'static const ShAlleyFlicker s_flicker_initial = {' + str(value) + ', {' + ', '.join(map(str, phase)) + '}, {' + ', '.join(map(str, rate)) + '}};',
             'static void flicker_step(ShAlleyFlicker *state, ShEnvironment *environment, int32_t delta)', '{', body, '}', '']
    return '\n'.join(line.rstrip() for line in '\n'.join(lines).split('\n'))


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original lighter environment flicker and verified ROM initial state')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
