"""Extract piano medallion motion constants and source comparison functions."""
from pathlib import Path
import hashlib
import re
import struct
import sys

import gen_map_data as g
from gen_school_smoke import function

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def fixed(value, angle=False):
    value = struct.unpack('<f', struct.pack('<f', float(value.rstrip('f'))))[0]
    if angle:
        value = struct.unpack('<f', struct.pack('<f', value / 360.0))[0]
    return int(value * 4096)


def outputs():
    source = g.strip_comments((DECOMP / 'src/maps/map1_s01/map1_s01.c').read_text(encoding='utf-8'))
    body = function(source, 'MapEvent_PianoPuzzleInteract')
    cases = {n: body.split(f'case {n}:', 1)[1].split('break;', 1)[0] for n in (12, 13)}
    constants = {}
    for n, code in cases.items():
        for angle, value in re.findall(r'Q12(_ANGLE)?\(([-\d.]+)f\)', code):
            constants[(angle, value)] = fixed(value, bool(angle))
    config = (DECOMP / 'configs/USA/maps/map1_s01.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP1_S01.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / 'configs/USA/maps/sym.map1_s01.txt').read_text(encoding='utf-8')
    velocity_name = re.search(r'(D_[\dA-F]+)\s*\+= g_GravitySpeed', cases[13])[1]
    address = int(velocity_name.removeprefix('D_'), 16)
    offset = int(re.search(r'PA: (0x[\dA-Fa-f]+)\s+VA: 0x' + f'{address:X}' + r'\s+subsegment: data', symbols)[1], 16)
    assert address - base == offset
    velocity = struct.unpack_from('<i', raw, address - base)[0]
    init = re.findall(r'WorldObject_Init\(&g_WorldObject_SilverH, "SILVER_H", ([^)]+)\)', source)
    assert len(init) == 2
    lines = ['/* Generated by tools/gen_silver_motion.py; original PS1 Q12 axes/angles. */']
    for index, coords in enumerate(init):
        values = coords.split(', ')
        assert len(values) == 6 and fixed(values[-1], True) == 0
        position = ', '.join(str(fixed(v)) for v in values[:3])
        angles = ', '.join(str(fixed(v, True)) for v in values[3:5])
        lines.append(f'static const ShSilverMotion s_silver_{"hanging" if index == 0 else "ground"} = {{{{{position}}}, {{{angles}}}, {velocity}}};')
    def constant(pattern, n):
        angle, value = re.search(pattern, cases[n]).groups()
        return fixed(value, bool(angle))
    patterns = {
        'SWING_SPEED': (r'rotation.vx \+= Q12_MULT_PRECISE\(g_DeltaTime, Q12(_ANGLE)?\(([-\d.]+)f\)', 12),
        'SWING_RADIUS': (r'Math_Cos\([^)]*\) \* Q12(_ANGLE)?\(([-\d.]+)f\)', 12),
        'SWING_Y': (r'Q12_SHIFT\) - Q12(_ANGLE)?\(([-\d.]+)f\)', 12),
        'SWING_Z': (r'Q12_SHIFT\) \+ Q12(_ANGLE)?\(([-\d.]+)f\)', 12),
        'FALL_SPEED': (r'rotation.vx \+= Q12_MULT_PRECISE\(g_DeltaTime, Q12(_ANGLE)?\(([-\d.]+)f\)', 13),
        'DRIFT_SPEED': (r'position.vz \+= Q12_MULT_PRECISE\(g_DeltaTime, Q12(_ANGLE)?\(([-\d.]+)f\)', 13),
    }
    lines += [f'#define SH_SILVER_{name} {constant(pattern, n)}' for name, (pattern, n) in patterns.items()]
    ref = ['/* Generated from MapEvent_PianoPuzzleInteract cases 12 and 13. */']
    ref += ['static void reference_swing(void) {', cases[12], '}',
            'static void reference_fall(void) {', cases[13].replace('Sfx_Unk1417', str(g.value('Sfx_Unk1417'))), '}']
    return {ROOT / 'source/game/silver_motion_data.h': '\n'.join(lines + ['']),
            ROOT / 'tools/silver_motion_reference.h': '\n'.join(ref + [''])}


if __name__ == '__main__':
    for path, data in outputs().items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='ascii') == data, path
        else:
            path.write_text(data, encoding='ascii', newline='\n')
    if '--check' in sys.argv:
        print('PASS: silver initial velocity/poses and swing/fall constants match original overlay and C')
