"""Extract the original piano event's camera, warp, messages, fades and waits."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s01/map1_s01.c'
OUTPUT = ROOT / 'source/game/piano_scene_data.h'


def emit():
    body = function(g.strip_comments(SOURCE.read_text(encoding='utf-8')), 'MapEvent_PianoPuzzleInteract')
    events = g.load_events('map1_s01')
    event = next(e for e in events if e['func'] == 'MapEvent_PianoPuzzleInteract')
    assert event['transition_flags'] == 0
    lines = ['/* Generated by tools/gen_piano_scene.py from MapEvent_PianoPuzzleInteract. */',
             f'#define SH_PIANO_CALLBACK {event["event_param"]}']
    flag = re.search(r'Event_SysStateBranchOnFlag\((\w+),', body)[1]
    sound = re.search(r'SD_Call\((\w+)\)', body)[1]
    lines += [f'#define SH_PIANO_SOLVED_FLAG {g.value(flag)}', f'#define SH_PIANO_FALL_SOUND {g.value(sound)}']
    def case(number):
        return body.split(f'case {number}:', 1)[1].split('break;', 1)[0]
    for command, name in [('CameraPosition', 'camera'), ('CameraLookAt', 'look')]:
        vectors = re.findall(r'Event_' + command + r'Set\(NULL,\s*Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\)', body)
        assert len(vectors) == 2
        lines.append(f'static const float s_piano_{name}[2][3] = {{')
        for xyz in vectors:
            values = [fixed(v) / 4096 for v in xyz]
            values[1], values[2] = -values[1], -values[2]
            lines.append('    {' + ', '.join(f'{v:.8f}f' for v in values) + '},')
        lines.append('};')
    warp = case(11)
    x = re.search(r'position.vx = Q12\(([-\d.]+)f\)', warp)[1]
    z = re.search(r'position.vz = Q12\(([-\d.]+)f\)', warp)[1]
    yaw = re.search(r'rotation.vy = Q12_ANGLE\(([-\d.]+)f\)', warp)[1]
    lines += [f'static const float s_piano_player[2] = {{{fixed(x) / 4096:.8f}f, {-fixed(z) / 4096:.8f}f}};',
              f'#define SH_PIANO_PLAYER_YAW {-fixed(yaw, True) * 6.283185307179586 / 4096:.10f}f',
              'static const int32_t s_piano_scene_waits[16] = {']
    for number in (11, 12, 14, 15):
        wait = re.search(r'Event_WaitTimer\(Q12\(([-\d.]+)f\)', case(number))[1]
        lines.append(f'    [{number}] = {fixed(wait)},')
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: piano scene cameras, player warp, waits, callback/flag and sound match retail')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
