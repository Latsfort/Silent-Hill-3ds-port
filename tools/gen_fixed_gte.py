"""Extract PsyQ atan/root tables from SHA1-verified retail BODYPROG."""
import hashlib
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/fixed_gte_data.h'


def retail():
    config = (DECOMP / 'configs/USA/bodyprog.yaml').read_text(encoding='utf-8')
    data = (ROOT / 'dump/assets/1ST/BODYPROG.BIN').read_bytes()
    assert hashlib.sha1(data).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    vram = int(re.search(r'    vram: (0x[\da-fA-F]+)', config)[1], 16)
    text = (DECOMP / 'configs/USA/sym.bodyprog.txt').read_text(encoding='utf-8')
    symbols = {name: int(value, 16) for name, value in re.findall(r'^(\w+)\s*=\s*(0x[\da-fA-F]+)', text, re.M)}
    return data, vram, symbols


def emit():
    data, vram, symbols = retail()
    lines = ['/* Generated by tools/gen_fixed_gte.py - do not edit. */',
             '/* SHA1-verified BODYPROG: libgte/ratan and libgte/sqrtbl. */']
    for symbol, count, name in (('ratan_tbl', 1025, 's_fixed_atan'), ('SQRT', 192, 's_fixed_sqrt')):
        values = struct.unpack_from(f'<{count}h', data, symbols[symbol] - vram)
        lines.append(f'static const int16_t {name}[] = {{')
        for first in range(0, count, 16):
            lines.append('    ' + ', '.join(map(str, values[first:first + 16])) + ',')
        lines.append('};')
    return '\n'.join(lines + [''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: 1025 atan entries and 192 root entries match the verified retail binary')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
