"""Adapt the unopened locker using the shared locker event conversion."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_locker_body import adapt

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_locker_open.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    name = 'MapEvent_UnopenedCatLockerInspect'
    body = function(source, name)
    code = body[body.index('if ((g_Controller0'):]
    for symbol, value in re.findall(r'(EventState_\w+)\s*=\s*(\d+)', body): code = code.replace(symbol, value)
    code = code.replace('(g_Controller0->buttonFlags.clicked & g_GameWorkPtr->config.controllerConfig.skip)', 'sh_input_down(input, KEY_START)')
    subs = {
        'ScreenFade_ResetTimestep()': 'locker_fade_reset(town)',
        'SysWork_StateStepSet(0, 13)': 'step_set(town, 13)',
        'Event_WaitPlayerStop()': 'step_set(town, town->step + 1)',
        'g_SysWork.playerWork.player.moveSpeed   = Q12(0.0f)': 'town->school.card_player.move_speed = Q12(0.0f)',
        'func_8003D03C()': '(town->school.empty_hand = true)',
        'func_8003D01C()': '(town->school.empty_hand = false)',
        'Player_EmptyWeaponHandSet()': '(town->school.empty_hand = true)',
        'Player_WeaponAttackRestore()': '(town->school.empty_hand = false)',
        'Event_ScreenFadeCmd(ScreenFadeCmd_Auto, true, 2, 0, false)': 'locker_border_in(town)',
        'Event_ScreenFadeCmd(ScreenFadeCmd_Start, false, 2, 0, false)': '(town->border.state = SH_BORDER_FADEOUTSTART)',
        'Event_ScreenFadeCmd(ScreenFadeCmd_Start, false, 0, 0, false)': 'fade_to(town, 0.0f, 0.0f)',
        'ScreenFade_IsFinished()': '(town->fade >= 1.0f)',
        'Event_CharaAnimCmdExecute(CharaAnimCmd_AnimReset, &g_SysWork.playerWork.player, 0, false)': 'locker_animation_reset(town)',
        'Event_BgTextureCmd(BgTextureCmd_Draw, 0, false)': '(town->school.image = "LOCKER1.TIM")',
    }
    for old, new in subs.items(): code = code.replace(old, new)
    code = re.sub(r'Event_CharaAnimPlayToEnd\(&g_SysWork.playerWork.player, (\d+)\)', r'card_animation(town, \1, dt)', code)
    code = re.sub(r'Event_CharaAnimCmdExecute\(CharaAnimCmd_SetState, &g_SysWork.playerWork.player, (\d+), false\)',
        r'locker_animation_start(town, \1)', code)
    code = re.sub(r'Event_DisplayMapMsg\(false, (\d+), 0, 0, 0, false\)', r'card_message(town, input, \1)', code)
    code = re.sub(r'Event_BgTextureFadeIn\(FILE_TIM_(\w+)_TIM, Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\)\)',
        r'locker_image_in(town, "\1.TIM", \2f, \3f)', code)
    code = re.sub(r'Event_BgTextureFadeOut\(Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\)\)', r'locker_image_out(town, \1f, \2f)', code)
    code = adapt(code)
    code = re.sub(r'(town->school.card_player.rotation.vy = -?\d+;)', r'\1\n            card_warp(town);', code)
    return '\n'.join(['/* Generated by tools/gen_locker_open.py from UnopenedCatLockerInspect. */',
        f'#define SH_SCHOOL_LOCKER_OPEN_CALLBACK {g.event_funcs("map1_s03").index(name)}',
        'static void locker_open_steps(ShTown *town, ShSavegame *save, const ShInputState *input, float dt)', '{', code, '}', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original unopened locker cases, skip branch, flags, cameras and messages')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
