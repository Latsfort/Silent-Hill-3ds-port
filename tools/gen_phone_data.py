"""Extract original phone message timers and animation event thresholds."""
from pathlib import Path
import ast
import json
import re
import sys
import gen_map_data as g
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/phone_data.h'


def emit():
    source = (ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s02/map1_s02.c').read_text(encoding='utf-8')
    raw_messages = source.split('const char* MAP_MESSAGES[] = {', 1)[1].split('};', 1)[0]
    messages = {int(index): ast.literal_eval(literal) for index, literal in
        re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', raw_messages)}
    lines = ['/* Generated by tools/gen_phone_data.py from MAP1_S02 messages and shared player states. */',
        '#pragma once', '#include "sh3ds/phone.h"',
        'static const ShPhonePage s_phone_pages[] = {']
    for index in range(31, 37):
        assert set(re.findall(r'~([A-Z])', messages[index])) <= set('JDNE')
        assert len(messages[index]) < 400 and messages[index].count('~N') < 9
        audio, duration = re.search(r'~J(\d)\(([-\d.]+)\)', messages[index]).groups()
        lines.append(f'    {{{index}, {fixed(duration)}, {int(audio) + 1}, {str("~E" in messages[index]).lower()}, {str("~D" in messages[index]).lower()}, {json.dumps(messages[index])}}},')
    lines += ['};']
    lines += ['static const ShPhonePage s_arrival_pages[] = {']
    for index in range(15, 18):
        assert set(re.findall(r'~([A-Z])', messages[index])) <= set('JDNE')
        assert '~E' in messages[index]
        audio, duration = re.search(r'~J(\d)\(([-\d.]+)\)', messages[index]).groups()
        lines.append(f'    {{{index}, {fixed(duration)}, {int(audio) + 1}, true, false, {json.dumps(messages[index])}}},')
    lines += ['};', 'static const ShPhonePage *school_timed_page(int index)', '{',
        '    for (unsigned i = 0; i < sizeof(s_phone_pages) / sizeof(s_phone_pages[0]); i++) {',
        '        if (s_phone_pages[i].message == index) { return &s_phone_pages[i]; }', '    }',
        '    for (unsigned i = 0; i < sizeof(s_arrival_pages) / sizeof(s_arrival_pages[0]); i++) {',
        '        if (s_arrival_pages[i].message == index) { return &s_arrival_pages[i]; }', '    }', '    return NULL;', '}']
    world = (ROOT / 'vendor/silent-hill-decomp/src/bodyprog/world/world_draw.c').read_text(encoding='utf-8')
    assert re.search(r'if \(heldItem->itemId == InvItemId_CutscenePhone\)\s*\{\s*coord = &g_SysWork.playerBoneCoords\[HarryBone_LeftHand\]', world)
    lines += [f'int sh_phone_held_bone(void) {{ return {g.value("HarryBone_LeftHand")}; }}']
    shared = (ROOT / 'vendor/silent-hill-decomp/include/maps/shared/sharedFunc_800CDAA8_0_s02.h').read_text(encoding='utf-8')
    pickup = shared.split('case PlayerState_Unk97:', 1)[1].split('break;', 1)[0]
    put_down = shared.split('case PlayerState_Unk98:', 1)[1].split('break;', 1)[0]
    flag_frame, flag = re.search(r'keyframeIdx >= (\d+)\)\s*\{\s*Savegame_EventFlagSet\((\w+)\)', pickup).groups()
    hidden_frame = re.search(r'keyframeIdx < (\d+)\)\s*\{\s*func_8003D03C', pickup)[1]
    returned_frame, returned_flag = re.search(r'keyframeIdx >= (\d+)\)\s*\{\s*Savegame_EventFlagClear\((\w+)\)', put_down).groups()
    assert flag == returned_flag
    lines += [f'#define SH_PHONE_PICKUP_STATE {g.value("PlayerState_Unk97")}',
        f'#define SH_PHONE_RETURN_STATE {g.value("PlayerState_Unk98")}',
        f'#define SH_PHONE_PICKUP_STATE_FLAG {g.value(flag)}',
        f'#define SH_PHONE_PICKUP_FLAG_FRAME {flag_frame}',
        f'#define SH_PHONE_HELD_VISIBLE_FRAME {hidden_frame}',
        f'#define SH_PHONE_RETURN_FLAG_FRAME {returned_frame}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: six original phone page timers/audio types/ends and player animation flag/visibility thresholds')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
