"""Extract MAP1_S03 text/rooms and adapt both original book switches."""
import ast
import hashlib
import json
from pathlib import Path
import re
import sys
import struct
import gen_map_data as g
import gen_common_pickups as pickups
import gen_vc_roads as cameras
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    name = 'map1_s03'
    raw_source = (DECOMP / f'src/maps/{name}/{name}.c').read_text(encoding='utf-8')
    source = g.strip_comments(raw_source)
    common = (DECOMP / 'include/maps/shared/map_msg_common.h').read_text(encoding='utf-8').split('#if VERSION_REGION_IS(NTSC)', 1)[1].split('#elif', 1)[0]
    messages = re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', common + raw_source.split('const char* MAP_MESSAGES[] = {', 1)[1].split('};', 1)[0])
    assert [int(index) for index, _ in messages] == list(range(len(messages)))
    data = ['/* Generated by tools/gen_school_roof.py from MAP1_S03. */', '#pragma once',
            'static const ShSchoolMessage s_school_roof_messages[] = {']
    for index, literal in messages:
        raw = ast.literal_eval(literal)
        text = re.sub(r'~[A-Z]\d*(?:\([^)]*\))?', '', raw.replace('~N', '\x01')).replace('_', ' ')
        text = '\n'.join(' '.join(line.split()) for line in text.split('\x01'))
        data.append(f'    [{index}] = {{{json.dumps(text)}, {str("~E" in raw or "~S" in raw).lower()}}},')
    config = (DECOMP / f'configs/USA/maps/{name}.yaml').read_text(encoding='utf-8')
    overlay = (ROOT / 'dump/assets/VIN/MAP1_S03.BIN').read_bytes()
    assert hashlib.sha1(overlay).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / f'configs/USA/maps/sym.{name}.txt').read_text(encoding='utf-8')
    address_of = lambda symbol: int(re.search(r'^' + symbol + r'\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    mapping = list(struct.iter_unpack('<4h', overlay[address_of('g_MapHeaderTable_38') - base:address_of('LOADABLE_INVENTORY_ITEMS') - base]))
    other_config = (DECOMP / 'configs/USA/maps/map1_s02.yaml').read_text(encoding='utf-8')
    other_raw = (ROOT / 'dump/assets/VIN/MAP1_S02.BIN').read_bytes()
    assert hashlib.sha1(other_raw).hexdigest() == re.search(r'^sha1: (\w+)', other_config, re.M)[1]
    other_base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', other_config)[1], 16)
    other_symbols = (DECOMP / 'configs/USA/maps/sym.map1_s02.txt').read_text(encoding='utf-8')
    other_address = lambda symbol: int(re.search(r'^' + symbol + r'\s*=\s*(0x[\dA-Fa-f]+)', other_symbols, re.M)[1], 16)
    other_mapping = list(struct.iter_unpack('<4h', other_raw[other_address('g_MapHeaderTable_38') - other_base:other_address('LOADABLE_INVENTORY_ITEMS') - other_base]))
    shared = (DECOMP / 'include/maps/shared/sharedFunc_800CDAA8_0_s02.h').read_text(encoding='utf-8')
    animation_source = (DECOMP / f'src/maps/{name}/{name}_anim_info.c').read_text(encoding='utf-8')
    other_animation = (DECOMP / 'src/maps/map1_s02/map1_s02_anim_info.c').read_text(encoding='utf-8')
    for state in (59, 60):
        state_code = shared.split(f'case PlayerState_Unk{state}:', 1)[1].split('break;', 1)[0]
        virtual, active = re.search(r'ANIM_STATUS\((\d+), (true|false)\)', state_code).groups()
        virtual_status = int(virtual) * 2 + (active == 'true')
        row = next(row for row in mapping if row[1] == virtual_status)
        assert row == next(row for row in other_mapping if row[1] == virtual_status)
        index = (row[0] & 255) >> 1
        pattern = r'\{[^{}]*ANIM_STATUS\(' + str(index) + r', (?:false|true)\)[^{}]*\{[^{}]*\}[^{}]*\}'
        normalize = lambda text: [' '.join(re.sub(r'Q12\(([-\d.]+)f?\)', lambda m: str(fixed(m[1])), s).split()) for s in re.findall(pattern, g.strip_comments(text))]
        assert normalize(animation_source) == normalize(other_animation) and len(normalize(animation_source)) == 2, (state, normalize(animation_source), normalize(other_animation))
    assert (ROOT / 'romfs/game/anim/HB_M1S03.ANM').read_bytes() == (ROOT / 'dump/assets/ANIM/HB_M1S03.ANM').read_bytes()
    address = int(re.search(r'^MAP_ROOM_IDXS\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    header = (DECOMP / f'include/maps/map1/{name}.h').read_text(encoding='utf-8')
    lower = (DECOMP / 'include/maps/map1/map1_s00.h').read_text(encoding='utf-8')
    bounds = lambda text: dict(re.findall(r'#define (MAP_ROOM_\w+) Q12\(([^)]+)\)', text))
    assert bounds(header) == bounds(lower)
    limits = {key: float(value.rstrip('f')) for key, value in bounds(header).items()}
    terrain = (DECOMP / 'include/bodyprog/map/terrain.h').read_text(encoding='utf-8')
    chunk = float(re.search(r'#define CHUNK_SIZE\s+([-\d.]+)f', terrain)[1])
    size = int((limits['MAP_ROOM_MAX_X'] - limits['MAP_ROOM_MIN_X']) / chunk) * int((limits['MAP_ROOM_MAX_Z'] - limits['MAP_ROOM_MIN_Z']) / chunk)
    rooms = overlay[address - base:address - base + size]
    assert len(rooms) == size
    data += ['};', 'static const uint8_t s_school_roof_rooms[] = {', '    ' + ', '.join(map(str, rooms)), '};', '']
    books = ['/* Generated by tools/gen_school_roof.py; original book switches retained. */']
    for retail, native, macro in [('MapEvent_TheMonsterLurksBookRead', 'roof_monster_book', 'MONSTER'),
                                   ('MapEvent_SplitHeadFairyTaleBookRead', 'roof_fairy_book', 'FAIRY'),
                                   ('MapEvent_RubberBallUse', 'roof_rubber_ball', 'BALL'),
                                   ('MapEvent_RoofDrainPuzzleInteract0', 'roof_drain_inspect0', 'DRAIN0'),
                                   ('MapEvent_RoofDrainPuzzleInteract1', 'roof_drain_inspect1', 'DRAIN1')]:
        code = function(source, retail)
        def sound(match):
            x, y, z = [fixed(v.strip().rstrip('f')) / 4096 for v in match[2].split(',')]
            return f'sh_snd_at({g.value(match[1])}, (const float[3]){{{x:.12f}f, {-y:.12f}f, {-z:.12f}f}}, 0.5f);'
        code = re.sub(r'Sfx_WithFlagsPlay\((\w+), &Q12_VECTOR3\(([^)]+)\), Q8\(0.5f\), SfxFlag_None\);', sound, code)
        code = re.sub(r'typedef enum _EventState\s*\{(.*?)\}\s*e_EventState;', r'enum {\1};', code, flags=re.S)
        code = code.replace('NO_VALUE', '-1')
        code = re.sub(r'Q12\(([-\d.]+)f\)', lambda m: str(fixed(m[1])), code)
        code = re.sub(r'\bEventFlag_\w+\b', lambda m: str(g.value(m[0])), code)
        code = code.replace('g_SysWork.sysStateSteps[0]', 'town->step')
        code = code.replace('g_MapEventData->mapPointIdx', 'town->school.ladder_point')
        code = code.replace('g_MapEventData->activationType', 'town->school.activation_type')
        code = code.replace('TriggerActivationType_Item', str(g.value('TriggerActivationType_Item')))
        code = code.replace('Player_ControlFreeze()', '(town->controls_locked = true)').replace('Player_ControlUnfreeze(false)', 'ladder_unfreeze(town)')
        code = code.replace('SysWork_StateSetNext(SysState_Gameplay)', 'finish(town)').replace('SysWork_StateStepIncrement(0)', 'step_set(town, town->step + 1)')
        code = code.replace('Event_WaitPlayerStop()', 'step_set(town, town->step + 1)')
        code = re.sub(r'Event_WaitTimer\((\d+), false\)', r'ladder_wait(town, dt, \1)', code)
        code = re.sub(r'Savegame_EventFlagSet\((\d+)\)', r'sh_save_event_set(save, \1)', code)
        code = re.sub(r'Savegame_EventFlagGet\((\d+)\)', r'sh_save_event_get(save, \1)', code)
        code = re.sub(r'Event_SysStateBranchOnFlag\((\d+), (\w+), (\w+), false\)', r'step_set(town, sh_save_event_get(save, \1) ? \2 : \3)', code)
        code = re.sub(r'Event_DisplayMapMsg\(false, (\d+), false, false, 0, false\)', r'card_message(town, input, \1)', code)
        code = re.sub(r'Event_DisplayMapMsg\(false, (\d+), 0, 0, 0, false\)', r'card_message(town, input, \1)', code)
        code = re.sub(r'Event_CharaAnimPlayToEnd\(&g_SysWork.playerWork.player, (\d+)\)', r'card_animation(town, \1, dt)', code)
        def image(match):
            assert (ROOT / f'romfs/game/tim/{match[1]}.TIM').is_file()
            return f'(town->school.next_image = "{match[1]}.TIM")'
        code = re.sub(r'Event_BgTextureCmd\((?:BgTextureCmd_QueueRead|false), FILE_TIM_(\w+)_TIM, false\)', image, code)
        code = code.replace('Event_BgTextureCmd(BgTextureCmd_AwaitLoad, 0, false)', 'step_set(town, town->step + 1)')
        code = code.replace('Event_BgTextureCmd(true, 0, false)', 'step_set(town, town->step + 1)')
        code = code.replace('Event_BgTextureCmd(BgTextureCmd_Draw, 0, false)', '(town->school.image = town->school.next_image)')
        code = re.sub(r'Event_ScreenFadeCmd\(ScreenFadeCmd_(Start|Wait|Auto), (true|false), (?:0|false), (?:0|false), false\)',
                      lambda m: f'ladder_fade(town, {dict(Start=0, Wait=1, Auto=2)[m[1]]}, {m[2]}, 0)', code)
        code = re.sub(r'(step_set\(town, town->step \+ 1\);)(\s+case \w+:)', r'\1\n        /* fall through */\2', code)
        assert not re.search(r'\b(?:Event_|Player_|SysWork_|Savegame_|g_)\w*', code), code
        books += [f'#define SH_SCHOOL_ROOF_{macro}_CALLBACK {g.event_funcs(name).index(retail)}',
                  f'static void {native}(ShTown *town, ShSavegame *save, const ShInputState *input, float dt)', '{',
                  '    town->school.image = NULL;', code, '}']
    return {'school_roof_data.h': '\n'.join(data), 'school_roof_books.h': '\n'.join(line.rstrip() for line in books) + '\n'}


if __name__ == '__main__':
    for name, text in outputs().items():
        path = ROOT / 'source/game' / name
        if '--check' in sys.argv: assert path.read_text(encoding='ascii') == text
        else: path.write_text(text, encoding='ascii', newline='\n')
    if '--check' in sys.argv:
        name = 'map1_s03'
        assert (ROOT / f'source/game/mapdata_{name}.h').read_text(encoding='ascii') == g.emit(name)
        assert (ROOT / f'source/game/map_pickups_{name}.h').read_text(encoding='ascii') == pickups.emit(name)
        roads = [r for r in cameras.parse((DECOMP / f'src/maps/{name}/vc_road_data.h').read_text(encoding='utf-8')) if not r['flags'] & 1]
        rows = re.findall(r'^    \{\{(.+)\},$', (ROOT / f'source/game/vc_roads_{name}.h').read_text(encoding='ascii'), re.M)
        assert len(rows) == len(roads)
        for text, road in zip(rows, roads):
            values = [int(v, 16) if v.startswith('0x') else float(v) for v in re.findall(r'0x[\dA-F]+|[-\d.]+', text)]
            expected = road['sw'] + road['rd'] + [road[k] for k in ('flags', 'area', 'rd_type', 'mv_y', 'max_hy', 'min_hy', 'ofs_watch_hy', 'cam_mv', 'fix_x', 'fix_y')]
            assert values == [round(v, 3) for v in expected]
        print('PASS: MAP1_S03 data and original switches for books, ball use and both drain inspections')
