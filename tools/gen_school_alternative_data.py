"""Extract MAP1_S02 messages and its verified retail room grid."""
import ast
import hashlib
import json
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/school_alternative_data.h'


def emit():
    map_name = 'map1_s02'
    source = (DECOMP / f'src/maps/{map_name}/{map_name}.c').read_text(encoding='utf-8')
    common = (DECOMP / 'include/maps/shared/map_msg_common.h').read_text(encoding='utf-8')
    common = common.split('#if VERSION_REGION_IS(NTSC)', 1)[1].split('#elif', 1)[0]
    literals = re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")',
                          common + source.split('const char* MAP_MESSAGES[] = {', 1)[1].split('};', 1)[0])
    pickup_calls = re.findall(r'void\s+(\w+)\(void\)[^{]*\{\s*Event_ItemTake\((\w+), DEFAULT_PICKUP_ITEM_COUNT, (\w+), (\d+)\);\s*\}', g.strip_comments(source))
    assert len(pickup_calls) == 2
    animated_pickups = []
    for name in ('func_800DBFC8', 'MapEvent_ClassroomKeyItemTake'):
        body = function(g.strip_comments(source), name)
        item, quantity = re.search(r'InvItemCmd_AddItem, (\w+), (\w+), false', body).groups()
        flag = re.search(r'Savegame_EventFlagSet\((\w+)\)', body)[1]
        msg, accept, decline = re.search(r'Event_DisplayMapMsg\(true, (\d+), (\d+), (\d+), 0, false', body).groups()
        assert int(decline) == int(accept) + 1
        assert 'CharaAnimCmd_SetState, &g_SysWork.playerWork.player, 59, false' in body
        assert 'Event_CharaAnimPlayToEnd(&g_SysWork.playerWork.player, 60)' in body
        animated_pickups.append((name, item, flag, msg, int(accept) - 1, g.value(quantity)))
    item_calls = pickup_calls + [row[:4] for row in animated_pickups]
    item_source = (DECOMP / 'src/bodyprog/items/item_unk_data.c').read_text(encoding='utf-8')
    names = re.findall(r'"(?:[^"\\]|\\.)*"|\bNULL\b', g.strip_comments(item_source.split('const char* INV_ITEM_NAMES[] = {', 1)[1].split('#else', 1)[1].split('#endif', 1)[0]))
    rotations = re.findall(r'\{\s*Q12_ANGLE\(([-\d.]+)f\),\s*Q12_ANGLE\(([-\d.]+)f\)\s*\}', item_source.split('const DVECTOR INV_ITEM_ROTATIONS[] = {', 1)[1].split('};', 1)[0])
    lines = ['/* Generated by tools/gen_school_alternative_data.py; do not edit. */', '#if defined(SH_SCHOOL_ALT_NAMES)']
    for _, item, _, _ in item_calls:
        item_id = g.value(item)
        lines.append(f'    case {item_id}: return {json.dumps(ast.literal_eval(names[item_id - 32]).replace("_", " "))};')
    lines.append('#elif defined(SH_SCHOOL_ALT_ASSETS)')
    model_source = (DECOMP / 'src/bodyprog/items/item_screens_3.c').read_text(encoding='utf-8')
    for _, item, _, _ in item_calls:
        item_id = g.value(item)
        rx, rz = rotations[item_id - 32]
        asset = re.search(r'case ' + item + r':\s*Fs_QueueStartRead\(FILE_ITEM_(\w+)_TMD,', model_source)[1]
        assert asset == f'UNQ{item_id:02X}'
        assert (ROOT / f'romfs/game/item/{asset}.TMD').read_bytes() == (ROOT / f'dump/assets/ITEM/{asset}.TMD').read_bytes()
        lines.append(f'    {{{item_id}, "romfs:/game/item/UNQ{item_id:02X}.TMD", {rx}f, {rz}f}},')
    lines += ['#else', '#pragma once', 'static const ShSchoolMessage s_school_alternative_messages[] = {']
    assert [int(index) for index, _ in literals] == list(range(len(literals)))
    for index, literal in literals:
        raw = ast.literal_eval(literal)
        text = raw.replace('~N', '\x01')
        text = re.sub(r'~[A-Z]\d*(?:\([^)]*\))?', '', text).replace('_', ' ')
        text = '\n'.join(' '.join(line.split()) for line in text.split('\x01'))
        lines.append(f'    [{index}] = {{{json.dumps(text)}, {str("~E" in raw or "~S" in raw).lower()}}},')
    lines.append('};')
    callbacks = g.event_funcs(map_name)
    lines.append('static const struct { int callback, count; } s_school_alternative_pickup_counts[] = {')
    for name, _, _, _, _, quantity in animated_pickups:
        lines.append(f'    {{{callbacks.index(name)}, {quantity}}},')
    lines.append('};')
    slot = function(g.strip_comments(source), 'MapEvent_DoorWithHorizontalSlotInteract')
    slot_messages = re.findall(r'Event_DisplayMapMsg\(false, (\d+),', slot)
    assert len(slot_messages) == 4
    slot_flags = re.findall(r'Savegame_EventFlag(?:Get|Set)\((\w+)\)', slot)
    assert len(set(slot_flags)) == 1
    slot_images = re.findall(r'Event_BgTextureCmd\(BgTextureCmd_QueueRead(?:Secondary)?, FILE_TIM_(\w+)_TIM,', slot)
    assert len(slot_images) == 2
    lines += [f'#define SH_SCHOOL_ALT_SLOT_CALLBACK {callbacks.index("MapEvent_DoorWithHorizontalSlotInteract")}',
              f'#define SH_SCHOOL_ALT_SLOT_FLAG {g.value(slot_flags[0])}']
    for label, msg in zip(('SEEN', 'NEW', 'DETAIL', 'SLOT'), slot_messages):
        lines.append(f'#define SH_SCHOOL_ALT_SLOT_{label}_MESSAGE {msg}')
    for index, image in enumerate(slot_images, 1):
        assert (ROOT / f'romfs/game/tim/{image}.TIM').is_file()
        lines.append(f'#define SH_SCHOOL_ALT_SLOT_IMAGE{index} "{image}.TIM"')
    blend = re.search(r'D_800E1FD0 \+= Q12\(([-\d.]+)f\)', slot)[1]
    lines.append(f'#define SH_SCHOOL_ALT_SLOT_BLEND_STEP {fixed(blend) / 4096:.12f}f')
    lobby = function(g.strip_comments(source), 'MapEvent_LobbyKeyUse')
    key, amount = re.search(r'Player_ItemRemove\((\w+), (\d+)\)', lobby).groups()
    lobby_msg, sound = re.search(r'Event_DisplayMapMsgWithSfx\((\d+), (\w+),', lobby).groups()
    assert amount == '1' and 'Q12(-1.2f)' in lobby
    lines += [f'#define SH_SCHOOL_ALT_LOBBY_CALLBACK {callbacks.index("MapEvent_LobbyKeyUse")}',
              f'#define SH_SCHOOL_ALT_LOBBY_ITEM {g.value(key)}',
              f'#define SH_SCHOOL_ALT_LOBBY_MESSAGE {lobby_msg}',
              f'#define SH_SCHOOL_ALT_LOBBY_SOUND {g.value(sound)}']
    utility = (DECOMP / 'src/bodyprog/events/events_util.c').read_text(encoding='utf-8').split('void Event_ItemTake', 1)[1]
    prompt_step = int(re.search(r'EventState_SelectionDialog\s*=\s*(\d+)', utility)[1])
    assert g.value('DEFAULT_PICKUP_ITEM_COUNT') == 1
    lines.append('static const ShSchoolPickup s_school_alternative_pickups[] = {')
    for name, item, flag, msg in pickup_calls:
        lines.append(f'    {{{callbacks.index(name)}, {g.value(item)}, {g.value(flag)}, {msg}, {prompt_step}}},')
    for name, item, flag, msg, prompt, _ in animated_pickups:
        lines.append(f'    {{{callbacks.index(name)}, {g.value(item)}, {g.value(flag)}, {msg}, {prompt}}},')
    lines.append('};')
    lines.append('static const ShSchoolInspection s_school_alternative_inspections[] = {')
    inspections = 0
    inspection_flags = []
    for match in re.finditer(r'void\s+(\w+)\(void\)[^{]*\{([^{}]*)\}', source):
        name, body = match.groups()
        call = re.search(r'Event_DisplayMapMsgWithBg\(FILE_TIM_(\w+)_TIM, Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\), (\d+)\)', body)
        if not call: continue
        if 'Savegame_' in body:
            flag = re.fullmatch(r'\s*Savegame_EventFlagSet\((\w+)\);\s*Event_DisplayMapMsgWithBg\([^;]+\);\s*', body)
            assert flag, name
            inspection_flags.append((callbacks.index(name), g.value(flag[1])))
        image, fade_out, fade_in, msg = call.groups()
        assert (ROOT / f'romfs/game/tim/{image}.TIM').is_file()
        lines.append(f'    {{{callbacks.index(name)}, "{image}.TIM", {fade_out}f, {fade_in}f, {msg}, -1, 128}},')
        inspections += 1
    assert inspections == 3 and len(inspection_flags) == 1
    tower = function(g.strip_comments(source), 'func_800DA8F8')
    msg = int(re.search(r'Event_DisplayMapMsg\(false, (\d+),', tower)[1])
    lines += ['};', f'#define SH_SCHOOL_ALT_TOWER_CALLBACK {callbacks.index("func_800DA8F8")}',
              f'#define SH_SCHOOL_ALT_TOWER_MESSAGE {msg}']
    lines.append('static const struct { int callback, flag; } s_school_alternative_inspection_flags[] = {')
    for callback, flag in inspection_flags:
        lines.append(f'    {{{callback}, {flag}}},')
    lines.append('};')
    config = (DECOMP / f'configs/USA/maps/{map_name}.yaml').read_text(encoding='utf-8')
    overlay = (ROOT / 'dump/assets/VIN/MAP1_S02.BIN').read_bytes()
    assert hashlib.sha1(overlay).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    vram = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / f'configs/USA/maps/sym.{map_name}.txt').read_text(encoding='utf-8')
    address = int(re.search(r'^MAP_ROOM_IDXS\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    header = (DECOMP / f'include/maps/map1/{map_name}.h').read_text(encoding='utf-8')
    lower = (DECOMP / 'include/maps/map1/map1_s00.h').read_text(encoding='utf-8')
    bounds = lambda text: dict(re.findall(r'#define (MAP_ROOM_\w+) Q12\(([^)]+)\)', text))
    assert bounds(header) == bounds(lower)
    limits = {key: float(value.rstrip('f')) for key, value in bounds(header).items()}
    terrain = (DECOMP / 'include/bodyprog/map/terrain.h').read_text(encoding='utf-8')
    chunk = float(re.search(r'#define CHUNK_SIZE\s+([-\d.]+)f', terrain)[1])
    size = int((limits['MAP_ROOM_MAX_X'] - limits['MAP_ROOM_MIN_X']) / chunk) * int((limits['MAP_ROOM_MAX_Z'] - limits['MAP_ROOM_MIN_Z']) / chunk)
    rooms = overlay[address - vram:address - vram + size]
    assert len(rooms) == size
    lines += ['static const uint8_t s_school_alternative_rooms[] = {',
              '    ' + ', '.join(map(str, rooms)), '};', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: MAP1_S02 US messages, room bounds and SHA1-verified overlay room bytes')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
