"""Extract the alternative school arrival animation from the original mapping."""
import hashlib
from pathlib import Path
import re
import struct
import sys
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/school_arrival_anim.h'


def emit():
    config = (DECOMP / 'configs/USA/maps/map1_s02.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP1_S02.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    symbols = (DECOMP / 'configs/USA/maps/sym.map1_s02.txt').read_text(encoding='utf-8')
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    address = lambda name: int(re.search(r'^' + name + r'\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    begin, end = address('g_MapHeaderTable_38'), address('LOADABLE_INVENTORY_ITEMS')
    rows = list(struct.iter_unpack('<4h', raw[begin - base:end - base]))
    shared = (DECOMP / 'include/maps/shared/sharedFunc_800CDAA8_0_s02.h').read_text(encoding='utf-8')
    info = (DECOMP / 'src/maps/map1_s02/map1_s02_anim_info.c').read_text(encoding='utf-8')
    clips = re.findall(r'\{ Anim_PlaybackOnce, ANIM_STATUS\((\d+), true\).*?\{ Q12\(([-\d.]+)f?\)\s*\}, (\d+), (\d+)\s*\}', info)
    lines = ['/* Generated by tools/gen_school_arrival_anim.py from retail MAP1_S02. */',
             'static const ShSchoolAnimation s_school_arrival_animations[] = {']
    for state in (74, 94, 95, 59, 60, 97, 98):
        code = shared.split(f'case PlayerState_Unk{state}:', 1)[1].split('break;', 1)[0]
        virtual, active = re.search(r'ANIM_STATUS\((\d+), (true|false)\)', code).groups()
        status, _, first, last = next(row for row in rows if row[1] == (int(virtual) * 2 + (active == 'true')))
        _, fps, start, stop = next(row for row in clips if int(row[0]) == ((status & 255) >> 1))
        rate = fixed(fps)
        rate = (rate + (1 << 31)) % (1 << 32) - (1 << 31)
        if rate < 0:
            assert last == int(stop)
            first, last = int(stop), int(start)
        else:
            assert (first, last) == (int(start), int(stop)), (state, status, first, last, start, stop)
        lines.append(f'    {{{state}, {first}, {last}, {rate / 4096:.12f}f}},')
    assert (ROOT / 'romfs/game/anim/HB_M1S02.ANM').read_bytes() == (ROOT / 'dump/assets/ANIM/HB_M1S02.ANM').read_bytes()
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: arrival animation mapping, clip and packaged original ANM')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
