"""Extract Old Silent Hill story data from retail C and the verified US overlay."""
import ast
import hashlib
import json
from pathlib import Path
import re
import struct
import sys

import gen_map_data as g

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "vendor/silent-hill-decomp"
OUTPUT = ROOT / "source/game/town_story_data.h"


def emit():
    config = (DECOMP / "configs/USA/maps/map2_s00.yaml").read_text(encoding="utf-8")
    overlay = (ROOT / "dump/assets/VIN/MAP2_S00.BIN").read_bytes()
    expected_hash = re.search(r'^sha1: (\w+)', config, re.M)[1]
    if hashlib.sha1(overlay).hexdigest() != expected_hash:
        raise ValueError("MAP2_S00.BIN differs from the decomp's US overlay")
    vram = int(re.search(r'    vram: (0x[0-9A-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / "configs/USA/maps/sym.map2_s00.txt").read_text(encoding="utf-8")

    def extract(symbol, fmt):
        address = int(re.search(rf'^{symbol}\s*=\s*(0x[0-9A-Fa-f]+)', symbols, re.M)[1], 16)
        return struct.unpack_from(fmt, overlay, address - vram)

    source = (DECOMP / "src/maps/map2_s00/map2_s00.c").read_text(encoding="utf-8")
    common = (DECOMP / "include/maps/shared/map_msg_common.h").read_text(encoding="utf-8")
    common = common.split("#if VERSION_REGION_IS(NTSC)", 1)[1].split("#elif", 1)[0]
    messages = re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', common + source.split("const char* MAP_MESSAGES[] = {", 1)[1].split("};", 1)[0])
    lines = ["/* Generated by tools/gen_town_story.py - do not edit. */",
             "/* Retail map2_s00.c, map0 US messages, and SHA1-verified MAP2_S00.BIN. */",
             "#if defined(SH_TOWN_STORY_MESSAGES)", "static const char *s_town_story_messages[] = {"]
    for index, literal in messages:
        raw = ast.literal_eval(literal)
        text = re.sub(r'~N', '\x01', raw)
        text = re.sub(r'~[A-Z]\d*(?:\([^)]*\))?', '', text).replace('_', ' ')
        text = '\n'.join(' '.join(line.split()) for line in text.split('\x01'))
        lines.append(f'    [{index}] = {json.dumps(text)},')
    lines += ["};", "#elif defined(SH_TOWN_STORY_ASSETS)"]
    item_source = (DECOMP / "src/bodyprog/items/item_unk_data.c").read_text(encoding="utf-8")
    rotations = re.findall(r'\{\s*Q12_ANGLE\(([-\d.]+)f\),\s*Q12_ANGLE\(([-\d.]+)f\)\s*\}', item_source.split("const DVECTOR INV_ITEM_ROTATIONS[] = {", 1)[1].split("};", 1)[0])
    item = g.value("InvItemId_KeyOfWoodman")
    rx, rz = rotations[item - 32]
    lines += [f'    {{{item}, "romfs:/game/item/UNQ{item:02X}.TMD", {float(rx):.1f}f, {float(rz):.1f}f}},',
              "#elif defined(SH_TOWN_STORY_NAMES)"]
    name_source = item_source.split("const char* INV_ITEM_NAMES[] = {", 1)[1].split("#else", 1)[1].split("#endif", 1)[0]
    names = re.findall(r'"(?:[^"\\]|\\.)*"|\bNULL\b', g.strip_comments(name_source))
    lines += [f'    case {item}: return {json.dumps(ast.literal_eval(names[item - 32]).replace("_", " "))};', "#else"]
    constants = ["InvItemId_KeyOfWoodman", "InvItemId_KeyOfLion", "InvItemId_KeyOfScarecrow",
                 "EventFlag_M2S00_PickupKeyOfWoodman", "EventFlag_M2S00_PickupKeyOfLion", "EventFlag_M2S00_PickupKeyOfScarecrow",
                 "EventFlag_MapMark_OldTown_DogYardKeyLine", "EventFlag_MapMark_55",
                 "EventFlag_M2S00_LockOfLionOpen", "EventFlag_M2S00_LockOfWoodmanOpen", "EventFlag_M2S00_LockOfScarecrowOpen",
                 "EventFlag_M2S00_DoorOfEclypseOpen", "EventFlag_MapMark_OldTown_DoghouseArrowsOnly",
                 "EventFlag_158", "EventFlag_159", "AreaTransitionFlag_SkipFadeIn"]
    for constant in constants:
        lines.append(f'#define SH_RETAIL_{constant} {g.value(constant)}')
    paths = dict((int(i), p) for i, p in re.findall(r'= (\d+), // (\S+)', (ROOT / "dump/assets/fileenum.h.inc").read_text(encoding="utf-8")))
    lines += ["static const char *s_town_lock_images[] = {"]
    for file_id in extract("g_Gfx_LockTimFileIdxs", "<8h"):
        path = paths[file_id]
        if not path.startswith("TIM/") or not (ROOT / "dump/assets" / path).is_file():
            raise ValueError(path)
        lines.append(f'    "{Path(path).name}",')
    lines += ["};"]
    anim_info = (DECOMP / "src/maps/map2_s00/map2_s00_anim_info.c").read_text(encoding="utf-8")
    rows = re.findall(r'\{ Anim_PlaybackOnce, ANIM_STATUS\((\d+), true\).*?\{ Q12\((\d+)\) \}, (\d+), (\d+) \}', anim_info)
    header = (DECOMP / "include/maps/map2/map2_s00.h").read_text(encoding="utf-8")
    mapping = list(zip(*(iter(extract("g_MapHeaderTable_38", "<160h")),) * 4))
    for state in (59, 60):
        start = int(re.search(rf'#define KEYFRAME_PlayerState_Unk{state}\s+(\d+)', header)[1])
        anim, fps, first, last = next(row for row in rows if int(row[2]) == start)
        # Shared player state 59 selects virtual anim 150 inactive; 60 selects active.
        virtual_status = (150 << 1) | (state == 60)
        status, _, _, _ = next(row for row in mapping if row[1] == virtual_status)
        # func_8007FB94 assigns this s16 into s_ModelAnim.status (u8).
        if (status & 0xff) >> 1 != int(anim):
            raise ValueError(f"Player state {state} mapping differs from clip")
        lines += [f'#define SH_TOWN_STATE_{state}_FIRST {first}',
                  f'#define SH_TOWN_STATE_{state}_LAST {last}',
                  f'#define SH_TOWN_STATE_{state}_FPS {fps}.0f']
    lines += ["#endif", ""]
    return '\n'.join(lines)


if __name__ == "__main__":
    data = emit()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="ascii") != data:
            raise SystemExit("FAIL: town story data differs from retail")
        print("PASS: town messages, flags, eight lock images, and two mapped Harry clips match retail")
    else:
        OUTPUT.write_text(data, encoding="ascii", newline="\n")
