#!/usr/bin/env python3
"""Generate common-item pickup table from a map's Event_CommonItemTake wrapper.

  gen_common_pickups.py MAP [OUT]
    e.g. gen_common_pickups.py map2_s00 source/game/map_pickups_map2_s00.h

Parses `case POINT: pickupType = CommonPickupItemId_*; eventFlagIdx = EventFlag_*;`
inside the function that calls Event_CommonItemTake (func_800E7B74 / MapEvent_CommonItemTake).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECOMP = os.path.join(ROOT, "vendor", "silent-hill-decomp")
sys.path.insert(0, os.path.join(ROOT, "tools"))
import gen_map_data as g  # noqa: E402

PICKUP = {
    "CommonPickupItemId_FirstAidKit": 0,
    "CommonPickupItemId_HealthDrink": 1,
    "CommonPickupItemId_Ampoule": 2,
    "CommonPickupItemId_HandgunBullets": 3,
    "CommonPickupItemId_RifleShells": 4,
    "CommonPickupItemId_ShotgunShells": 5,
}


def find_common_take_fn(map_name):
    """Body of the map function that ends with Event_CommonItemTake(pickupType, eventFlagIdx)."""
    d = os.path.join(DECOMP, "src", "maps", map_name)
    call = re.compile(r"Event_CommonItemTake\s*\(\s*pickupType\s*,\s*eventFlagIdx\s*\)")
    for f in os.listdir(d):
        if not f.endswith(".c"):
            continue
        path = os.path.join(d, f)
        text = open(path, encoding="utf-8", errors="replace").read()
        for cm in call.finditer(text):
            # Walk back to the enclosing `void Name(...) {`.
            head = text[: cm.start()]
            fm = None
            for m in re.finditer(r"void\s+(\w+)\s*\([^;{]*\)\s*(?://[^\n]*)?\s*\{", head):
                fm = m
            if not fm:
                continue
            body = text[fm.end() : cm.end()]
            if "pickupType" in body and "case" in body:
                return fm.group(1), body, os.path.relpath(path, ROOT)
    return None, None, None


def emit(map_name):
    name, body, src = find_common_take_fn(map_name)
    if not body:
        raise SystemExit(f"{map_name}: no Event_CommonItemTake wrapper found")
    g.enums()
    rows = []
    for pt, ptype, flag in re.findall(
        r"case\s+(\d+)\s*:\s*pickupType\s*=\s*(CommonPickupItemId_\w+)\s*;\s*"
        r"eventFlagIdx\s*=\s*(EventFlag_\w+)\s*;",
        body,
    ):
        rows.append((int(pt), PICKUP[ptype], g.value(flag), ptype, flag))
    rows.sort()
    L = [
        f"/* Generated by tools/gen_common_pickups.py {map_name} - do not edit. */",
        f"/* Source: {src} :: {name} */",
        "#pragma once",
        '#include "sh3ds/mapdata.h"',
        "",
        f"static const ShMapCommonPickup s_map_pickups_{map_name}[] = {{",
    ]
    for pt, typ, fl, ptype, flag in rows:
        L.append(f"    {{{pt}, {typ}, {fl}}}, /* {ptype} {flag} */")
    if not rows:
        L.append("    {0},")
    L += [
        "};",
        f"#define MAP_PICKUP_COUNT_{map_name.upper()} {len(rows)}",
        "",
    ]
    return "\n".join(L)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = emit(sys.argv[1])
    if len(sys.argv) > 2:
        with open(sys.argv[2], "w", encoding="ascii", newline="\n") as f:
            f.write(out)
    else:
        sys.stdout.write(out)
