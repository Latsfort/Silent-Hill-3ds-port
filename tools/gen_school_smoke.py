"""Extract acid smoke settings and a C oracle directly from retail source."""
from pathlib import Path
import re
import struct
import sys

import gen_map_data as g

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
FIELDS = dict(zip(('0', '1', '2', '3', '4', '6', '8', 'A', 'C', 'E', '10', '12', '14', '18', '1C'),
                  ('shape', 'half_size', 'disable_spawn', 'reserved', 'count', 'ceiling', 'base', 'spread', 'speed', 'fade_rate', 'phase', 'depth_bias', 'origin_x', 'origin_z', 'emission_time')))


def function(text, name):
    start = re.search(r'\b' + name + r'\([^)]*\)\s*\{', text).end()
    depth = 1
    for i in range(start, len(text)):
        depth += (text[i] == '{') - (text[i] == '}')
        if depth == 0: return text[start:i]
    raise ValueError(name)


def outputs():
    source = (DECOMP / 'src/maps/map1_s01/map1_s01.c').read_text(encoding='utf-8')
    acid = function(source, 'func_800D7308')
    assignments = re.findall(r'sharedData_800DEE50_1_s01.field_(\w+)\s*=\s*([^;]+);', acid)
    header = (DECOMP / 'include/maps/map1/map1_s01.h').read_text(encoding='utf-8')
    capacity = int(re.search(r'#define MAP_FIELD_4C_COUNT (\d+)', header)[1])
    lines = ['/* Generated by tools/gen_school_smoke.py - retail func_800D7308 case 6. */',
             'static const ShSmokeConfig s_school_acid_smoke = {']
    for field, value in assignments:
        lines.append(f'    .{FIELDS[field]} = {g.value(value)},')
    lines += ['};', '']
    effects = (DECOMP / 'src/maps/unk_draw_m1s01.c').read_text(encoding='utf-8')

    def convert(text):
        text = g.strip_comments(text)
        text = re.sub(r'sharedData_800DEE50_1_s01.field_(\w+)', lambda m: 'ref_config.' + FIELDS[m[1]], text)
        text = re.sub(r'sharedData_800DFB7C_0_s00\[([^]]+)\].(field_0.vx_0|field_4.vz_4|vy_8|field_A|field_B|field_C.field_0)',
                      lambda m: f'ref_particles[{m[1]}].' + {'field_0.vx_0': 'x', 'field_4.vz_4': 'z', 'vy_8': 'y', 'field_A': 'kind', 'field_B': 'variant', 'field_C.field_0': 'age'}[m[2]], text)
        text = text.replace('sharedData_800DFB7C_0_s00', 'ref_particles').replace('D_800C4414', 'ref_flags')
        text = text.replace('sharedFunc_800CB8A0_1_s01', 'ref_spawn').replace('Rng_Rand16', 'ref_rand16')
        text = text.replace('g_DeltaTime', 'ref_delta').replace('SquareRoot0', 'sh_fixed_sqrt0').replace('ratan2', 'sh_fixed_atan2')
        text = text.replace('Math_Cos', 'sh_fixed_cos').replace('Math_Sin', 'sh_fixed_sin')
        return text

    ref = ['/* Generated from retail smoke functions; projection is excluded from the physics oracle. */']
    rng = (DECOMP / 'src/main/rng.c').read_text(encoding='utf-8')
    for name, signature in [('Rng_Rand32', 'static uint32_t ref_rand32(void)'), ('Rng_Rand16', 'static int32_t ref_rand16(void)')]:
        code = function(rng, name).replace('g_RngSeed', 'ref_seed').replace('Rng_Rand32', 'ref_rand32')
        ref += [signature + ' {', code, '}']
    for name, signature in [('sharedFunc_800CB7F4_1_s01', 'static void ref_begin(void)'),
                            ('sharedFunc_800CB8A0_1_s01', 'static void ref_spawn(s32 idx)'),
                            ('sharedFunc_800CBA38_1_s01', 'static bool ref_delay(s32 idx)')]:
        body = convert(function(effects, name))
        body = re.sub(r's32\s+rngB;', '', body)
        ref += [signature + ' {', body, '}']
    update = function(effects, 'sharedFunc_800CBB30_1_s01')
    update = update[update.index('temp_v1_2 ='):update.index('    gte_ldv0(')]
    update = re.sub(r'setRGBC0\([^;]+;', 'ref_particles[idx].shade = var_a1;', update)
    update = re.sub(r'Math_SetSVectorFastSum\(.*?\);', '', update, flags=re.S)
    # Retail DIV does not have a zero-divisor trap here; MIPS HI retains the dividend.
    update = update.replace('(Rng_Rand16() % temp_s1)', 'ref_remainder(Rng_Rand16(), temp_s1)')
    ref += ['static bool ref_update(s32 idx) {',
            's32 temp_v1_2, temp_v0_2, temp_v0_3, temp_v0_4, temp_s1, temp_v1_3, temp_v0_5, var_a1;',
            convert(update), 'return true;', '}']
    global_source = (DECOMP / 'src/bodyprog/gfx/bodyprog_effects_8005E0DC.c').read_text(encoding='utf-8')
    global_tick = global_source.split('else if (D_800C4414 & 2)', 1)[1].split('else if (D_800C4414 & 8)', 1)[0]
    global_tick = global_tick.replace('g_MapOverlayHdr.field_7C->', 'sharedData_800DEE50_1_s01.')
    ref += ['static void ref_global_tick(void) {', convert(global_tick), '}']
    uv_lines = {name: next(line for line in effects.splitlines() if '->' + name + ' =' in line) for name in ('u0', 'u1', 'u2')}
    packed0 = int(re.search(r'\+ (0x[\da-fA-F]+);', uv_lines['u0'])[1], 16)
    packed1 = int(re.search(r'\+ (0x[\da-fA-F]+);', uv_lines['u1'])[1], 16)
    stride, top = map(int, re.search(r'field_B << (\d+)\) \+ (\d+)', uv_lines['u0']).groups())
    bottom = int(re.search(r'field_B << \d+\) \+ (\d+)', uv_lines['u2'])[1])
    width, height = (packed1 & 255) - (packed0 & 255) + 1, bottom - top + 1
    variants = int(re.search(r'field_B\s*= Rng_Rand16\(\) % (\d+)', effects)[1])
    screen = (DECOMP / 'src/bodyprog/screen/screen_data.c').read_text(encoding='utf-8')
    image_desc = list(map(int, re.findall(r'\d+', screen.split('D_800A9084', 1)[1].split(';', 1)[0])))
    page, _, _, clut_x, clut_y = image_desc[1:]
    tpage, clut = packed1 >> 16, packed0 >> 16
    assert (tpage & 15) == page and (tpage >> 5) & 3 == 1
    assert (clut & 63) * 16 == clut_x
    row = (clut >> 6) - clut_y
    raw = (ROOT / 'dump/assets/TIM/BLD.TIM').read_bytes()
    assert (ROOT / 'romfs/game/tim/BLD.TIM').read_bytes() == raw
    assert struct.unpack_from('<I', raw, 4)[0] == 8
    colors = struct.unpack_from('<H', raw, 16)[0]
    palette = struct.unpack_from(f'<{colors}H', raw, 20 + row * colors * 2)
    assert all(not color or color & 0x8000 for color in palette)
    palettes, representatives, mapping = [], [], []
    for shade in range(65):
        shaded = tuple(tuple(((color >> axis) & 31) * shade // 128 for axis in (0, 5, 10)) for color in palette)
        if shaded not in palettes:
            palettes.append(shaded)
            representatives.append(shade)
        mapping.append(palettes.index(shaded))
    atlas_width = width * 8
    atlas_height = 1 << (((len(palettes) * variants + 7) // 8 * height - 1).bit_length())
    constants = dict(TEXTURE_U=packed0 & 255, TEXTURE_V=top, TEXTURE_W=width, TEXTURE_H=height,
                     TEXTURE_STRIDE=1 << stride, TEXTURE_VARIANTS=variants, CLUT_ROW=row,
                     ATLAS_WIDTH=atlas_width, ATLAS_HEIGHT=atlas_height, ATLAS_COLUMNS=8,
                     ORDERING_TABLE_SIZE=g.value('ORDERING_TABLE_SIZE'), TIM_SIZE=len(raw))
    metadata = ['/* Generated from unk_draw_m1s01.c and BLD.TIM. */', '#pragma once']
    metadata += [f'#define SH_SMOKE_{name} {value}' for name, value in constants.items()]
    palette_data = ['/* Generated: exact 5-bit texture modulation, deduplicated by palette. */',
                    'static const uint8_t s_smoke_shade_slot[] = {' + ', '.join(map(str, mapping)) + '};',
                    'static const uint8_t s_smoke_slot_shade[] = {' + ', '.join(map(str, representatives)) + '};', '']
    return {
        ROOT / 'include/sh3ds/smoke_render_data.h': '\n'.join(metadata + ['']),
        ROOT / 'source/game/smoke_palette_data.h': '\n'.join(palette_data),
        ROOT / 'include/sh3ds/smoke_capacity.h': f'/* Generated from map1_s01.h. */\n#pragma once\n#define SH_SMOKE_CAPACITY {capacity}\n',
        ROOT / 'source/game/school_smoke_data.h': '\n'.join(lines),
        ROOT / 'tools/school_smoke_reference.h': '\n'.join(line.rstrip() for line in ref + [''])}


if __name__ == '__main__':
    for path, text in outputs().items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='ascii') == text, path
        else:
            path.write_text(text, encoding='ascii', newline='\n')
    if '--check' in sys.argv: print('PASS: smoke pool, acid settings and physics reference match retail source')
