"""Read verified valve camera tables and retain the original case-9 interpolation."""
import hashlib
from pathlib import Path
import re
import struct
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    config = (DECOMP / 'configs/USA/maps/map1_s03.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP1_S03.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / 'configs/USA/maps/sym.map1_s03.txt').read_text(encoding='utf-8')
    address = lambda name: int(re.search(r'^' + name + r'\s*=\s*(0x[\dA-Fa-f]+)', symbols, re.M)[1], 16)
    start, stop = address('MapEvent_DrainageValveInteract'), address('MapEvent_TheMonsterLurksBookRead')
    instructions = list(struct.iter_unpack('<I', raw[start - base:stop - base]))
    refs = set()
    for i, (word,) in enumerate(instructions):
        if word >> 26 != 15: continue
        register, high = (word >> 16) & 31, (word & 65535) << 16
        for (following,) in instructions[i + 1:i + 7]:
            if following >> 26 == 9 and ((following >> 21) & 31) == register:
                low = following & 65535
                refs.add((high + (low if low < 32768 else low - 65536)) & 0xFFFFFFFF)
    header = (DECOMP / 'include/maps/map1/map1_s03.h').read_text(encoding='utf-8')
    names = ('D_800E1F7C', 'D_800E1F88', 'D_800E1FC4')
    addresses = []
    for name in names:
        assert re.search(r'extern \w+\s+' + name + r'\[\];', header)
        value = int(name.split('_')[1], 16)
        assert value in refs, (name, 'not referenced by original MIPS address pair')
        addresses.append(value)
    next_address = int(re.search(r'extern u16 (D_[\dA-F]+)\[1\]', header)[1][2:], 16)
    end = addresses[1:]+[next_address]
    rows = [list(struct.iter_unpack(fmt, raw[a - base:b - base])) for a, b, fmt in zip(addresses, end, ('<H', '<3i', '<3i'))]
    assert len(rows[0]) == 6 and len(rows[1]) == len(rows[2]) == 5
    assert all(a[0] < b[0] for a, b in zip(rows[0], rows[0][1:]))
    data = ['/* Generated by tools/gen_drain_camera.py from verified MAP1_S03 tables. */']
    data += ['static const uint16_t s_drain_camera_times[] = {' + ', '.join(str(r[0]) for r in rows[0]) + '};']
    for label, values in zip(('positions', 'looks'), rows[1:]):
        data.append(f'static const ShPathPoint s_drain_camera_{label}[] = {{')
        data += ['    {' + ', '.join(map(str, row)) + '},' for row in values]
        data.append('};')
    source = g.strip_comments((DECOMP / 'src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    code = function(source, 'MapEvent_DrainageValveInteract').split('case 9:', 1)[1]
    code = code[code.index('for (i ='):code.index('Event_CameraPositionSet(&lightPos,')]
    code = re.sub(r'Savegame_EventFlagGet\(EventFlag_M1S02_UsedRubberBall\)', 'ball', code)
    code = code.replace('SysWork_StateStepIncrement(0)', 'return false')
    for old, new in [('D_800E20FA', 'ticks'), (names[0], 's_drain_camera_times'),
                     (names[1], 's_drain_camera_positions'), (names[2], 's_drain_camera_looks')]:
        code = code.replace(old, new)
    assert not re.search(r'\b(?:g_|Event_|SysWork_|Savegame_)\w*', code)
    steps = ['/* Generated from MapEvent_DrainageValveInteract case 9. */',
             'bool sh_drain_camera_sample(int32_t ticks, bool ball, ShPathPoint *position, ShPathPoint *look)', '{',
             '    int i, lightPosIdx;', '    ShPathPoint lightPos, lookAtPos;', code,
             '        *position = lightPos;', '        *look = lookAtPos;', '        return true;', '    }', '}']
    body = function(source, 'MapEvent_DrainageValveInteract')
    light = body[body.index('g_SysWork.lightRotation.vx'):body.index('g_SysWork.lightPosition.vz = lightPos.vz;') + len('g_SysWork.lightPosition.vz = lightPos.vz;')]
    light = light.replace('g_SysWork.lightBoneCoord   = NULL;', '')
    light = light.replace('g_SysWork.lightRotation.', 'light->rotation.').replace('g_SysWork.lightPosition.', 'light->position.')
    light = light.replace('ratan2', 'sh_fixed_atan2').replace('Math_Vector2MagCalcSafeQ6', 'drain_magnitude_q6').replace('MAX', 'drain_max')
    light = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f\)', lambda m: str(fixed(m[2], bool(m[1]))), light)
    assert not re.search(r'\b(?:g_|Math_|Q12_)\w*', light), light
    lights = ['/* Generated from DrainageValveInteract case 9 light attributes. */',
        'void sh_drain_camera_light(ShPathPoint lightPos, ShPathPoint lookAtPos, ShDrainLight *light)', '{', light, '}', '']
    return {'drain_camera_data.h': '\n'.join(data) + '\n',
            'drain_camera_steps.h': '\n'.join(line.rstrip() for line in steps) + '\n',
            'drain_light_steps.h': '\n'.join(line.rstrip() for line in lights)}


if __name__ == '__main__':
    for name, text in outputs().items():
        path = ROOT / 'source/game' / name
        if '--check' in sys.argv: assert path.read_text(encoding='ascii') == text
        else: path.write_text(text, encoding='ascii', newline='\n')
    if '--check' in sys.argv: print('PASS: camera tables, original MIPS references and case-9 interpolation')
