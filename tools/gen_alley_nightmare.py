"""Extract the original corpse-scene path, camera commands, text and voice chain."""
from pathlib import Path
import ast
import hashlib
import json
import re
import struct
import sys
from fractions import Fraction
import gen_map_data as g
from gen_bathroom_motion import arguments
from gen_school_smoke import function
from gen_silver_motion import fixed
from gen_phone_text import emit as text_controller

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'
OUTPUT = ROOT / 'source/game/alley_nightmare_data.h'


def number(value):
    match = re.fullmatch(r'Q12(_ANGLE)?\(([-\d.]+)f?\)', value)
    assert match, value
    return fixed(match[2], bool(match[1]))


def emit():
    source = (DECOMP / 'src/maps/map0_s00/map0_s00_2.c').read_text(encoding='utf-8')
    body = function(g.strip_comments(source), 'MapEvent_CutsceneAlleyNightmare')
    points = [arguments(x) for x in re.findall(r'Event_PathWaypointSet\(([^;]+)\);', body)]
    assert len(points) == 2 and [p[:3] for p in points] == [['true', '0', '0'], ['true', '0', '1']]
    lines = ['/* Generated by tools/gen_alley_nightmare.py; original MapEvent_CutsceneAlleyNightmare. */',
             'static const ShPathPoint s_nightmare_waypoints[] = {']
    for p in points:
        lines.append(f'    {{{number(p[4])}, 0, {number(p[5])}}},')
    lines += ['};', f'static const int16_t s_nightmare_heading = {number(points[-1][3])};']
    calls = re.findall(r'Event_Camera(Position|LookAt)Set\(([^;]+)\);', body)
    assert [kind for kind, _ in calls] == ['Position', 'LookAt', 'LookAt', 'Position', 'LookAt', 'Position', 'LookAt']
    lines += ['static const ShNightmareCameraCommand s_nightmare_camera[] = {']
    for i, (_, call) in enumerate(calls):
        args = arguments(call)
        assert len(args) == 9
        assert args[0] in ('NULL', '&playerChara.position')
        if i == 5:
            assert args[1:4] == ['camPos.vx', 'camPos.vy', 'camPos.vz']
            point = [0, 0, 0]
        else:
            point = list(map(number, args[1:4]))
        params = list(map(number, args[4:8]))
        assert args[8] in ('true', 'false', 'warpCam')
        lines.append('    {{' + ', '.join(map(str, point)) + '}, {' + ', '.join(map(str, params)) + '}},')
    warp = re.search(r'Math_Vector3Set\(&playerChara.position, ([^;]+)\);', body)[1]
    lines += ['};', 'static const ShPathPoint s_nightmare_player_warp = {' + ', '.join(map(str, map(number, arguments(warp)))) + '};']
    offset = re.search(r'Math_SetSVectorFast\(&offset, ([^;]+)\);', body)[1]
    values = list(map(int, arguments(offset)))
    assert len(values) == 3
    lines += ['static const int16_t s_nightmare_head_offset[3] = {' + ', '.join(map(str, values)) + '};',
              f'enum {{ SH_NIGHTMARE_HEAD_BONE = {g.value("HarryBone_Head")} }};']
    ntsc = source.split('const char* MAP_MESSAGES[] = {', 1)[1].split('#if VERSION_REGION_IS(NTSC)', 1)[1].split('#elif', 1)[0]
    messages = {int(i): ast.literal_eval(raw) for i, raw in re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', ntsc)}
    start = int(re.search(r'Event_DisplayMapMsgWithAudio\((\d+),', body)[1])
    selected = []
    while True:
        raw = messages[start + len(selected)]
        assert set(re.findall(r'~([A-Z])', raw)) <= set('JDNE')
        selected.append(raw)
        if '~E' in raw:
            break
    lines += ['static const ShPhonePage s_nightmare_pages[] = {']
    for i, raw in enumerate(selected):
        audio, duration = re.search(r'~J(\d)\(([-\d.]+)\)', raw).groups()
        lines.append(f'    {{{start+i}, {fixed(duration)}, {int(audio)+1}, {str("~E" in raw).lower()}, false, {json.dumps(raw)}}},')
    lines += ['};', f'enum {{ SH_NIGHTMARE_MESSAGE = {start} }};',
              'static const ShPhonePage *nightmare_page(int index)', '{',
              '    for (unsigned i = 0; i < sizeof(s_nightmare_pages) / sizeof(s_nightmare_pages[0]); i++) {',
              '        if (s_nightmare_pages[i].message == index) { return &s_nightmare_pages[i]; }',
              '    }', '    return NULL;', '}']
    config = (DECOMP / 'configs/USA/maps/map0_s00.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP0_S00.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    voice_name = re.search(r'Event_DisplayMapMsgWithAudio\(\d+, &\w+, &(D_[\dA-F]+)\)', body)[1]
    voices = struct.unpack_from('<' + str(len(selected)) + 'H', raw, int(voice_name[2:], 16) - base)
    lines += ['static const uint16_t s_nightmare_voices[] = {' + ', '.join(map(str, voices)) + '};']
    sound = arguments(re.search(r'Sd_SfxPlay\(([^;]+)\);', body)[1])
    sound_values = []
    for item in sound[1:]:
        parts = re.sub(r'[f\s]', '', re.fullmatch(r'Q8\((.+)\)', item)[1]).split('/')
        value = Fraction(parts[0])
        assert len(parts) <= 2
        if len(parts) == 2:
            value /= Fraction(parts[1])
        sound_values.append(int(value * 256))
    balance, attenuation = sound_values
    lines += [f'static const int s_nightmare_start_sound[3] = {{{g.value(sound[0])}, {balance}, {attenuation}}};']
    controller = text_controller().replace('school_timed_page', 'nightmare_page').replace('phone_text_', 'nightmare_text_')
    controller = controller.replace('int sh_nightmare_text_step(', 'static int sh_nightmare_text_step(')
    lines += [controller]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original corpse path, seven camera commands, head offset, messages and ROM voice chain')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
