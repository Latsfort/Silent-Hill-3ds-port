"""Extract the library reserve key pickup switch and original inventory asset."""
import ast
import json
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def outputs():
    source = g.strip_comments((DECOMP / 'src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    name = 'MapEvent_LibraryReserveKeyItemTake'
    code = function(source, name)
    item_name, quantity = re.search(r'InvItemCmd_AddItem, (\w+), (\d+), false', code).groups()
    item = g.value(item_name)
    flag_name = re.search(r'Savegame_EventFlagSet\((\w+)\)', code)[1]
    flag = g.value(flag_name)
    message, accept, decline = re.search(r'Event_DisplayMapMsg\(true, (\d+), (\d+), (\d+), 0, false', code).groups()
    assert (int(accept), int(decline)) == (5, 6)
    callback = g.event_funcs('map1_s03').index(name)
    items = (DECOMP / 'src/bodyprog/items/item_unk_data.c').read_text(encoding='utf-8')
    names = re.findall(r'"(?:[^"\\]|\\.)*"|\bNULL\b', g.strip_comments(items.split('const char* INV_ITEM_NAMES[] = {', 1)[1].split('#else', 1)[1].split('#endif', 1)[0]))
    rotations = re.findall(r'\{\s*Q12_ANGLE\(([-\d.]+)f\),\s*Q12_ANGLE\(([-\d.]+)f\)\s*\}', items.split('const DVECTOR INV_ITEM_ROTATIONS[] = {', 1)[1].split('};', 1)[0])
    rx, rz = rotations[item - 32]
    model_source = (DECOMP / 'src/bodyprog/items/item_screens_3.c').read_text(encoding='utf-8')
    asset = re.search(r'case ' + item_name + r':\s*Fs_QueueStartRead\(FILE_ITEM_(\w+)_TMD,', model_source)[1]
    assert (ROOT / f'romfs/game/item/{asset}.TMD').read_bytes() == (ROOT / f'dump/assets/ITEM/{asset}.TMD').read_bytes()
    data = ['/* Generated by tools/gen_roof_pickup.py from the original library reserve key. */',
        '#if defined(SH_SCHOOL_ROOF_PICKUP_NAMES)',
        f'    case {item}: return {json.dumps(ast.literal_eval(names[item - 32]).replace("_", " "))};',
        '#elif defined(SH_SCHOOL_ROOF_PICKUP_ASSETS)',
        f'    {{{item}, "romfs:/game/item/{asset}.TMD", {rx}f, {rz}f}},', '#else', '#pragma once',
        f'#define SH_SCHOOL_ROOF_KEY_PICKUP_CALLBACK {callback}',
        f'static const ShSchoolPickup s_school_roof_key_pickup = {{{callback}, {item}, {flag}, {message}, {int(accept)-1}}};', '#endif', '']
    code = code.replace('g_SysWork.sysStateSteps[0]', 'town->step')
    code = code.replace(f'Savegame_EventFlagSet({flag_name});', '')
    code = re.sub(r'if \(Gfx_PickupItemAnimate\(' + item_name + r'\)\)\s*\{\s*Event_DisplayMapMsg\([^;]+;\s*\}',
        'upper_pickup_prompt(town, save, &s_school_roof_key_pickup, input, dt, &town->step);', code)
    code = code.replace(f'Savegame_EventFlagClear({flag_name})', f'sh_save_event_clear(save, {flag})')
    code = code.replace(f'Event_InvItemCmd(InvItemCmd_QueueLoad, {item_name}, 0, false)', '(town->pickup_active = true)')
    code = code.replace(f'Event_InvItemCmd(InvItemCmd_AwaitLoad, {item_name}, 0, false)', 'step_set(town, town->step + 1)')
    code = code.replace(f'Event_InvItemCmd(InvItemCmd_AddItem, {item_name}, {quantity}, false)', f'sh_save_item_add(save, {item}, {quantity})')
    code = code.replace('Player_ControlFreeze()', '(town->controls_locked = true)')
    code = code.replace('Player_ControlUnfreeze(false)', 'ladder_unfreeze(town)').replace('SysWork_StateSetNext(SysState_Gameplay)', 'finish(town)')
    code = code.replace('SysWork_StateStepIncrement(0)', 'step_set(town, town->step + 1)').replace('Event_WaitPlayerStop()', 'step_set(town, town->step + 1)')
    code = re.sub(r'Event_CharaAnimPlayToEnd\(&g_SysWork.playerWork.player, (\d+)\)', r'card_animation(town, \1, dt)', code)
    code = code.replace('case 6:', 'case 6:\n            town->pickup_active = town->prompt_open = false;\n            town->subtitle = NULL;')
    code = re.sub(r'(step_set\(town, town->step \+ 1\);)(\s+case \d+:)', r'\1\n        /* fall through */\2', code)
    assert not re.search(r'\b(?:Event_|Player_|SysWork_|Gfx_|Savegame_|g_)\w*', code), code
    steps = ['/* Generated by tools/gen_roof_pickup.py: original pickup switch. */',
        'static void roof_library_key_pickup(ShTown *town, ShSavegame *save, const ShInputState *input, float dt)', '{',
        '    if (!town->step) {', f'        town->pickup_item_id = {item};',
        '        town->pickup_scale = town->pickup_spin = 0;',
        f'        town->pickup_msg = s_school_roof_messages[{message}].text;', '    }', code, '}', '']
    return {'school_roof_pickup_data.h': '\n'.join(data),
            'school_roof_pickup_steps.h': '\n'.join(line.rstrip() for line in steps)}


if __name__ == '__main__':
    for name, data in outputs().items():
        path = ROOT / 'source/game' / name
        if '--check' in sys.argv: assert path.read_text(encoding='ascii') == data
        else: path.write_text(data, encoding='ascii', newline='\n')
    if '--check' in sys.argv: print('PASS: library reserve key switch, item name, rotation and original TMD')
