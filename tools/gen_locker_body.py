"""Adapt the original dead-body locker event using existing school helpers."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_locker_body.h'


def adapt(code):
    code = code.replace('EventState_Flag106False', '4').replace('EventState_Flag106True', '5')
    code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f?\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
    code = re.sub(r'Savegame_EventFlagSet\((\w+)\)', lambda m: f'sh_save_event_set(save, {g.value(m[1])})', code)
    code = re.sub(r'Event_SysStateBranchOnFlag\((\w+), (\d+), (\d+), false\)',
        lambda m: f'step_set(town, sh_save_event_get(save, {g.value(m[1])}) ? {m[2]} : {m[3]})', code)
    code = code.replace('g_SysWork.sysStateSteps[0]', 'town->step')
    code = code.replace('g_SysWork.playerWork.player.position.', 'town->school.card_player.position.')
    code = code.replace('g_SysWork.playerWork.player.rotation.vy', 'town->school.card_player.rotation.vy')
    code = code.replace('ratan2(', 'sh_fixed_atan2(')
    substitutions = {
        'Player_ControlFreeze()': '(town->controls_locked = true)',
        'Player_ControlUnfreeze(false)': 'ladder_unfreeze(town)',
        'SysWork_StateStepIncrement(0)': 'step_set(town, town->step + 1)',
        'SysWork_StateSetNext(SysState_Gameplay)': 'finish(town)',
        'func_8008D438()': '(town->school.drain_flare_suppressed = true)',
        'func_8008D448()': '(town->school.drain_flare_suppressed = false)',
        'Model_AnimFlagsClear(&g_SysWork.playerWork.player.model, AnimFlag_Visible)': '(town->school.player_hidden = true)',
        'Model_AnimFlagsSet(&g_SysWork.playerWork.player.model, AnimFlag_Visible)': '(town->school.player_hidden = false)',
    }
    for old, new in substitutions.items(): code = code.replace(old, new)
    code = re.sub(r'Event_WaitTimer\((\d+), false\)', r'ladder_wait(town, dt, \1)', code)
    def camera(m):
        args = [s.strip() for s in m[2].split(',')]
        assert args[0] == 'NULL' and args[4:8] == ['0'] * 4 and args[8] == 'true'
        return f'ladder_camera(town, {str(m[1] == "LookAt").lower()}, ' + ', '.join(args[1:4]) + ');'
    code = re.sub(r'Event_Camera(Position|LookAt)Set\(([^;]+)\);', camera, code)
    def sound(m):
        position = [fixed(s.strip()) / 4096 for s in m[2].split(',')]
        position[1], position[2] = -position[1], -position[2]
        return '{ const float position[3] = {' + ', '.join(f'{v:.12f}f' for v in position) + f'}}; sh_snd_at({g.value(m[1])}, position, {fixed(m[3]) / 4096:.12f}f); }}'
    code = re.sub(r'Sfx_WithFlagsPlay\((\w+), &Q12_VECTOR3\(([^)]+)\), Q8\(([-\d.]+)f\), SfxFlag_None\);', sound, code)
    code = re.sub(r'(town->school.card_player.rotation.vy = sh_fixed_atan2\([^;]+;)', r'\1\n            card_warp(town);', code)
    code = re.sub(r'(step_set\(town, town->step \+ 1\);)(\s+case \d+:)', r'\1\n        /* fall through */\2', code)
    assert not re.search(r'\b(?:Event_|Player_|SysWork_|Model_|func_|g_|D_)\w*', code), code
    return code


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    name = 'MapEvent_LockerDeadBodyCutscene'
    body = function(source, name)
    code = adapt(body[body.index('switch ('):])
    return '\n'.join(['/* Generated by tools/gen_locker_body.py from MapEvent_LockerDeadBodyCutscene. */',
        f'#define SH_SCHOOL_LOCKER_BODY_CALLBACK {g.event_funcs("map1_s03").index(name)}',
        'static void locker_body_steps(ShTown *town, ShSavegame *save, float dt)', '{',
        '    if (!town->step) { town->school.card_player.position = town->school.player_position; }',
        code, '}', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original locker body steps, camera, yaw, sound, waits and flags')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
