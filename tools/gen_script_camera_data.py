"""Extract default scripted camera parameters from retail VC declarations."""
from pathlib import Path
import re
import sys
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/script_camera_data.h'


def emit():
    source = (ROOT / 'vendor/silent-hill-decomp/src/bodyprog/view/vc_main.c').read_text(encoding='utf-8')
    lines = ['/* Generated by tools/gen_script_camera_data.py from retail VC parameters. */',
             'static const ShVcScriptParams s_script_camera_defaults = {']
    for symbol in ('cam_mv_prm_user', 'deflt_watch_mv_prm'):
        body = source.split(symbol + ' = {', 1)[1].split('};', 1)[0]
        values = re.findall(r'Q12\(([-\d.]+)f\)', body)
        assert len(values) == 4
        lines.append('    {' + ', '.join(f'{fixed(value) / 4096:.12f}f' for value in values) + '},')
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: eight scripted camera defaults match source Q12 values')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
