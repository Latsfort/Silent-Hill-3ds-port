"""Extract original save-menu text, location names, title labels and slot limits."""
import ast
import json
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_cafe_messages import messages

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / 'vendor/silent-hill-decomp'


def strings(body):
    values = []
    for group in re.findall(r'(?:"(?:[^"\\]|\\.)*"\s*)+', body):
        raw = ''.join(ast.literal_eval(s) for s in re.findall(r'"(?:[^"\\]|\\.)*"', group))
        raw = raw.replace('_', ' ')
        values.append(' '.join(''.join(c if ord(c) >= 32 else ' ' for c in raw).split()))
    return values


def outputs():
    source = g.strip_comments((DECOMP / 'src/screens/saveload/saveload.c').read_text(encoding='utf-8'))
    title = g.strip_comments((DECOMP / 'src/bodyprog/events/title.c').read_text(encoding='utf-8'))
    locations = strings(re.search(r'g_Savegame_SaveLocationNames\[\]\s*=\s*\{(.*?)\}', source, re.S)[1])
    state = function(source, 'SaveScreen_MemCardStateDraw')
    dialogs = strings(re.search(r'DIALOG_STRS\[\]\s*=\s*\{(.*?)\}', state, re.S)[1])
    overwrite = strings(re.search(r'DIALOG_STRS\[\]\s*=\s*\{(.*?)\}', function(source, 'SaveScreen_WriteOptionsStepDraw'), re.S)[1])
    main = strings(re.search(r'MAIN_MENU_ENTRY_STRINGS\[\]\s*=\s*\{(.*?)\}', title, re.S)[1])
    assert len(dialogs) == 12 and len(main) == 5
    definitions = ['/* Generated from original memcard.h. */', '#pragma once']
    for short, original in [('CARDS', 'MEMCARD_SLOT_COUNT_MAX'), ('ENTRIES', 'SAVEGAME_COUNT_MAX')]:
        definitions.append(f'#define SH_SAVE_{short} {g.value(original)}')
    data = ['/* Generated by tools/gen_save_menu.py; US retail text. */', '#pragma once']
    for name, rows in [('s_save_locations', locations), ('s_save_dialogs', dialogs),
                       ('s_save_overwrite', overwrite), ('s_title_labels', main)]:
        data += [f'static const char *const {name}[] = {{']
        data += ['    ' + json.dumps(row, ensure_ascii=True) + ',' for row in rows]
        data += ['};']
    for name, text in [('s_save_intro', messages()[2][1]), ('s_save_yes', messages()[0][1]), ('s_save_no', messages()[1][1])]:
        data.append(f'static const char {name}[] = {json.dumps(text, ensure_ascii=True)};')
    assert 'const char* FILE_STR = "FILE"' in source
    data += ['static const char s_save_file[] = "FILE";', '']
    return {ROOT / 'include/sh3ds/save_menu_limits.h': '\n'.join(definitions) + '\n',
            ROOT / 'source/game/save_menu_data.h': '\n'.join(data)}


if __name__ == '__main__':
    for path, text in outputs().items():
        if '--check' in sys.argv:
            assert path.read_text(encoding='ascii') == text
        else:
            path.write_text(text, encoding='ascii', newline='\n')
    print('PASS: save limits, title/menu labels, locations and messages match retail')
