"""Adapt MAP1_S02's card insertion callback, retaining its original switch."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_card.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s02/map1_s02.c').read_text(encoding='utf-8'))
    code = function(source, 'func_800DB058')
    def sound(match):
        coords = [fixed(value.strip().rstrip('f')) / 4096 for value in match[2].split(',')]
        x, y, z = coords
        return f'sh_snd_at({g.value(match[1])}, (const float[3]){{{x:.12f}f, {-y:.12f}f, {-z:.12f}f}}, 0.5f);'
    code = re.sub(r'Sfx_WithFlagsPlay\((\w+), &Q12_VECTOR3\(([^)]+)\), Q8\(0.5f\), SfxFlag_None\);', sound, code)
    code = re.sub(r'Q12(_ANGLE)?\(([-\d.]+)f\)', lambda m: str(fixed(m[2], bool(m[1]))), code)
    code = re.sub(r'\bEventFlag_\w+\b', lambda m: str(g.value(m[0])), code)
    code = code.replace('g_SysWork.sysStateSteps[0]', 'town->step')
    code = code.replace('playerChara.', 'town->school.card_player.position.')
    code = code.replace('g_SysWork.playerWork.player.rotation.vy', 'town->school.card_player.rotation.vy')
    substitutions = {
        'Player_ControlFreeze()': '(town->controls_locked = true)',
        'Player_MoveSpeedClear()': '(town->school.card_player.move_speed = 0)',
        'CutsceneBorder_ForceShow()': '(town->border.state = SH_BORDER_FORCESHOW)',
        'func_8003D03C()': '(void)0', 'func_8003D01C()': '(void)0',
        'Player_EmptyWeaponHandSet()': '(town->school.empty_hand = true)',
        'Player_WeaponAttackRestore()': '(town->school.empty_hand = false)',
        'Player_ControlUnfreeze(true)': 'ladder_unfreeze(town)',
        'SysWork_StateSetNext(SysState_Gameplay)': 'finish(town)',
        'vcReturnPreAutoCamWork(true)': '(town->cam_active = town->script_use_cam = false)',
        'SysWork_StateStepIncrement(0)': 'step_set(town, town->step + 1)',
    }
    for old, new in substitutions.items(): code = code.replace(old, new)
    code = re.sub(r'(town->school.card_player.rotation.vy = -?\d+;)', r'\1\n            card_warp(town);', code)
    def camera(match):
        args = [a.strip() for a in match[2].split(',')]
        assert args[0] == 'NULL' and args[4:8] == ['0'] * 4 and args[8] == 'true'
        return f'ladder_camera(town, {str(match[1] == "LookAt").lower()}, ' + ', '.join(args[1:4]) + ');'
    code = re.sub(r'Event_Camera(Position|LookAt)Set\(([^;]+)\);', camera, code)
    code = code.replace('Event_ScreenFadeCmd(ScreenFadeCmd_Start, false, 2, 0, false)', '(town->border.state = SH_BORDER_FADEOUTSTART)')
    code = re.sub(r'Event_ScreenFadeCmd\(ScreenFadeCmd_(Start|Wait|Auto), (true|false), 0, 0, false\)',
                  lambda m: f'ladder_fade(town, {dict(Start=0, Wait=1, Auto=2)[m[1]]}, {m[2]}, 0)', code)
    code = re.sub(r'Event_WaitTimer\((\d+), false\)', r'ladder_wait(town, dt, \1)', code)
    code = re.sub(r'Event_CharaAnimPlayToEnd\(&g_SysWork.playerWork.player, (\d+)\)', r'card_animation(town, \1, dt)', code)
    code = re.sub(r'Event_DisplayMapMsg\(false, (\d+), 0, 0, 0, false\)', r'card_message(town, input, \1)', code)
    code = re.sub(r'Savegame_EventFlagSet\((\d+)\)', r'sh_save_event_set(save, \1)', code)
    code = re.sub(r'(step_set\(town, town->step \+ 1\);)(\s+case \d+:)', r'\1\n        /* fall through */\2', code)
    assert not re.search(r'\b(?:Event_|Player_|SysWork_|Sfx_|g_|func_)\w*', code), code
    lines = ['/* Generated by tools/gen_school_card.py from func_800DB058. */',
             f'#define SH_SCHOOL_ALT_CARD_CALLBACK {g.event_funcs("map1_s02").index("func_800DB058")}',
             'static void alternative_card_update(ShTown *town, ShSavegame *save, const ShInputState *input, float dt)',
             '{', code, '}']
    return '\n'.join(line.rstrip() for line in lines) + '\n'


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original card insertion switch, camera, positions, sounds and completion flag')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
