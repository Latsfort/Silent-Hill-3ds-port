"""Extract map1_s01 messages, inspections, pickups and verified retail room grid."""
import ast
import hashlib
import json
from pathlib import Path
import re
import struct
import sys

import gen_map_data as g
import gen_common_pickups as pickups
import gen_vc_roads as cameras

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "vendor/silent-hill-decomp"
OUTPUT = ROOT / "source/game/school_upper_data.h"


def emit():
    source = (DECOMP / "src/maps/map1_s01/map1_s01.c").read_text(encoding="utf-8")
    header = (DECOMP / "src/maps/map1_s01/map1_s01_header.c").read_text(encoding="utf-8")
    callbacks = re.findall(r'/\*\s*\d+\s*\*/\s*(\w+)', header.split("void (*g_MapEventFuncs[])() = {", 1)[1].split("};", 1)[0])
    items = (DECOMP / "src/bodyprog/items/item_unk_data.c").read_text(encoding="utf-8")
    names = re.findall(r'"(?:[^"\\]|\\.)*"|\bNULL\b', g.strip_comments(items.split("const char* INV_ITEM_NAMES[] = {", 1)[1].split("#else", 1)[1].split("#endif", 1)[0]))
    rotations = re.findall(r'\{\s*Q12_ANGLE\(([-\d.]+)f\),\s*Q12_ANGLE\(([-\d.]+)f\)\s*\}', items.split("const DVECTOR INV_ITEM_ROTATIONS[] = {", 1)[1].split("};", 1)[0])
    chemical, gold = g.value("InvItemId_Chemical"), g.value("InvItemId_GoldMedallion")
    lines = ["/* Generated by tools/gen_school_upper_data.py - do not edit. */", "#if defined(SH_SCHOOL_UPPER_NAMES)",
             f'    case {chemical}: return {json.dumps(ast.literal_eval(names[chemical - 32]).replace("_", " "))};',
             "#elif defined(SH_SCHOOL_UPPER_ASSETS)"]
    for item in (chemical, gold, g.value('InvItemId_SilverMedallion')):
        rx, rz = rotations[item - 32]
        if not (ROOT / f"dump/assets/ITEM/UNQ{item:02X}.TMD").is_file():
            raise ValueError("Missing retail pickup model")
        lines.append(f'    {{{item}, "romfs:/game/item/UNQ{item:02X}.TMD", {rx}f, {rz}f}},')
    common = (DECOMP / "include/maps/shared/map_msg_common.h").read_text(encoding="utf-8")
    common = common.split("#if VERSION_REGION_IS(NTSC)", 1)[1].split("#elif", 1)[0]
    messages = re.findall(r'/\*\s*(\d+)\s*\*/\s*("(?:[^"\\]|\\.)*")', common + source.split("const char* MAP_MESSAGES[] = {", 1)[1].split("};", 1)[0])
    acid = next(e for e in g.load_events('map1_s01') if e['func'] == 'func_800D7308')
    assert acid['required_item'] == chemical
    lines += ["#elif defined(SH_SCHOOL_UPPER_ITEM_USE)", f'    case {chemical}: return true;',
              "#else", "#pragma once", "static const ShSchoolMessage s_school_upper_messages[] = {"]
    for index, literal in messages:
        raw = ast.literal_eval(literal)
        text = re.sub('~N', '\x01', raw)
        text = re.sub(r'~[A-Z]\d*(?:\([^)]*\))?', '', text).replace('_', ' ')
        text = '\n'.join(' '.join(line.split()) for line in text.split('\x01'))
        lines.append(f'    [{index}] = {{{json.dumps(text)}, {str("~E" in raw or "~S" in raw).lower()}}},')
    lines += ["};", "static const ShSchoolInspection s_school_upper_inspections[] = {"]
    for match in re.finditer(r'void\s+(\w+)\(void\)[^{]*\{([^{}]*)\}', source):
        name, body = match.groups()
        call = re.search(r'Event_DisplayMapMsgWith(Bg|DimmedBg)\(FILE_TIM_(\w+)_TIM,\s*Q12\(([-\d.]+)f\),\s*Q12\(([-\d.]+)f\),\s*(\d+)(?:,\s*(\d+))?\)', body)
        if call:
            _, image, fade0, fade1, msg, dim = call.groups()
            lines.append(f'    {{{callbacks.index(name)}, "{image}.TIM", {fade0}f, {fade1}f, {msg}, {dim or -1}, 128}},')
    lines += ["};", "static const ShSchoolPickup s_school_upper_pickups[] = {"]
    body = source.split("void MapEvent_ChemicalItemTake(void)", 1)[1].split("\n}\n", 1)[0]
    item, count, flag, msg = re.search(r'Event_ItemTake\((\w+), (\w+), (\w+), (\d+)\)', body).groups()
    utility = (DECOMP / "src/bodyprog/events/events_util.c").read_text(encoding="utf-8").split("void Event_ItemTake", 1)[1]
    shared_prompt = int(re.search(r'EventState_SelectionDialog\s*=\s*(\d+)', utility)[1])
    assert g.value(count) == 1
    lines.append(f'    {{{callbacks.index("MapEvent_ChemicalItemTake")}, {g.value(item)}, {g.value(flag)}, {msg}, {shared_prompt}}},')
    body = source.split("void MapEvent_GoldMedallionItemPickup(void)", 1)[1].split("\n}\n", 1)[0]
    flag = re.search(r'Savegame_EventFlagSet\((\w+)\)', body)[1]
    msg = re.search(r'Event_DisplayMapMsg\(true, (\d+),', body)[1]
    prompt = int(re.search(r'EventState_PickUpMedallion\s*=\s*(\d+)', body)[1]) - 1
    lines += [f'    {{{callbacks.index("MapEvent_GoldMedallionItemPickup")}, {gold}, {g.value(flag)}, {msg}, {prompt}}},']
    body = source.split('void func_800D857C(void)', 1)[1].split('\n}\n', 1)[0]
    flag = re.search(r'Savegame_EventFlagSet\((\w+)\)', body)[1]
    msg, accept, decline = map(int, re.search(r'Event_DisplayMapMsg\(true, (\d+), (\d+), (\d+),', body).groups())
    item = re.search(r'InvItemCmd_AddItem, (\w+), 1', body)[1]
    assert accept == 6 and decline == 7
    lines += [f'    {{{callbacks.index("func_800D857C")}, {g.value(item)}, {g.value(flag)}, {msg}, {accept - 1}}},', '};']
    config = (DECOMP / "configs/USA/maps/map1_s01.yaml").read_text(encoding="utf-8")
    overlay = (ROOT / "dump/assets/VIN/MAP1_S01.BIN").read_bytes()
    assert hashlib.sha1(overlay).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    vram = int(re.search(r'    vram: (0x[0-9A-Fa-f]+)', config)[1], 16)
    symbols = (DECOMP / "configs/USA/maps/sym.map1_s01.txt").read_text(encoding="utf-8")
    address = int(re.search(r'^MAP_ROOM_IDXS\s*=\s*(0x[0-9A-Fa-f]+)', symbols, re.M)[1], 16)
    lower = (DECOMP / "include/maps/map1/map1_s00.h").read_text(encoding="utf-8")
    upper = (DECOMP / "include/maps/map1/map1_s01.h").read_text(encoding="utf-8")
    bounds = lambda s: dict(re.findall(r'#define (MAP_ROOM_\w+) Q12\(([^)]+)\)', s))
    assert bounds(lower) == bounds(upper)
    limits = {key: float(value.rstrip('f')) for key, value in bounds(upper).items()}
    terrain = (DECOMP / "include/bodyprog/map/terrain.h").read_text(encoding="utf-8")
    chunk = float(re.search(r'#define CHUNK_SIZE\s+([-\d.]+)f', terrain)[1])
    size = int((limits['MAP_ROOM_MAX_X'] - limits['MAP_ROOM_MIN_X']) / chunk) * int((limits['MAP_ROOM_MAX_Z'] - limits['MAP_ROOM_MIN_Z']) / chunk)
    rooms = overlay[address - vram:address - vram + size]
    assert len(rooms) == size
    lines += ["static const uint8_t s_school_upper_rooms[] = {", "    " + ', '.join(map(str, rooms)), "};"]
    hand = re.search(r'Math_Vector3Set\(&D_800DF080, (.+)\);', source)[1]
    hand_pos = [float(v) for v in re.findall(r'Q12\(([-\d.]+)f\)', hand)]
    assert len(hand_pos) == 3
    lines.append("static const ShSchoolProp s_school_upper_props[] = {")
    for index, symbol in enumerate(("HandHid", "Hand2Hi", "PanelgH", "AcidHid")):
        if index < 3:
            model = re.search(r'WorldObject_ModelNameSet\(&g_WorldObject_' + symbol + r', "(\w+)"\)', source)[1]
            pos = hand_pos
        else:
            model, coords = re.search(r'WorldObject_PosePositionInit\(&g_WorldObject_' + symbol + r', "(\w+)", ([^)]+)\)', source).groups()
            pos = [float(v.rstrip('f')) for v in coords.split(', ')]
        values = ', '.join(f'{int(v * 4096) / 4096:.8f}f' for v in pos)
        lines.append(f'    {{"{model}", {{{values}}}, {{0.0f, 0.0f, 0.0f}}, {1 << index}u}},')
    def fixed_float(value):
        return struct.unpack('<f', struct.pack('<f', float(value.rstrip('f'))))[0]

    for index, symbol in enumerate(('Futa1Hi', 'Futa2Hi'), 4):
        model, coords = re.search(r'WorldObject_PosePositionInit\(&g_WorldObject_' + symbol + r', "(\w+)", ([^)]+)\)', source).groups()
        values = ', '.join(f'{int(fixed_float(v) * 4096) / 4096:.8f}f' for v in coords.split(', '))
        lines.append(f'    {{"{model}", {{{values}}}, {{0.0f, 0.0f, 0.0f}}, {1 << index}u}},')
    silver_poses = re.findall(r'WorldObject_Init\(&g_WorldObject_SilverH, "(\w+)", ([^)]+)\)', source)
    assert len(silver_poses) == 2
    for index, (model, coords) in enumerate(silver_poses, 6):
        values = [fixed_float(v) for v in coords.split(', ')]
        assert len(values) == 6
        position = ', '.join(f'{int(v * 4096) / 4096:.8f}f' for v in values[:3])
        angles = ', '.join(f'{int(v * 4096 / 360) * 360 / 4096:.8f}f' for v in values[3:])
        lines.append(f'    {{"{model}", {{{position}}}, {{{angles}}}, {1 << index}u}},')
    lines += ["};"]
    shared = (DECOMP / "include/maps/shared/sharedFunc_800CDAA8_0_s02.h").read_text(encoding="utf-8")
    address = int(re.search(r'^g_MapHeaderTable_38\s*=\s*(0x[0-9A-Fa-f]+)', symbols, re.M)[1], 16)
    mapping = list(struct.iter_unpack('<4h', overlay[address - vram:address - vram + 320]))
    animation_source = (DECOMP / "src/maps/map1_s01/map1_s01_anim_info.c").read_text(encoding="utf-8")
    clips = re.findall(r'\{ Anim_PlaybackOnce, ANIM_STATUS\((\d+), true\).*?\{ Q12\((\d+)\) \}, (\d+), (\d+) \}', animation_source)
    lines.append("static const ShSchoolAnimation s_school_upper_animations[] = {")
    for state in (59, 60, 83):
        state_code = shared.split(f'case PlayerState_Unk{state}:', 1)[1].split('break;', 1)[0]
        virtual, active = re.search(r'ANIM_STATUS\((\d+), (true|false)\)', state_code).groups()
        virtual_status = (int(virtual) << 1) | (active == 'true')
        status, _, first, last = next(row for row in mapping if row[1] == virtual_status)
        clip, fps, clip_first, clip_last = next(row for row in clips if int(row[0]) == ((status & 255) >> 1))
        assert (first, last) == (int(clip_first), int(clip_last))
        if state in (59, 60):
            assert first == int(re.search(rf'#define KEYFRAME_PlayerState_Unk{state}\s+(\d+)', upper)[1])
        lines.append(f'    {{{state}, {first}, {last}, {fps}.0f}},')
    lines += ["};", "#endif", ""]
    return '\n'.join(lines)


if __name__ == "__main__":
    data = emit()
    if "--check" in sys.argv:
        assert OUTPUT.read_text(encoding="ascii") == data
        assert (ROOT / "source/game/mapdata_map1_s01.h").read_text(encoding="ascii") == g.emit("map1_s01")
        assert (ROOT / "source/game/map_pickups_map1_s01.h").read_text(encoding="ascii") == pickups.emit("map1_s01")
        roads = [r for r in cameras.parse((DECOMP / "src/maps/map1_s01/vc_road_data.h").read_text(encoding="utf-8")) if not r['flags'] & 1]
        rows = re.findall(r'^    \{\{(.+)\},$', (ROOT / "source/game/vc_roads_map1_s01.h").read_text(encoding="ascii"), re.M)
        assert len(rows) == len(roads)
        for text, road in zip(rows, roads):
            values = [int(v, 16) if v.startswith('0x') else float(v) for v in re.findall(r'0x[\dA-F]+|[-\d.]+', text)]
            expected = road['sw'] + road['rd'] + [road[k] for k in ('flags', 'area', 'rd_type', 'mv_y', 'max_hy', 'min_hy', 'ofs_watch_hy', 'cam_mv', 'fix_x', 'fix_y')]
            assert values == [round(v, 3) for v in expected]
        print("PASS: upper school messages, inspections, pickup assets/flags and room grid match retail")
        print(f"PASS: {len(g.load_points('map1_s01'))} points, {len(g.load_events('map1_s01'))} events and {len(roads)} camera roads match retail")
    else:
        OUTPUT.write_text(data, encoding="ascii", newline="\n")
