"""Generate overlay -> retail MAP_INFOS bindings, checking every source row."""
from pathlib import Path
import re
import sys

import gen_map_data as g

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "vendor/silent-hill-decomp"
OUTPUT = ROOT / "source/game/overlay_data.h"


def emit():
    source = (DECOMP / "src/bodyprog/sys/map_info.c").read_text(encoding="utf-8")
    body = source.split("const s_MapInfo MAP_INFOS[MapType_Count] = {", 1)[1].split("};", 1)[0]
    infos = re.findall(r'\{\s*\w+,\s*"(\w+)",\s*([^,]+),', g.strip_comments(body))
    if len(infos) != g.value("MapType_Count"):
        raise ValueError("MAP_INFOS row count differs from MapType_Count")
    effects = (DECOMP / "src/bodyprog/world/world_effects.c").read_text(encoding="utf-8")
    presets = {name: (int(a), int(b)) for name, a, b in re.findall(r'static s_MapEnvPresetIdxs (\w+) = \{\s*(\d+),\s*(\d+)\s*\}', effects)}
    preset_switch = effects.split("switch (mapHdr->field_16)", 1)[1].split("Gfx_MapEnvSet", 1)[0]
    preset_cases = {label: re.findall(r'presetIdxPtr = &(\w+)', body) for label, body in
                    re.findall(r'(?:case (\d+)|default)(?:\s*):([^:]+?)(?=\bcase\b|\bdefault\b|$)', preset_switch, re.S)}
    audio = (DECOMP / "src/bodyprog/game_boot/background_sound_init.c").read_text(encoding="utf-8")
    ambient_tasks = [int(value.strip()) for value in audio.split('static u16 g_AmbientVabTaskLoad[40] = {', 1)[1].split('};', 1)[0].split(',') if value.strip()]
    if len(ambient_tasks) != 40:
        raise ValueError("ambient task table count differs from retail")
    rows = []
    for header in sorted((DECOMP / "src/maps").glob("map[0-7]_s??/*_header.c")):
        name = header.parent.name
        text = header.read_text(encoding="utf-8")
        binding = re.search(r'\.mapInfo\s*=\s*&MAP_INFOS\[(\w+)\]', text)
        if not binding:
            raise ValueError(f"{name}: missing mapInfo")
        area, flags = infos[g.value(binding[1])]
        idx = g.value("MapIdx_" + name.upper())
        if not any((ROOT / "romfs/game/bg").glob(area + "????.IPD")):
            raise ValueError(f"{name}: no {area} geometry assets")
        flags = g.value(flags)
        selector = re.search(r'\.field_16\s*=\s*(\d+)', text)[1]
        candidates = preset_cases.get(selector, preset_cases[""])
        active = bool(flags & g.value("MapFlag_Interior") and flags & (g.value("MapFlag_OneActiveChunk") | g.value("MapFlag_TwoActiveChunks")))
        binding = candidates[0 if active or len(candidates) == 1 else 1]
        ambient = int(re.search(r'\.ambientAudioIdx\s*=\s*(\d+)', text)[1])
        rows.append((idx, name, area, flags, presets[binding], ambient_tasks[ambient]))
    rows.sort()
    if [row[0] for row in rows] != list(range(g.value("MapIdx_MAP7_S03") + 1)):
        raise ValueError("overlay coverage is not contiguous")
    lines = ["/* Generated by tools/gen_overlay_data.py - do not edit. */", "#pragma once",
             "typedef struct ShOverlayInfo {", "    const char *area;", "    unsigned flags;", "    unsigned presets[2];", "    unsigned ambient_task;",
             "} ShOverlayInfo;", "static const ShOverlayInfo s_overlay_info[] = {"]
    for idx, name, area, flags, presets, ambient_task in rows:
        lines.append(f'    [{idx}] = {{"{area}", {flags}, {{{presets[0]}, {presets[1]}}}, {ambient_task}}}, /* {name} */')
    lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    data = emit()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="ascii") != data:
            raise SystemExit("FAIL: overlay bindings differ from retail")
        print("PASS: all 43 overlay area names and flags match retail; geometry assets present")
    else:
        OUTPUT.write_text(data, encoding="ascii", newline="\n")
