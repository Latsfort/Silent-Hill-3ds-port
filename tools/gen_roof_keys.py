"""Extract the original upper alternative-school key-use callbacks."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_roof_keys.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    lines = ['/* Generated by tools/gen_roof_keys.py from MAP1_S03. */',
        'typedef struct ShSchoolRoofKey { int callback, item, message, sound, flag; } ShSchoolRoofKey;',
        'static const ShSchoolRoofKey s_school_roof_keys[] = {']
    for name in ('MapEvent_LibraryReserveKeyUse', 'MapEvent_ClassroomKeyUse'):
        code = function(source, name)
        item, quantity = re.search(r'Player_ItemRemove\((\w+), (\d+)\)', code).groups()
        assert quantity == '1'
        message, sound = re.search(r'Event_DisplayMapMsgWithSfx\((\d+), (\w+), &sfxPos\)', code).groups()
        flag = re.search(r'Savegame_EventFlagSet\((\w+)\)', code)
        assert 'Q12(-1.2f)' in code and 'MAP_POINTS[g_MapEventData->mapPointIdx].positionX' in code
        lines.append(f'    {{{g.event_funcs("map1_s03").index(name)}, {g.value(item)}, {message}, {g.value(sound)}, {g.value(flag[1]) if flag else 0}}},')
    lines += ['};', 'static const ShSchoolRoofKey *roof_key_use(int callback)', '{',
        '    for (unsigned i = 0; i < sizeof(s_school_roof_keys) / sizeof(s_school_roof_keys[0]); i++) {',
        '        if (s_school_roof_keys[i].callback == callback) { return &s_school_roof_keys[i]; }',
        '    }', '    return NULL;', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original library/classroom key callbacks, item removal, messages, sounds and flag')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
