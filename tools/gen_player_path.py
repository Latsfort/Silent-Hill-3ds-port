"""Adapt the original player waypoint state machine without rewriting its cases."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/player_path_steps.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/characters/player.c').read_text(encoding='utf-8'))
    code = function(source, 'Player_PathWaypointExecute')
    code = re.sub(r'#if[^\n]*(?:\\\n[^\n]*)*\n', '', code)
    code = code.replace('#endif', '')
    code = code[code.index('    angle       ='):]
    code = re.sub(r'Q12_ANGLE\(([-\d.]+)f?\)', lambda m: str(fixed(m[1], True)), code)
    code = re.sub(r'Q12\(([-\d.]+)f?\)', lambda m: str(fixed(m[1])), code)
    code = code.replace('Q8(0.15f)', str(int(0.15 * 256)))
    code = re.sub(r'\b(PlayerState_\w+|PlayerCutsceneState_\w+)\b', lambda m: str(g.value(m[0])), code)
    code = re.sub(r'\bplayerExtra = [^;]+;\s*', '', code)
    code = re.sub(r'\bplayerChara = [^;]+;\s*', '', code)
    replacements = {
        'g_Player_FlexRotationY': 'path->flex_y', 'D_800C4588': 'path->step',
        'sharedData_800DD5A4_0_s00': 'path->waypoint',
        'sharedData_800E39E0_0_s00': 'path->target_angle',
        'sharedData_800E39E2_0_s00': 'path->next_angle',
        'sharedData_800DD5A0_0_s00': 'path->previous_distance',
        'g_Player_CutsceneState': 'player->cutscene_state',
        'g_Player_AnimResetRequest': 'player->animation_reset',
        'g_SysWork.playerWork.player.properties.player.moveSpeed': 'player->move_speed',
        'playerChara->': 'player->', 'g_DeltaTime': 'dt',
        'ANGLE_THRESHOLD': '(4096 >> 6)', 'Q12_ANGLE_ABS': 'path_angle',
        'Math_ShortestAngleGet': 'path_shortest', 'ratan2': 'sh_fixed_atan2',
        'SquareRoot0': 'sh_fixed_sqrt0', 'Q12_2D_DISTANCE_SQR': 'PATH_DISTANCE_SQR',
        'Q12_TO_Q8': 'PATH_TO_Q8', 'TIMESTEP_SCALE_30_FPS': 'PATH_TIMESTEP',
        'ABS': 'abs', 'CLAMP': 'sh_q12_clamp',
    }
    for old, new in replacements.items():
        code = code.replace(old, new)
    code = re.sub(r'Player_ExtraStateSet\(playerChara, playerExtra, ([^)]+)\)', r'sh_path_state_set(player, \1)', code)
    assert not re.search(r'\b(?:g_|sharedData_|Player_|Math_)\w+', code), code
    # Retail reads the next distance before checking completion. Keep the resulting
    # distance unused at completion, but avoid reading beyond a caller's array.
    code = code.replace('playerVecDist = sh_fixed_sqrt0(PATH_DISTANCE_SQR(localVec[path->waypoint], player->position));\n\n                if',
                        'playerVecDist = path->waypoint < vecCount ? sh_fixed_sqrt0(PATH_DISTANCE_SQR(localVec[path->waypoint], player->position)) : 0;\n\n                if')
    lines = ['/* Generated by tools/gen_player_path.py from Player_PathWaypointExecute. */',
             'bool sh_path_player_step(ShPath *path, ShPathPlayer *player, int playerExtraState,',
             '                         ShPathPoint *vec, int16_t angle, int vecCount, int32_t dt)', '{',
             '    ShPathPoint *localVec;', '    int32_t playerVecDist, angleStep;',
             '    int16_t playerRotDelta;', code, '}']
    return '\n'.join(line.rstrip() for line in lines) + '\n'


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original player waypoint steps and expressions retained')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
