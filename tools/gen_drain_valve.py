"""Retain the original hand-driven valve rotation and sound branches."""
from pathlib import Path
import re
import sys
import hashlib
import struct
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/drain_valve_steps.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    body = function(source, 'MapEvent_DrainageValveInteract')
    code = body[body.index('if (var_v0 >= 6'):body.index('D_800E20F8 = temp_s2;') + len('D_800E20F8 = temp_s2;')]
    code = re.sub(r'Sfx_WithFlagsPlay\(Sfx_Unk1463, &D_800CBAA4, Q8\(0.5f\), SfxFlag_None\)',
                  'sounds |= SH_DRAIN_VALVE_SQUEAK', code)
    code = re.sub(r'Sfx_WithFlagsPlay\(Sfx_Unk1462, &D_800CBAA4, Q8\(0.5f\), SfxFlag_None\)',
                  'sounds |= SH_DRAIN_VALVE_CLICK', code)
    code = code.replace('Sd_SfxStop(Sfx_Unk1465)', 'sounds |= SH_DRAIN_WATER_STOP')
    code = code.replace('SD_Call(Sfx_Unk1465)', 'sounds |= SH_DRAIN_WATER_START')
    for old, new in [('var_v0', 'relative_frame'), ('temp_s2', 'hand_angle'),
                     ('g_SysWork.sysStateSteps[0]', 'step'), ('g_WorldObject5.rotation.vx', 'valve->rotation'),
                     ('D_800E20F8', 'valve->previous_angle'), ('D_800E2101', 'valve->sound_phase'),
                     ('D_800E2100', 'valve->running'), ('D_800E20FC', 'valve->opening'),
                     ('Math_AngleNormalizeSigned', 'valve_angle_signed')]:
        code = code.replace(old, new)
    code = re.sub(r'Q12_ANGLE\(([-\d.]+)f\)', lambda m: str(fixed(m[1], True)), code)
    assert not re.search(r'\b(?:g_|D_|Sfx_|Sd_|SD_|Q12_)\w*', code)
    decomp = ROOT / 'vendor/silent-hill-decomp'
    config = (decomp / 'configs/USA/maps/map1_s03.yaml').read_text(encoding='utf-8')
    raw = (ROOT / 'dump/assets/VIN/MAP1_S03.BIN').read_bytes()
    assert hashlib.sha1(raw).hexdigest() == re.search(r'^sha1: (\w+)', config, re.M)[1]
    base = int(re.search(r'    vram: (0x[\dA-Fa-f]+)', config)[1], 16)
    point_name = re.search(r'gte_ldv0\(&(D_[\dA-F]+)\)', body)[1]
    header = (decomp / 'include/maps/map1/map1_s03.h').read_text(encoding='utf-8')
    assert f'extern SVECTOR {point_name};' in header
    point_address = int(point_name[2:], 16)
    values = struct.unpack_from('<4h', raw, point_address - base)
    assert values[3] == 0
    harry = (decomp / 'include/maps/characters/harry.h').read_text(encoding='utf-8')
    bone_name = re.search(r'playerBoneCoords\[(\w+)\]', body)[1]
    bone = int(re.search(r'\b' + bone_name + r'\s*=\s*(\d+)', harry)[1])
    angle = re.search(r'temp_s2 = ratan2\(\(sp78.vy \* 16\) \+ Q12\(([-\d.]+)f\), \(sp78.vz \* 16\) \+ Q12\(([-\d.]+)f\)\)', body)
    assert angle
    prefix = ['/* Generated by tools/gen_drain_valve.py from DrainageValveInteract. */',
        'static const int16_t s_drain_hand_local[] = {' + ', '.join(map(str, values[:3])) + '};',
        f'unsigned sh_drain_valve_hand_bone(void) {{ return {bone}; }}',
        'void sh_drain_valve_hand_local(int16_t point[3])', '{',
        '    for (int axis = 0; axis < 3; axis++) { point[axis] = s_drain_hand_local[axis]; }', '}',
        'int sh_drain_valve_hand_angle(const ShCharaBone *world_bone)', '{',
        '    int32_t point[3];',
        '    for (int axis = 0; axis < 3; axis++) {',
        '        int64_t sum = 0;',
        '        for (int column = 0; column < 3; column++) {',
        '            sum += (int64_t)world_bone->rotation[axis][column] * s_drain_hand_local[column];',
        '        }',
        '        point[axis] = (int32_t)(sum >> 12) + world_bone->translation[axis];',
        '    }',
        f'    return sh_fixed_atan2(point[1] * 16 + {fixed(angle[1])}, point[2] * 16 + {fixed(angle[2])});',
        '}', '']
    volume = body[body.index('if (temp_v1_9 < Q12(1.0f))'):body.index('Sd_SfxAttributesUpdate(Sfx_Unk1465')]
    volume = volume.replace('temp_v1_9', 'distance').replace('D_800E20FC', 'opening')
    volume = re.sub(r'Q12\(([-\d.]+)f\)', lambda m: str(fixed(m[1])), volume)
    volume = volume.replace('Q12_MULT_PRECISE', 'sh_q12_mul').replace('Q12_DIV', 'valve_q12_div')
    assert not re.search(r'\b(?:g_|D_|Q12_)\w*', volume)
    suffix = ['uint8_t sh_drain_water_attenuation(int32_t distance, int opening)', '{',
              '    int vol;', volume, '    return (uint8_t)vol;', '}', '']
    distance = re.search(r'temp_v1_9 = Math_Vector3MagCalcSafe\(([^;]+)\);', body)[1]
    distance = distance.replace('g_SysWork.playerWork.player.position.', 'player.').replace('sp48.', 'camera.')
    distance = re.sub(r'Q12\(([-\d.]+)f\)', lambda m: str(fixed(m[1])), distance)
    assert not re.search(r'\b(?:g_|Q12_)\w*', distance)
    suffix += ['int32_t sh_drain_water_distance(ShPathPoint player, ShPathPoint camera)', '{',
               f'    return drain_magnitude3_q6({distance});', '}', '']
    return '\n'.join(prefix + [
        'unsigned sh_drain_valve_hand(ShDrainValve *valve, int step, int hand_angle, int relative_frame)',
        '{', '    unsigned sounds = 0;', '    if (step != 7 && step != 12) { return 0; }', code,
        '    return sounds;', '}', ''] + suffix)


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: original valve hand rotation, sound phases and opening clamp')
    else:
        OUTPUT.write_text(data, encoding='ascii', newline='\n')
