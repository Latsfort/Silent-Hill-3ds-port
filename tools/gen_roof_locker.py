"""Extract the original opened-locker inspection for the upper school."""
from pathlib import Path
import re
import sys
import gen_map_data as g
from gen_school_smoke import function
from gen_silver_motion import fixed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/game/school_roof_locker.h'


def emit():
    source = g.strip_comments((ROOT / 'vendor/silent-hill-decomp/src/maps/map1_s03/map1_s03.c').read_text(encoding='utf-8'))
    name = 'MapEvent_OpenedCatLockerInspect'
    body = function(source, name)
    image, fade_out, fade_in, message = re.search(r'Event_DisplayMapMsgWithBg\(FILE_TIM_(\w+)_TIM, Q12\(([-\d.]+)f\), Q12\(([-\d.]+)f\), (\d+)\)', body).groups()
    assert (ROOT / f'romfs/game/tim/{image}.TIM').read_bytes() == (ROOT / f'dump/assets/TIM/{image}.TIM').read_bytes()
    return '\n'.join(['/* Generated by tools/gen_roof_locker.py from OpenedCatLockerInspect. */',
        f'static const ShSchoolInspection s_school_roof_locker = {{{g.event_funcs("map1_s03").index(name)}, "{image}.TIM", {fixed(fade_out)/4096:.12f}f, {fixed(fade_in)/4096:.12f}f, {message}, -1, 128}};', ''])


if __name__ == '__main__':
    data = emit()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='ascii') == data
        print('PASS: opened locker callback, exact background asset, fade rates and message')
    else: OUTPUT.write_text(data, encoding='ascii', newline='\n')
