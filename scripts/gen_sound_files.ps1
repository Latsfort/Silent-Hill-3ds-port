# Generates source/sound/sd_files.h: g_AudioData index -> extracted file path (by CD sector).
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$decomp = Join-Path $root 'vendor\silent-hill-decomp'

$lbaToName = @{}
foreach ($line in Get-Content (Join-Path $decomp 'src\main\filetable.c.USA.inc')) {
    if ($line -match '\{\s*0x([0-9a-fA-F]+),.*//\s*(\S+)') {
        $lbaToName[[Convert]::ToInt32($Matches[1], 16)] = $Matches[2]
    }
}

$entries = @()
$inTable = $false
foreach ($line in Get-Content (Join-Path $decomp 'src\bodyprog\sound\sound_data.c')) {
    if ($line -match 'g_AudioData\[') { $inTable = $true; continue }
    if ($inTable -and $line -match '^\};') { break }
    if ($inTable -and $line -match '\{\s*(\w+),\s*0,\s*(\d+),\s*(\d+),\s*(\d+)\s*\}') {
        $lba = [int]$Matches[4]
        $name = if ($lba -ne 0 -and $lbaToName.ContainsKey($lba)) { $lbaToName[$lba] } else { '' }
        $entries += [pscustomobject]@{ Type = $Matches[1]; Off = $Matches[2]; Size = $Matches[3]; Name = $name }
    }
}

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('/* Generated by scripts/gen_sound_files.ps1 from sound_data.c + filetable.c.USA.inc. */')
[void]$out.AppendLine('#pragma once')
[void]$out.AppendLine('')
[void]$out.AppendLine('#include "sd_types.h"')
[void]$out.AppendLine('')
[void]$out.AppendLine('static const SdAudioFile g_SdAudioFiles[] = {')
for ($i = 0; $i -lt $entries.Count; $i++) {
    $e = $entries[$i]
    $type = switch ($e.Type) { 'AudioType_BaseAudio' { 0 } 'AudioType_MusicSheet' { 0 } 'AudioType_Weapon' { 1 } 'AudioType_Ambient' { 2 } 'AudioType_MusicKeys' { 3 } default { 0 } }
    [void]$out.AppendLine(("    /* {0,3} */ {{ {1}, {2,5}, {3,6}, ""{4}"" }}," -f $i, $type, $e.Off, $e.Size, $e.Name))
}
[void]$out.AppendLine('};')
$dest = Join-Path $root 'source\sound\sd_files.h'
New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
[IO.File]::WriteAllText($dest, $out.ToString())
Write-Host "wrote $dest ($($entries.Count) entries)"
